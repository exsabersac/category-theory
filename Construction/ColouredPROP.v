(** * Coloured PROPs / * 彩色道具 *)

(*
 nLab:      https://ncatlab.org/nlab/show/PROP
 Wikipedia: https://en.wikipedia.org/wiki/PROP_(category_theory)

 nLab defines the coloured PROP under the PROP entry (Definition 3): a
 "colored PROP with set of colors C is a strict symmetric monoidal
 category (P, ⊙) whose monoid of objects is freely generated by C."
 The free monoid on C is the set C* of finite lists/words over C, so
 the objects are LISTS of colours and the tensor on objects is list
 concatenation.  Wikipedia has no dedicated coloured-PROP page and its
 PROP article does not treat the coloured/multisorted generalisation
 (it covers only the one-sorted objects = ℕ case); the URL above is
 the closest real page.

 Further reading (no nLab/Wikipedia page of their own): Lack–Sobocinski
 "Adhesive and quasiadhesive categories" §7; Bonchi–Sobocinski–Zanasi
 "A categorical semantics of signal flow graphs" §4.

 A coloured PROP is the natural many-sorted generalisation of a PROP.
 Fix a set [Colour : Type] of "wire types".  Objects of the PROP are
 LISTS of colours rather than natural numbers; tensor on objects is
 list concatenation rather than addition; the monoidal unit is the
 empty list.  In a PROP all wires are interchangeable; in a coloured
 PROP they carry a type so that morphisms have shape-typed signatures.
 The one-colour (monochromatic) case [Colour = unit] recovers an
 ordinary PROP, since [list unit] is in bijection with [nat] by length
 (see the discussion at the end of the file).

 In library notation, an instance bundles a category with strict and
 symmetric monoidal structure together with the object correspondence

 cprop_of_list  : list Colour -> obj
 cprop_unit_nil   : I = cprop_of_list nil
 cprop_tensor_app : cprop_of_list cs ⨂ cprop_of_list ds
 = cprop_of_list (cs ++ ds)

 Coloured PROPs are the natural setting for tensor-shape-aware
 rewriting: a "transpose" generator on rank-3 inputs is a different
 morphism from the rank-4 version, where the dimensions appear in the
 colour-list signature.

 The class structure mirrors [PROP] (Construction/PROP.v) with [nat]
 replaced by [list Colour] and [+] replaced by [++].

 ** Policy: the coloured spine MIRRORS the one-sorted spine

 The files under Construction/ColouredPROP/ are deliberate
 file-by-file mirrors of their one-sorted donors, not
 instantiations of a shared parameterized core: Free.v mirrors
 PROP/Free.v + PROP/Tensor.v; Cast.v mirrors PROP/Cast.v +
 PROP/CastTensor.v + PROP/Structural.v; Monoidal.v mirrors
 PROP/Naturality.v + PROP/Monoidal.v; Braided.v mirrors
 PROP/Braided.v + PROP/Symmetric.v; Interp.v mirrors
 PROP/Interp.v; Universal.v mirrors PROP/Universal.v; Relabel.v
 mirrors the signature-morphism kit of PROP/Tietze.v; the
 satellite files' headers each name their own donor.  The
 duplication is a deliberate decision, not an accident: the two
 spines differ in their decider/UIP plumbing ([nat] has the
 canonical [Nat.eq_dec], so the donor's UIP layer is
 unconditional, while [list Colour] threads an explicit colour
 decider [Cdec], and the coloured interpretation kit routes UIP
 through the TARGET's objects via [ObjDecEq] instead of the
 boundary index), so a shared strict-boundary-monoid
 parameterization would have to abstract over exactly the plumbing
 that differs.

 Consequences for maintenance:

 - Any change to the [TermEq]/[CTermEq] constructors must budget
 synchronized edits at the four parallel 19-case induction
 sites — [T_subst_TermEq] (PROP/TermEq.v; [T_map_TermEq] and
 [retract_TermEq] in PROP/Tietze.v are one-line corollaries of
 it), [CT_map_CTermEq] (ColouredPROP/Relabel.v),
 [interp_sound_heq] (PROP/Interp.v) and [cinterp_sound_heq]
 (ColouredPROP/Interp.v) — plus the interpretation kits
 downstream of the two soundness theorems.

 - Only three kits are shared BY IMPORT rather than mirrored: the
 [BraidTransport] coherence quarantine (PROP/Interp.v), the
 [MonoidalFunctor_transport] kit (PROP/Universal.v), and the
 hom-congruence quotient machinery (Construction/Quotient.v).
 New features should grow this imported-not-cloned set rather
 than the mirror: follow the model of ColouredPROP/BaseChange.v,
 which is built through the universal property instead of a
 fresh term recursion with yet another 19-case soundness
 induction. 

 --------
 nLab:       https://ncatlab.org/nlab/show/PROP 
 维基百科:  https://en.wikipedia.org/wiki/PROP_(category_theory) 

 nLab 在 PROP 条目下（定义 3）定义了有色 PROP：
 “带有颜色集合 C 的有色 PROP 是一个严格对称单体范畴 (P, ⊙)，其对象的幺半群由 C 自由生成。”
 C 上的自由幺半群是有限列表/单词组成的集合 C*，所以对象是颜色的列表，对象上的张量是列表连接。维基百科没有专门的有色 PROP 页面，其 PROP 文章也没有讨论有色/多类型的推广（只覆盖单类型对象 = ℕ 的情况）；上面提供的 URL 是最接近的实际页面。

 进一步阅读（没有自己独立的 nLab/维基百科页面）：Lack–Sobocinski 《粘着与准粘着范畴》第 7 节；Bonchi–Sobocinski–Zanasi 《信号流图的范畴语义》第 4 节。有色PROP是PROP的自然多范畴推广。
 固定一个“线类型”的集合[Colour : Type]。PROP的对象是颜色的列表而不是自然数；对象的张量是列表连接而不是加法；单模态单位是空列表。在PROP中，所有线是可互换的；在有色PROP中，它们带有类型，因此态射具有形状类型签名。单色（单一颜色）情况[Colour = unit]恢复了普通的PROP，因为[list unit]与[nat]通过长度一一对应（参见文件末尾的讨论）。

 在库符号中，一个实例将一个具有严格对称单模结构的范畴与对象对应关系捆绑在一起。cprop_of_list  : 列表 Colour -> 对象
 cprop_unit_nil   : I = cprop_of_list nil
 cprop_tensor_app : cprop_of_list cs ⨂ cprop_of_list ds
 = cprop_of_list (cs ++ ds)

 彩色 PROPs 是适用于张量形状感知重写的自然环境：在秩为 3 的输入上“转置”生成器是不同于秩为 4 版本的态射，其中维度出现在颜色列表签名中。

 类结构镜像了 [PROP] (Construction/PROP.v)，其中 [nat] 被 [list Colour] 替代，[+] 被 [++] 替代。

 **策略：彩色主干镜像单一类型主干Construction/ColouredPROP/ 下的文件是有意为之的逐文件镜像它们的单一来源文件，而不是共享参数化核心的实例化：Free.v 镜像 PROP/Free.v + PROP/Tensor.v；Cast.v 镜像 PROP/Cast.v + PROP/CastTensor.v + PROP/Structural.v；Monoidal.v 镜像 PROP/Naturality.v + PROP/Monoidal.v；Braided.v 镜像 PROP/Braided.v + PROP/Symmetric.v；Interp.v 镜像 PROP/Interp.v；Universal.v 镜像 PROP/Universal.v；Relabel.v 镜像 PROP/Tietze.v 的签名-同态工具包；卫星文件的头部各自命名自己的来源文件。这种重复是有意的决策，而不是意外：两个主干在它们的决策器/UIP 管道上有所不同（[nat] 有标准的 [Nat.eq_dec]，因此捐赠者的 UIP 层是无条件的，而 [list Colour] 则穿插了一个显式颜色决策器 [Cdec]，并且彩色解释工具包通过 [ObjDecEq] 将 UIP 通过目标的对象路由，而不是边界索引），因此共享的严格边界单子参数化必须对正好不同的管道进行抽象。

 维护的后果：- 对 [TermEq] / [CTermEq] 构造函数的任何更改都必须在四个并行的 19 案例归纳位置预算同步编辑——[T_subst_TermEq]（PROP/TermEq.v；PROP/Tietze.v 中的 [T_map_TermEq] 和 [retract_TermEq] 是它的一行推论）、[CT_map_CTermEq]（ColouredPROP/Relabel.v）、[interp_sound_heq]（PROP/Interp.v）和 [cinterp_sound_heq]（ColouredPROP/Interp.v）——以及两个完备性定理下游的解释工具包。- 只有三个套件是通过导入共享的，而不是镜像的：
 [BraidTransport] 相干隔离（PROP/Interp.v）、
 [MonoidalFunctor_transport] 套件（PROP/Universal.v）、以及
 同余商机械（Construction/Quotient.v）。
 新功能应增加这个导入而非克隆的集合，而不是镜像：
 遵循 ColouredPROP/BaseChange.v 的模型，它是通过通用性质构建的，而不是通过新的术语递归加上另一个19步的正确性归纳。
*)

Section ColouredPROP.

Context (Colour : Type).

Class ColouredPROP : Type := {
  cprop_cat : Category;

  cprop_strict : @StrictMonoidal cprop_cat;
  cprop_symmetric : @SymmetricMonoidal cprop_cat;

  (*
   * Coherence between the two [Monoidal] paths — see the analogous
   [prop_monoidal_coherence] in [Construction/PROP.v] for
   motivation. 

   --------
   * 两条 [Monoidal] 路径之间的一致性 — 参见 [Construction/PROP.v] 中的类似 [prop_monoidal_coherence]，以获取动机。
*)
  cprop_monoidal_coherence :
    (@strict_is_monoidal cprop_cat cprop_strict)
    = (@braided_is_monoidal cprop_cat
         (@symmetric_is_braided cprop_cat cprop_symmetric));

  (*
   * The canonical object correspondence: every list of colours names
   an object of [cprop_cat], with the empty list the monoidal unit
   and concatenation reflecting tensor. 

   --------
   * 规范的对象对应：每一个颜色名称列表对应 [cprop_cat] 的一个对象，空列表对应幺元，列表的连接对应张量。
*)
  cprop_of_list : list Colour -> @obj cprop_cat;

  cprop_unit_nil :
    @I cprop_cat (@strict_is_monoidal cprop_cat cprop_strict)
    = cprop_of_list nil;

  cprop_tensor_app : forall (cs ds : list Colour),
    ((cprop_of_list cs) ⨂[@strict_is_monoidal cprop_cat cprop_strict]
     (cprop_of_list ds))%object
    = cprop_of_list (cs ++ ds)
}.

#[export] Existing Instance cprop_strict.
#[export] Existing Instance cprop_symmetric.

Coercion cprop_cat : ColouredPROP >-> Category.

End ColouredPROP.

Arguments ColouredPROP Colour : assert.
Arguments cprop_cat {Colour} _.
Arguments cprop_strict {Colour} _.
Arguments cprop_symmetric {Colour} _.
Arguments cprop_monoidal_coherence {Colour} _.
Arguments cprop_of_list {Colour _} _.
Arguments cprop_unit_nil {Colour _}.
Arguments cprop_tensor_app {Colour _} _ _.

(** ** Smart accessors / ** 智能访问器 *)

Section ColouredPROPLemmas.

Context {Colour : Type}.
Context (P : ColouredPROP Colour).

(*
   * The Coloured-PROP-object indexed by colour list [cs]. 

   --------
   * 由颜色列表 [cs] 索引的有色 PROP 对象。
*)
Notation "'⟦' cs '⟧c'" := (cprop_of_list (ColouredPROP := P) cs)
  (at level 0, format "⟦ cs ⟧c").

(** Sanity: the unit object of [P] is [⟦[]⟧c]. / 理智：[P] 的单位对象是 [⟦[] ⟧c]。 *)
Lemma cprop_I_eq_nil : @I P _ = ⟦nil⟧c.
Proof. exact (@cprop_unit_nil Colour P). Qed.

(** Sanity: tensor on objects is list concatenation. / 理智：对象上的张量是列表连接。 *)
Lemma cprop_tensor_eq_app (cs ds : list Colour) :
  (⟦cs⟧c ⨂ ⟦ds⟧c)%object = ⟦cs ++ ds⟧c.
Proof. exact (cprop_tensor_app cs ds). Qed.

(*
   * Singleton-colour wire: [⟦[c]⟧c] is the canonical 1-colour object. 

   --------
   * 单色线：[⟦[c] ⟧c] 是典型的单色对象。
*)
Definition wire (c : Colour) : @obj P := ⟦[c]⟧c.

End ColouredPROPLemmas.

Arguments wire {Colour P} c.

(*
   * ** Hypergraph Coloured PROPs

   Analogous to [HypergraphPROP]: a [ColouredPROP] whose underlying
   symmetric monoidal category carries a [Hypergraph] instance.
   Every wire-list carries a special commutative Frobenius algebra
   coherent under concatenation. 

   --------
   * ** 超图彩色PROPs

   类似于[HypergraphPROP]：一个[ColouredPROP]，其底层对称单范畴承载了[Hypergraph]实例。
   每个线列表携带一个特殊的可交换Frobenius代数，并在串联下保持相干性。
*)

Class HypergraphColouredPROP {Colour : Type} : Type := {
  hcprop : ColouredPROP Colour;

  hcprop_hyper : @Hypergraph
                   (@cprop_cat Colour hcprop)
                   (@cprop_symmetric Colour hcprop)
}.

Arguments HypergraphColouredPROP Colour : assert.

#[export] Existing Instance hcprop_hyper.

Coercion hcprop : HypergraphColouredPROP >-> ColouredPROP.

(*
   * ** Discussion: relationship to plain PROPs

   A [PROP] is the special case of [ColouredPROP unit] (one colour).
   The wire-list [list unit] is in bijection with [nat] via length,
   so [cprop_of_list (repeat tt n)] corresponds to [prop_of_nat n]
   and concatenation corresponds to addition.

   That correspondence is formalised in
   [Construction/ColouredPROP/UnitBridge.v]: class-level transports
   in both directions, free-level bridge functors, and
   hom_cast-conjugated round-trip laws showing coloured PROPs
   strictly generalise PROPs. 

   --------
   * ** 讨论：与普通 PROP 的关系

   A [PROP] 是 [ColouredPROP unit]（单色）的特例。
   电线列表 [list unit] 通过长度与 [nat] 存在一一对应，因此 [cprop_of_list (repeat tt n)] 对应于 [prop_of_nat n]，
   且连接对应于加法。

   这种对应关系在 [Construction/ColouredPROP/UnitBridge.v] 中得到形式化：类级别的传输
   在两个方向上、自由级别的桥接函子，以及通过 hom_cast 伴随的往返定律表明，有色 PROP 严格地推广了 PROP。
*)
