(*
   * ** The universal property, bundled

   Riehl §4.2 Example 4 and Mac Lane §II.7 Ex. 3 in one statement.  The
   object agreement [Hobj] is nested INSIDE the bundle on purpose, exactly
   as in [Construction/Free/Quiver/Presented.v]'s [presented_universal]: a
   flat statement of the generator clause has no common hom, since for an
   abstract [K] the objects [fobj[K] x] and [@fnodes _ _ F x] are not
   convertible until [Hobj] is in scope.

   The generator clause constrains only the POSITIVE generators — the edges
   of [G] — which is what makes this the universal property of the free
   GROUPOID rather than of the free category on the signed quiver. 

   --------
   * ** 通用性质，捆绑形式

   Riehl §4.2 示例 4 和 Mac Lane §II.7 练习 3 的综合陈述。对象一致性 [Hobj] 被有意嵌套在捆绑中，正如 [Construction/Free/Quiver/Presented.v] 的 [presented_universal] 一样：生成元子句的平铺陈述没有公共 Hom，因为对于抽象的 [K]，[fobj[K] x] 和 [@fnodes _ _ F x] 对象在 [Hobj] 在作用域内之前不可转换。

   生成元子句仅约束正生成元——[G] 的边——这正是使其成为自由群oids 的通用性质，而不是带符号弦图自由范畴的通用性质。
*)

Section FreeGroupoidUniversal.

Context (G : Quiver) {D : Category}.
Context (Dg : IsGroupoid D).

Theorem free_groupoid_universal
  (F : QuiverHomomorphism G (QuiverOfCat D)) :
  { K : FreeGroupoid G ⟶ D &
  { Hobj : ∀ x : G, fobj[K] x = @fnodes _ _ F x &
    ((∀ (x y : G) (e : edges x y),
        hom_cast (Hobj x) (Hobj y) (fmap[K] (fgpos e))
          ≈ @fedgemap _ _ F x y e) *
     (∀ (K' : FreeGroupoid G ⟶ D)
        (Hobj' : ∀ x : G, fobj[K'] x = @fnodes _ _ F x),
        (∀ (x y : G) (e : edges x y),
           hom_cast (Hobj' x) (Hobj' y) (fmap[K'] (fgpos e))
             ≈ @fedgemap _ _ F x y e) →
        ∀ (x y : G) (f : x ~{FreeGroupoid G}~> y),
          hom_cast (Hobj' x) (Hobj' y) (fmap[K'] f)
            ≈ hom_cast (Hobj x) (Hobj y) (fmap[K] f)))%type } }.
Proof using D Dg G.
  exists (FreeGroupoidFunctor G Dg F), (fun _ => eq_refl).
  split.
  - intros x y e. exact (FreeGroupoidFunctor_gen G Dg F e).
  - intros K' Hobj' Hgen x y f.
    exact (FreeGroupoidFunctor_unique G Dg F K' Hobj' Hgen x y f).
Qed.

End FreeGroupoidUniversal.

(*
   * ** The converse leg

   Restricting a functor out of the free groupoid along the unit gives back
   a quiver homomorphism, and re-extending recovers the functor.  This is
   what makes Riehl's “exactly” honest in both directions. 

   --------
   * ** 逆腿

   将函子沿单位从自由群oid限制出来，会得到一个图同态，重新扩展则可以恢复原函子。这正是使得Riehl的“确切”在两个方向上都诚实的原因。
*)

Definition fg_restrict {G : Quiver} {D : Category} (S : FreeGroupoid G ⟶ D)
  : QuiverHomomorphism G (QuiverOfCat D) :=
  QuiverComp (FreeGroupoidUnit G) (QuiverHomomorphismOfFunctor _ _ S).

(*
   * On generators the restriction is [S] itself, definitionally — a Leibniz
   equality of morphisms, stated at that strength deliberately, in the
   manner of [QuotientLift_proj] ([Construction/Quotient.v]). 

   --------
   * 在生成元上，限制本身就是 [S]，从定义上来说 — 一个摩尔范数的莱布尼兹等式，以这种强度故意陈述，方式类似于 [QuotientLift_proj] ([Construction/Quotient.v])。
*)
Lemma fg_restrict_gen {G : Quiver} {D : Category} (S : FreeGroupoid G ⟶ D)
  {x y : G} (e : edges x y) :
  @fedgemap _ _ (fg_restrict S) x y e = fmap[S] (fgpos e).
Proof. reflexivity. Qed.

(*
   * ...and the restriction re-extends to [S] on every word. 

   --------
   * ……并且这个限制在每个单词上重新扩展到 [S]。
*)
Lemma fg_restrict_recovers {G : Quiver} {D : Category} (Dg : IsGroupoid D)
  (S : FreeGroupoid G ⟶ D) (x y : G) (f : x ~{FreeGroupoid G}~> y) :
  fmap[S] f ≈ fmap[FreeGroupoidFunctor G Dg (fg_restrict S)] f.
Proof.
  refine (FreeGroupoidFunctor_unique G Dg (fg_restrict S) S
            (fun _ => eq_refl) _ x y f).
  intros a b e; reflexivity.
Qed.

(*
   * The round trip at STRICT strength: an equality of functors in
   [StrictCat], via [Construction/Quotient.v]'s [strict_of_hom_cast]. 

   --------
   * 在严格强度下的往返：通过  [Construction/Quotient.v] 的  [strict_of_hom_cast] , 在 [StrictCat] 中的范畴函子等价。
*)
Lemma fg_restrict_recovers_strict {G : Quiver} {D : Category}
  (Dg : IsGroupoid D) (S : FreeGroupoid G ⟶ D) :
  @equiv _ (@Functor_StrictEq_Setoid (FreeGroupoid G) D)
    S (FreeGroupoidFunctor G Dg (fg_restrict S)).
Proof.
  apply (strict_of_hom_cast S (FreeGroupoidFunctor G Dg (fg_restrict S))
           (fun _ => eq_refl)).
  intros x y f.
  exact (fg_restrict_recovers Dg S x y f).
Qed.

(*
   * ...and the OTHER round trip: extending a quiver homomorphism and then
   restricting recovers it, as an equality in [QuiverCategory].  The two
   together make the correspondence run both ways with both round trips
   proved, which is what “exactly” has to mean. 

   --------
   * ……以及另一个往返过程：扩展一个箭袋同态，然后再进行限制可以恢复它，这在  [QuiverCategory] 中作为一个等式成立。两者结合使该对应关系可以双向运行，并且两个往返过程都被证明，这正是“确切地”必须意味着的。
*)
Lemma fg_extend_restrict {G : Quiver} {D : Category} (Dg : IsGroupoid D)
  (F : QuiverHomomorphism G (QuiverOfCat D)) :
  @equiv _ (@homset QuiverCategory G (QuiverOfCat D))
    (fg_restrict (FreeGroupoidFunctor G Dg F)) F.
Proof.
  exists (fun _ => eq_refl).
  intros x y e; simpl.
  exact (FreeGroupoidFunctor_gen G Dg F e).
Qed.

(*
   * ** Equations merge, and never add

   The projection is the identity on objects and on morphisms; only the
   hom-setoid equivalence coarsens.  It is full, and — as the witnesses
   below show — deliberately NOT faithful. 

   --------
   * ** 方程合并，而不是相加

   投影在对象和态射上都是恒等的；只有同态集合的等价关系变得更粗。它是满的，而且——如下方实例所示——故意不是忠实的。
*)

Lemma fg_proj_obj {G : Quiver} (x : G) :
  fobj[FreeGroupoidProj G] x = x.
Proof. reflexivity. Qed.

Lemma fg_hom_type {G : Quiver} (x y : G) :
  (x ~{FreeGroupoid G}~> y) = (x ~{FreeSigned G}~> y).
Proof. reflexivity. Qed.

Definition FreeGroupoidProj_Full {G : Quiver} : Full (FreeGroupoidProj G) :=
  @QuotientProj_Full (FreeSigned G) (CongClosure (FreeGroupoidRel G))
    (CongClosure_Congruence (FreeGroupoidRel G)).

(*
   * ** Non-vacuity

   The quotient genuinely does something, and it does not do everything.
   Both halves are proved, not asserted. 

   --------
   * ** 非空性

   商确实做了一些事情，但并非做所有事情。
   两个部分都被证明，而不是宣称。
*)

(*
   * In the free CATEGORY on the signed quiver, the cancellation equation
   FAILS: a two-letter word is not the empty word, by the path-length
   invariant [tlist'_equiv_lengths] ([Construction/Free/Quiver.v]). 

   --------
   * 在带符号箭簇的自由范畴中，消去方程式失败：一个双字母词不是空字，通过路径长度不变量 [tlist'_equiv_lengths]（[Construction/Free/Quiver.v]）。
*)
Theorem free_signed_no_cancellation {G : Quiver} {x y : G} (e : edges x y) :
  @equiv _ (@homset (FreeSigned G) x x) (sneg e ∘ spos e) id → False.
Proof.
  intro H.
  pose proof (tlist'_equiv_lengths (SignedQuiver G) x x x
                (spos e +++ sneg e) tnil eq_refl H) as Hl.
  unfold spos, sneg, tlist_singleton in Hl.
  rewrite tlist_app_length in Hl.
  simpl in Hl.
  discriminate.
Qed.

(*
   * The quotient is NECESSARY, not a convenience: as soon as the quiver has
   an edge, the free CATEGORY on the signed quiver is not a groupoid.  Any
   left inverse of a one-letter word would compose with it to a word of
   length at least one, and the empty word has length zero. 

   --------
   * 商是必要的，而不是方便的：一旦箭袋有一个边，带符号箭袋上的自由范畴就不是一个群范畴。任何单字的左逆会与它组合成一个长度至少为一的单词，而空单词的长度为零。
*)
Theorem free_signed_not_groupoid {G : Quiver} {x y : G} (e : edges x y) :
  IsGroupoid (FreeSigned G) → False.
Proof.
  intro Hg.
  pose proof (@is_left_inverse _ _ _ _ (Hg x y (spos e))) as Hinv.
  pose proof (tlist'_equiv_lengths (SignedQuiver G) x x x
                (spos e +++ @two_sided_inverse _ _ _ _ (Hg x y (spos e)))
                tnil eq_refl Hinv) as Hl.
  rewrite tlist_app_length in Hl.
  unfold spos, tlist_singleton in Hl.
  simpl in Hl.
  discriminate.
Qed.

(*
   * Hence the projection is not faithful: it identifies the two-letter word
   with the empty one.  Fong and Spivak's “equations merge, but never add”,
   with both halves in hand. 

   --------
   * 因此，该投影不是保真的：它将这个双字母词与空词识别为相同。Fong 和 Spivak 的“方程会合并，但从不相加”，两部分都掌握在手中。
*)
Theorem fg_proj_not_faithful {G : Quiver} {x y : G} (e : edges x y) :
  Faithful (FreeGroupoidProj G) → False.
Proof.
  intro HF.
  apply (free_signed_no_cancellation e).
  apply (@fmap_inj _ _ _ HF).
  exact (fg_cancel_left e).
Qed.

(*
   * *** A generator that is provably not an identity

   The quotient does not collapse: over the quiver with one node and one
   loop, the generator stays apart from the identity.  The separating
   functor lands in the delooping of Z/2 ([Construction/Deloop.v]'s
   [Bool_Xor_Grp], a groupoid by [Structure/Groupoid.v]'s
   [deloop_bool_groupoid]). 

   --------
   * *** 一个可以被证明不是恒等的生成元

   商不坍塌：在具有一个节点和一个循环的箭图上，生成元与恒等保持分离。分离函子落在 Z/2 的去循环上（[Construction/Deloop.v] 的 [Bool_Xor_Grp]，由 [Structure/Groupoid.v] 的 [deloop_bool_groupoid] 构成的一个群范畴）。
*)

(*
 NAME. This is [FGLoopQuiver] and not [LoopQuiver] because the tree already
 has TWO quivers by the latter name: [Theory/Diagram.v]'s (one node, one
 loop — differing from this one only in the node type) and
 [Construction/Free/Quiver/Concrete.v]'s (one node, TWO loops). Neither is
 imported here, so a third would not have conflicted today; it is renamed
 rather than merely disclosed because a silent shadow is exactly the hazard
 the two-[GrpObject] note above spends a paragraph on, and this file should
 not create the kind of collision it warns about. 

 --------
 名称。这是 [FGLoopQuiver]，而不是 [LoopQuiver]，因为树中用后者名字已经有两个箭袋：[Theory/Diagram.v]（一个节点，一个循环——与这个唯一不同的是节点类型）和 [Construction/Free/Quiver/Concrete.v]（一个节点，两个循环）。这里都没有导入，所以第三个今天不会产生冲突；它被重命名而不仅仅是公开，因为一个静默的影子正是上面两条 [GrpObject] 注释中用一段话讨论的危险，而这个文件不应该产生它警告的那种冲突。
*)
Definition FGLoopQuiver : Quiver :=
  Build_Quiver_Standard_Eq poly_unit (fun _ _ => unit).

(** The loop, as a morphism of the free groupoid. / 循环，作为自由群族的态射。 *)
Definition loop_gen : ttt ~{FreeGroupoid FGLoopQuiver}~> ttt :=
  @fgpos FGLoopQuiver ttt ttt tt.

Definition loop_to_Z2
  : QuiverHomomorphism FGLoopQuiver (QuiverOfCat (Deloop Bool_Xor_Grp)).
Proof.
  unshelve eapply Build_QuiverHomomorphism.
  - exact (fun _ => ttt).
  - exact (fun _ _ _ => true).
  - intros a b u v Huv; reflexivity.
Defined.

Definition loop_Z2 : FreeGroupoid FGLoopQuiver ⟶ Deloop Bool_Xor_Grp :=
  FreeGroupoidFunctor FGLoopQuiver deloop_bool_groupoid loop_to_Z2.

Theorem loop_generator_not_identity :
  loop_gen ≈ @id (FreeGroupoid FGLoopQuiver) ttt → False.
Proof.
  intro H.
  assert (Hb : @equiv _ (@homset (Deloop Bool_Xor_Grp) ttt ttt)
                 (fmap[loop_Z2] loop_gen)
                 (fmap[loop_Z2] (@id (FreeGroupoid FGLoopQuiver) ttt)))
    by (now rewrite H).
  rewrite fmap_id in Hb.
  rewrite (FreeGroupoidFunctor_gen FGLoopQuiver deloop_bool_groupoid
             loop_to_Z2 (x:=ttt) (y:=ttt) tt) in Hb.
  simpl in Hb.
  discriminate.
Qed.

(*
   * ...and it IS invertible, with the negative generator as its inverse —
   which is the whole point of passing to the groupoid. 

   --------
   *……并且它是可逆的，其逆元是负生成元——这就是转向群的整个意义所在。
*)
Example loop_generator_invertible :
  ginv (FreeGroupoid_IsGroupoid FGLoopQuiver) loop_gen
    = @fgneg FGLoopQuiver ttt ttt tt.
Proof. reflexivity. Qed.
