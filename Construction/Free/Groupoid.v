   Wikipedia:  https://en.wikipedia.org/wiki/Groupoid 
   书籍: Mac Lane, 《为工作数学家而写的范畴论》，第二版，GTM 5，§II.7，第 51 页（练习 3：图上的自由群，以及单对象情况下的自由群）
