(*
   * * Categories presented by generators and relations

   nLab: https://ncatlab.org/nlab/show/quotient+category
   nLab: https://ncatlab.org/nlab/show/congruence
   Book: Mac Lane, Categories for the Working Mathematician, 2nd ed.,
   §II.8, printed pp. 51-52 (Proposition 1; congruences and the
   least congruence containing a family; categories presented by
   generators and relations)
   Book: Awodey, Category Theory, §4.4, printed p. 89 (the finitely
   presented category C(G,Σ))
   Book: Fong and Spivak, Seven Sketches in Compositionality, CUP 2019,
   §3.2.2, printed p. 84 (path equations, finite presentations, and
   finitely presented categories)
   Book: Riehl, Category Theory in Context, §1.6 Remark 1.6.7, printed
   p. 41

   THE RECIPE.  Take the free category on a quiver, then quotient it by
   the congruence generated by a family of path equations.  This is the
   categorical analogue of presenting a monoid or a group by generators
   and relations, and it is Mac Lane's §II.7 followed immediately by his
   §II.8: [Construction/Free/Quiver.v] supplies the first half,
   [Construction/Quotient.v] the second, and this file is the chaining
   that [Construction/Free.v]'s header narrates.

   PARALLELISM IS STRUCTURAL, not a side condition.  Seven Sketches
   restricts an imposed equation to paths sharing both a source and a
   target.  Here that restriction costs nothing: [PathRel] is indexed by a
   source and a target with both arguments paths between exactly those
   endpoints, so an equation between non-parallel paths cannot be written
   down at all.  [PathRel_parallel] records the unfolding as a
   definitional equality.

   EQUATIONS ONLY MERGE.  The projection is the identity on objects and
   the identity on morphisms; only the hom-setoid equivalence coarsens.
   Hence [presented_proj_obj], [presented_hom_type] and
   [PresentedQuiverProj_Full] (restated existentially as
   [presented_proj_hom_surjective]), and hence also the projection is
   deliberately not [Faithful] — that non-instance is the whole content of
   Fong and Spivak's remark that imposing equations can merge morphisms
   but never add any.

   THE STRENGTH OF THE UNIVERSAL PROPERTY, which is the opposite of what a
   reader expects.  [presented_universal] is STRICT: the object agreement
   is Leibniz [=] and the morphism agreement is a [hom_cast] conjugation
   along it, which is exactly [StrictCat]'s functor equality
   ([Functor_StrictEq_Setoid]) — the level at which
   [Construction/Free/Quiver.v]'s free universal property already lives,
   since [Forgetful] is a functor over [StrictCat] and has no [Cat]
   counterpart ([Test/Issue138.v]).  Strict is STRONGER than a [Cat]-level
   reading, and the weaker one follows from it rather than replacing it:
   [strict_of_hom_cast] ([Construction/Quotient.v]) followed by
   [strict_equiv_implies_fun_equiv] ([Instance/StrictCat/ToCat.v]) turns
   the uniqueness clause into a natural isomorphism in [Cat] in two lines.
   Nothing here is stated only at that weaker level.

   THE ORDINAL 3.  The free category on the two-edge LINEAR quiver is
   already the ordinal 3 — its homs are the empty path at each node, [a],
   [b] and [a] then [b] — so a relation-free “presentation of 3 by a
   composable pair” is degenerate.  The non-degenerate reading, and the
   one the example below takes, is three generators a : 0 → 1, b : 1 → 2
   and c : 0 → 2 with the single relation c = b ∘ a, the commutative
   triangle.  [Instance/Ordinal.v]'s [Ordinal 3] is the comparison target
   for an isomorphism [Ord3 ≅ Ordinal 3]; that isomorphism is NOT proven
   here, and this file deliberately does not depend on
   [Instance/Ordinal.v], which would pull [Instance/Cat], [Instance/Two],
   [Coq.Lists.List] and [Coq.micromega.Lia] into the [Construction/] layer
   for a comparison this file does not make.  What is proven is that the two
   paths are distinct in the free category ([ord3_free_distinct]) and
   identified in the presented one ([ord3_relation_holds]);
   [presented_no_eqns_separates] below shows the quotient does not
   collapse indiscriminately.

   RIEHL'S SQUARE.  Riehl §1.6 Remark 1.6.7 asks that
   [funny_diagonals_distinct] ([Construction/Funny/Comparison.v]) be cited
   rather than reproved.  That instruction is not followable as written:
   the theorem is stated about [feq] in [_2 □ _2], and transporting it to
   [FreeOnQuiver] of the square quiver needs a comparison
   [_2 □ _2 ≅ FreeOnQuiver (square quiver)] which is not in tree.  This
   file therefore proves the [FreeOnQuiver]-native form directly
   ([free_square_diagonals_distinct], six lines, axiom-free) and cites
   [funny_diagonals_distinct] here as the independent shadow of the same
   fact under a different name.  No [Require] on [Construction/Funny/] is
   added.

   THE ONE-OBJECT CASE.  [hom_monoid] ([Construction/Deloop.v]), not
   [Deloop], is the relevant direction: the endomorphism monoid of the
   single node of a one-node quiver recovers the free monoid
   ([FreeMonoidOn]) and, after quotienting, the presented monoid
   ([PresentedMonoidOn]).

   FINITENESS IS DATA.  [FiniteQuiver] enumerates nodes and edges as
   [Fin.t] indices with retractions back onto them; [FiniteEquations]
   carries a per-endpoint-pair count with the two sides of each equation
   indexed by [Fin.t].  Neither is an existence claim over lists, so no
   choice principle is used anywhere.  [Ord3Finite] and
   [Ord3Presentation] are the in-tree witnesses.

   WHERE THE ENGINE IS.  The [Type]-valuedness rationale for the generated
   congruence, the universe constraint it carries, and the comparison with
   the bespoke [TermEqW] closure of the PROP presentation layer are stated
   once, in [Construction/Quotient.v]'s subsection on the congruence
   generated by a hom-relation; they are cross-referenced from here rather
   than repeated. 

   --------
   * * 由生成元和关系给出的范畴

   nLab: https://ncatlab.org/nlab/show/quotient+category 
   nLab: https://ncatlab.org/nlab/show/congruence 
   书籍: Mac Lane，《工作数学家的范畴论》，第二版，第 II.8 节，印刷页 51-52（命题 1；同余以及包含某族的最小同余；由生成元和关系给出的范畴）
   书籍: Awodey，《范畴论》，§4.4，印刷页 89（有限呈现的范畴 C(G,Σ)）
   书籍: Fong 和 Spivak，《组合性的七个草图》，CUP 2019，§3.2.2，印刷页 84（路径方程、有限呈现、有限呈现的范畴）
   书籍: Riehl，《语境中的范畴论》，§1.6 注释 1.6.7，印刷页 41配方。取一个箭图上的自由范畴，然后通过由一族路径方程生成的合同进行商化。这是用生成元和关系来描述幺半群或群的范畴类似物，它对应于 Mac Lane 的 §II.7 紧接着 §II.8：[Construction/Free/Quiver.v] 提供前半部分，[Construction/Quotient.v] 提供后半部分，而此文件则是 [Construction/Free.v] 的标题所叙述的链式连接。平行性是结构性的，而不是附带条件。七个素描将强加的方程限制在共享源和目标的路径上。在这里，这个限制毫无代价：[PathRel] 是按源和目标索引的，其两个参数都是在完全相同端点之间的路径，因此无法写出非平行路径之间的方程。[PathRel_parallel] 将展开记录为定义性的等式。仅方程会合并。投影在对象上是恒等的，在态射上也是恒等的；只有同态集合的等价被粗化。因此 [presented_proj_obj]、[presented_hom_type] 和 [PresentedQuiverProj_Full]（以存在量词重新表述为 [presented_proj_hom_surjective]），因此投影故意不是 [Faithful]——该非实例正是 Fong 和 Spivak 提出的评论的全部内容，即施加方程可以合并态射，但绝不能增加任何态射。宇宙性质的强度，这正好与读者的预期相反。[presented_universal] 是严格的：对象一致性是莱布尼茨 [=]，而箭头一致性是沿着它的 [hom_cast] 共轭，这正是 [StrictCat] 的函子等式（[Functor_StrictEq_Setoid]）——这是 [Construction/Free/Quiver.v] 的自由宇宙性质已经存在的层次，因为 [Forgetful] 是 [StrictCat] 上的一个函子，并且没有 [Cat] 的对应（[Test/Issue138.v]）。严格性比 [Cat] 层次的解释要强，而较弱的解释是从严格性中得出，而不是替代它：[strict_of_hom_cast]（[Construction/Quotient.v]）随后 [strict_equiv_implies_fun_equiv]（[Instance/StrictCat/ToCat.v]）将唯一性条款在 [Cat] 中转化为两行中的自然同构。这里没有内容仅在较弱的层次上陈述。序数 3。在两边 LINEAR quiver 上的自由范畴已经是序数 3——它的同态是每个结点上的空路径，[a], [b] 和 [a]，然后是 [b]——所以一个无关系的“由可组合对呈现 3”的表示是退化的。非退化的理解，以及下面示例采取的，是三个生成元 a : 0 → 1, b : 1 → 2 和 c : 0 → 2，且有单一关系 c = b ∘ a，即交换三角形。[Instance/Ordinal.v] 的 [Ordinal 3] 是用于同构比较的目标 [Ord3 ≅ Ordinal 3]；这个同构在此并未被证明，而且此文件刻意不依赖 [Instance/Ordinal.v]，否则将会把 [Instance/Cat], [Instance/Two], [Coq.Lists.List] 和 [Coq.micromega.Lia] 拉入 [Construction/] 层，而此文件没有进行这种比较。已被证明的是，在自由范畴 ([ord3_free_distinct]) 中这两条路径是不同的，而在给定范畴 ([ord3_relation_holds]) 中它们是相同的；下面的 [presented_no_eqns_separates] 显示了商并不会随意坍塌。

   RIEHL 的方形。Riehl §1.6 注释 1.6.7 要求引用 [funny_diagonals_distinct] ([Construction/Funny/Comparison.v]) 而不是重新证明。该指令按原文无法遵循：定理是关于 [feq] 在 [_2 □ _2] 中的，并且将其转移到方形箭图的 [FreeOnQuiver] 上需要一个 [_2 □ _2 ≅ FreeOnQuiver (square quiver)] 的比较，而该比较不在树中。因此，本文件直接证明了 [FreeOnQuiver]-本地形式 ([free_square_diagonals_distinct]，六行，无公理) 并在此引用 [funny_diagonals_distinct] 作为同一事实在不同名称下的独立影子。未增加 [Require] 对 [Construction/Funny/] 的引用。单对象情况。[hom_monoid]（[Construction/Deloop.v]），而不是[Deloop]，是相关方向：一个单节点箭图的单节点的自同态半群恢复了自由半群（[FreeMonoidOn]），并且在取商后，得到给定的半群（[PresentedMonoidOn]）。

   有限性是数据。[FiniteQuiver] 将节点和边列举为 [Fin.t] 指数，并有回缩到它们的映射；[FiniteEquations] 对每个端点对进行计数，每个方程的两边由 [Fin.t] 索引。两者都不是关于列表的存在性声明，因此在任何地方都没有使用选择公理。[Ord3Finite] 和 [Ord3Presentation] 是树内证据。发动机的位置。 [Type] 生成的合同性的数值合理性、它所承载的宇宙约束，以及与定制的 [TermEqW] PROP 表示层闭包的比较，都在 [Construction/Quotient.v] 关于由同态关系生成的合同性的子章节中说明；这里通过交叉引用而不是重复说明。
*)

Section Presentation.

Universes o h p.
Context (G : Quiver@{o h p}).

(*
   * ** Path equations

   A family of equations between paths of [G].  It is exactly a relation
   family on [FreeOnQuiver G], and it must be spelled as that alias rather
   than written out: recovering the ambient category from a spelled-out
   [∀ x y : G, tlist edges x y → …] is a higher-order problem, and
   [QuotientCong] then does not accept it. 

   --------
   * ** 路径方程

   一族关于  [G] 的路径方程。它恰好是
   [FreeOnQuiver G] 上的一个关系族，并且必须以该别名拼写，而不是写出来：
   从拼写出来的 [∀ x y : G, tlist edges x y → …] 恢复环境范畴是一个高阶问题，
   然后 [QuotientCong] 不接受它。
*)
Definition PathRel : Type := HomRelT (FreeOnQuiver G).

(*
   * Parallelism, as a definitional fact.  The family is indexed by a source
   and a target, and both arguments are paths between exactly those
   endpoints, so an equation between non-parallel paths is not merely
   disallowed — it cannot be written. 

   --------
   * 平行性，作为一个定义性事实。这个族由一个源和一个目标索引，并且两个参数都是在恰好这些端点之间的路径，因此非平行路径之间的方程不仅是不允许的——它甚至无法被书写。
*)
Example PathRel_parallel :
  PathRel = (∀ x y : G, tlist edges x y → tlist edges x y → Type).
Proof. reflexivity. Qed.

(*
   * ** Finiteness, carried as data

   Seven Sketches §3.2.2 asks for finiteness as enumerations rather than
   as an existence claim.  [FiniteQuiver] carries [Fin.t] indices with
   retractions; [FiniteEquations] carries a [Fin.t]-indexed family of
   equations.  No choice principle is used.  Nodes are compared by
   Leibniz [=] (a quiver's nodes are a strict [Type]) and edges by [≈]
   (they carry [edgeset]). 

   --------
   * ** 有限性，以数据的形式呈现

   《七个素描》第3.2.2节要求将有限性作为枚举而非存在性声明。[FiniteQuiver]  携带 [Fin.t] 索引及其收缩；[FiniteEquations] 携带 [Fin.t] 索引的方程族。未使用选择原理。节点通过莱布尼茨 [=] 进行比较（一幅箭形图的节点是严格的 [Type] ），边通过 [≈] 比较（它们携带 [edgeset]）。
*)
Record FiniteQuiver : Type := {
  fq_nodes : nat;
  fq_node : Fin.t fq_nodes → G;
  fq_index : G → Fin.t fq_nodes;
  fq_node_rt : ∀ x : G, fq_node (fq_index x) = x;
  fq_edges : G → G → nat;
  fq_edge : ∀ x y : G, Fin.t (fq_edges x y) → edges x y;
  fq_eindex : ∀ x y : G, edges x y → Fin.t (fq_edges x y);
  fq_edge_rt : ∀ (x y : G) (e : edges x y),
      fq_edge x y (fq_eindex x y e) ≈ e
}.

(** Finitely many equations, per parallel pair of endpoints. / 每对端点的平行线上的有限多方程。 *)
Record FiniteEquations : Type := {
  fe_count : G → G → nat;
  fe_lhs : ∀ x y : G, Fin.t (fe_count x y) → x ~{FreeOnQuiver G}~> y;
  fe_rhs : ∀ x y : G, Fin.t (fe_count x y) → x ~{FreeOnQuiver G}~> y
}.

(*
   * The path relation a finite equation set names.  [∃] is [sigT] here, so
   this lands in [Type], matching [PathRel]. 

   --------
   * 有限方程组命名的路径关系。[∃] 在这里是 [sigT]，所以这落在 [Type] 中，与 [PathRel] 匹配。
*)
Definition fe_rel (E : FiniteEquations) : PathRel :=
  fun x y f g => ∃ i : Fin.t (fe_count E x y),
    (f ≈ fe_lhs E x y i) * (g ≈ fe_rhs E x y i).

Context (R : PathRel).

(*
   * ** The presented category

   Generators [G], relations [R]: the free category on [G], quotiented by
   the congruence generated by [R]. 

   --------
   * ** 所呈现的范畴

   生成元  [G] ，关系  [R] ：在  [G] 上的自由范畴，被  [R] 生成的合同商所商化。
*)
Definition PresentedQuiver : Category := QuotientCong (FreeOnQuiver G) R.

(** The presenting projection. / 当前显示的投影。 *)
Definition PresentedQuiverProj : FreeOnQuiver G ⟶ PresentedQuiver :=
  QuotientCongProj R.

(*
   * A generating edge, read as a morphism of the presented category. 

   --------
   * 一个生成边，被读作所呈现范畴的一个态射。
*)
Definition pgen {x y : G} (e : edges x y) : x ~{PresentedQuiver}~> y :=
  tlist_singleton e.

(*
   * Mac Lane §II.8 Proposition 1, clause (i), specialized: the imposed
   equations hold in the presented category. 

   --------
   * Mac Lane §II.8 命题 1，条款 (i)，专门化：在所呈现的范畴中，所强加的方程成立。
*)
Lemma presented_relations_hold {x y : G}
  {p q : x ~{FreeOnQuiver G}~> y} (Hr : R x y p q) :
  fmap[PresentedQuiverProj] p ≈ fmap[PresentedQuiverProj] q.
Proof. exact (cong_identifies R Hr). Qed.

(** The projection is the identity on objects. / 投影在对象上是恒等映射。 *)
Lemma presented_proj_obj (x : G) : fobj[PresentedQuiverProj] x = x.
Proof. reflexivity. Qed.

(*
   * The hom TYPES are untouched: equations merge, and never add. 

   --------
   * 同质类型保持不变：方程合并，且从不新增。
*)
Lemma presented_hom_type (x y : G) :
  (x ~{PresentedQuiver}~> y) = (x ~{FreeOnQuiver G}~> y).
Proof. reflexivity. Qed.

(** Surjectivity on each hom-set, as a CHOSEN section. / 在每个同集上的满射，作为一个选定的截面。 *)
Definition PresentedQuiverProj_Full : Full PresentedQuiverProj :=
  @QuotientProj_Full (FreeOnQuiver G) (CongClosure R)
    (CongClosure_Congruence R).

(** The same, restated for readers who want the existential. / 相同的，为想要存在主义内容的读者重述。 *)
Lemma presented_proj_hom_surjective {x y : G}
  (f : x ~{PresentedQuiver}~> y) :
  { p : x ~{FreeOnQuiver G}~> y & fmap[PresentedQuiverProj] p ≈ f }.
Proof. exists f. reflexivity. Qed.

(*
   * ** The universal property

   A functor out of the presented category is exactly a quiver
   homomorphism whose induced functor merges the relations. 

   --------
   * ** 通用性质

   从所给范畴出的函子正好是一个箭图同态，其诱导的函子合并了这些关系。
*)

Section PresentedUMP.

Context {D : Category}.
Context (F : QuiverHomomorphism G (QuiverOfCat D)).
Context (HF : ∀ x y (f g : x ~{FreeOnQuiver G}~> y), R x y f g →
              fmap[InducedFunctor G F] f ≈ fmap[InducedFunctor G F] g).

(** The induced functor out of the presented category. / 从所呈现的范畴导出的诱导函子。 *)
Definition PresentedFunctor : PresentedQuiver ⟶ D :=
  QuotientCongLift R (InducedFunctor G F) HF.

(*
   * It sends each generator where the quiver homomorphism does.  (The
   [id_left] is the path fold's trailing identity on a singleton path.) 

   --------
   * 它将每个生成元发送到箭袋同态所到达的位置。（[id_left] 是单路径上路径折叠的尾随恒等式。）
*)
Lemma PresentedFunctor_gen {x y : G} (e : edges x y) :
  fmap[PresentedFunctor] (pgen e) ≈ @fedgemap _ _ F x y e.
Proof. simpl. now rewrite id_left. Qed.

(** ...and each node likewise, on the nose. / ...并且每个节点也一样，恰到好处。 *)
Lemma PresentedFunctor_obj (x : G) :
  fobj[PresentedFunctor] x = @fnodes _ _ F x.
Proof. reflexivity. Qed.

(*
   * Uniqueness, at STRICT strength: Leibniz equality on objects and a
   [hom_cast] conjugation on morphisms — [StrictCat]'s functor equality,
   which [strict_of_hom_cast] ([Construction/Quotient.v]) converts.  The
   induction is [Construction/Free/Quiver.v]'s, with [transport] and
   [transport_r] replaced by [hom_cast] and [hom_cast_comp]. 

   --------
   * 唯一性，在严格强度下：对象上的莱布尼茨等式和态射上的 [hom_cast] 共轭 —— [StrictCat] 的函子等式，由 [strict_of_hom_cast]（[Construction/Quotient.v]）转换。归纳法是 [Construction/Free/Quiver.v] 的，将 [transport] 和 [transport_r] 替换为 [hom_cast] 和 [hom_cast_comp]。
*)
Lemma PresentedFunctor_unique (K : PresentedQuiver ⟶ D)
  (Hobj : ∀ x : G, fobj[K] x = @fnodes _ _ F x)
  (Hgen : ∀ (x y : G) (e : edges x y),
      hom_cast (Hobj x) (Hobj y) (fmap[K] (pgen e))
        ≈ @fedgemap _ _ F x y e) :
  ∀ (x y : G) (f : x ~{PresentedQuiver}~> y),
    hom_cast (Hobj x) (Hobj y) (fmap[K] f) ≈ fmap[PresentedFunctor] f.
Proof.
  intros x y f.
  induction f.
  - change (@tnil _ _ y) with (@id PresentedQuiver y).
    rewrite fmap_id. simpl. rewrite hom_cast_id. reflexivity.
  - assert (RW : @equiv (@hom PresentedQuiver i y) _ (b ::: f)
                   (@compose PresentedQuiver _ _ _ f (pgen b))).
    { unfold pgen, tlist_singleton. simpl.
      apply cc_equiv. simpl. now rewrite <- tlist_app_cons. }
    rewrite RW, fmap_comp.
    rewrite <- (hom_cast_comp (Hobj i) (Hobj j) (Hobj y)).
    rewrite IHf, Hgen.
    now rewrite fmap_comp, PresentedFunctor_gen.
Qed.

(*
   * *** The converse leg

   Restricting a functor out of the presented category along the unit
   gives back a quiver homomorphism, and that homomorphism automatically
   satisfies the relations.  This is what makes Riehl's “exactly” honest
   in both directions. 

   --------
   * *** 共轭腿

   沿着单位限制从所呈现的范畴出的函子
   会返回一个弦图同态，并且该同态自动满足关系。这正是使 Riehl 的“完全”在两个方向上都是诚信的原因。
*)

Section Restrict.

Context (S : PresentedQuiver ⟶ D).

(** The quiver homomorphism underlying [S]. / [S] 所基于的箭袋同态。 *)
Definition presented_restrict : QuiverHomomorphism G (QuiverOfCat D) :=
  QuiverComp (UnitQuiverCatAdjunction G)
    (QuiverHomomorphismOfFunctor _ _ (S ◯ PresentedQuiverProj)).

(*
   * On generators the restriction is [S] itself, definitionally — a
   Leibniz equality of morphisms, stated at that strength deliberately,
   in the manner of [QuotientLift_proj] ([Construction/Quotient.v]). 

   --------
   * 在生成元上，限制本身就是 [S]，从定义上来说——这是一个态射的 Leibniz 等式，以那种强度故意陈述，方式类似于 [QuotientLift_proj]（[Construction/Quotient.v]）。
*)
Lemma presented_restrict_gen {x y : G} (e : edges x y) :
  @fedgemap _ _ presented_restrict x y e = fmap[S] (pgen e).
Proof. reflexivity. Qed.

(*
   * The functor induced by the restriction agrees with [S] on every
   path. 

   --------
   * 由限制引起的函子在每一条路径上都与 [S] 一致。
*)
Lemma presented_restrict_induced {a b : G}
  (u : a ~{FreeOnQuiver G}~> b) :
  fmap[InducedFunctor G presented_restrict] u ≈ fmap[S] u.
Proof.
  induction u; simpl.
  - now rewrite fmap_id.
  - transitivity (fmap[S] u ∘ fmap[S] (pgen b0)).
    + apply compose_respects; [ exact IHu | reflexivity ].
    + rewrite <- fmap_comp. apply fmap_respects.
      unfold pgen, tlist_singleton; simpl.
      apply cc_equiv; simpl. now rewrite <- tlist_app_cons.
Qed.

(*
   * Every functor out of the presented category merges [R] automatically —
   the converse of the merging hypothesis [HF]. 

   --------
   * 从所展示的范畴出的每个函子都会自动合并 [R]——合并假设 [HF] 的逆命题。
*)
Lemma presented_restrict_satisfies {x y : G}
  {p q : x ~{FreeOnQuiver G}~> y} (Hr : R x y p q) :
  fmap[InducedFunctor G presented_restrict] p
    ≈ fmap[InducedFunctor G presented_restrict] q.
Proof.
  transitivity (fmap[S] p); [ exact (presented_restrict_induced p) | ].
  transitivity (fmap[S] q);
    [ exact (@fmap_respects _ _ S x y p q (cc_gen Hr))
    | symmetry; exact (presented_restrict_induced q) ].
Qed.

End Restrict.

End PresentedUMP.

End Presentation.

