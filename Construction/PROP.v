(*
   *
   A PROP, in the sense of MacLane and the modern PROP/operad literature,
   is a strict symmetric monoidal category whose objects are the natural
   numbers and whose tensor on objects is addition:

   I = 0,    m ⨂ n = m + n.

   The object set is therefore the free monoid [(ℕ, +, 0)] on one
   generator — discrete AS AN OBJECT SET — while the hom-sets carry the
   rich symmetric monoidal structure; in particular each symmetric group
   [S_n] embeds into [PROP(n, n)], and every PROP receives a canonical
   strict symmetric monoidal functor from the free PROP of permutations.

   In this library's setoid-based, universe-polymorphic setting, we do not
   assert [obj prop_cat = nat] directly; instead we supply a naming function
   [prop_of_nat : nat -> obj] together with the strictness equalities

   prop_unit_zero    : I = prop_of_nat 0
   prop_tensor_plus  : prop_of_nat m ⨂ prop_of_nat n = prop_of_nat (m + n)

   These bind the monoidal structure to the additive monoid on ℕ at the
   Leibniz level — which is exactly what makes strict-monoidal arguments
   on PROPs work.  (Non-strict monoidal “weak PROPs” would weaken these to
   isomorphisms; the literature uniformly takes strict.)

   Downstream applications — Frobenius PROPs, hypergraph PROPs, the ZX
   PROP — refine [PROP] with extra structure on each object. 

   --------
   *
   PROP，在 MacLane 以及现代 PROP/operad 文献中的定义,
   是一个严格对称单体范畴，其对象是自然数，并且对象上的张量是加法：

   I = 0,    m ⨂ n = m + n。

   因此，对象集合是单个生成元的自由幺半群 [(ℕ, +, 0)] — 作为一个对象集合是离散的 — 而态射集合则承载丰富的对称单体结构；特别地，每个对称群 [S_n] 嵌入到 [PROP(n, n)] 中，并且每个 PROP 都接收来自置换自由 PROP 的一个规范严格对称单体函子。

   在这个库的基于等值集、宇宙多态的环境中，我们不直接断言 [obj prop_cat = nat]；相反，我们提供一个命名函数 [prop_of_nat : nat -> obj] 以及严格性等式prop_unit_zero    : I = prop_of_nat 0
   prop_tensor_plus  : prop_of_nat m ⨂ prop_of_nat n = prop_of_nat (m + n)

   这些将 monoidal 结构绑定到 ℕ 上的加法幺半群在 Leibniz 层面——这正是使得 PROPs 上的严格单体论证成立的原因。（非严格单体“弱 PROP”会将这些弱化为同构；文献中统一采用严格的。）

   下游应用——Frobenius PROP、超图 PROP、ZX PROP——通过在每个对象上增加额外结构来细化 [PROP]。
*)

(*
   * ** The PROP class

   Bundles a category, its strict symmetric monoidal structure, and the
   object correspondence with [nat].  The object correspondence is given
   by [prop_of_nat : nat -> obj], with [prop_unit_zero] / [prop_tensor_plus]
   pinning down [I] and [(⨂)] on objects.

   Note that this class does NOT assert the full “objects are exactly ℕ”
   condition — namely that [prop_of_nat] is a bijection on objects.  Omitting
   it captures the relaxed “PROP-like” notion (a strict symmetric monoidal
   category whose object monoid is generated by ℕ, containing the free PROP
   of permutations as a sub-PROP), which Wikipedia notes “is often relaxed”
   to in practice.  A consumer needing strict surjectivity-on-objects can
   bundle [PROP] with the extra hypothesis. 

   --------
   * ** PROP 类

   打包一个范畴、其严格对称幺半群结构，以及与 [nat] 的对象对应关系。对象对应关系由 [prop_of_nat : nat -> obj] 给出，其中 [prop_unit_zero] / [prop_tensor_plus] 确定对象上的 [I] 和 [(⨂)]。

   请注意，该类并未断言完整的“对象恰好是 ℕ”条件——即 [prop_of_nat] 在对象上的双射性质。省略该条件能够捕捉放宽的“类似 PROP”的概念（一个严格对称幺半群范畴，其对象单半群由 ℕ 生成，并包含作为子-PROP 的自由排列 PROP），维基百科指出，这种定义在实际中“通常是放宽的”。需要严格对象满射的使用者可以在附加假设下将 [PROP] 一并打包。
*)

Class PROP : Type := {
  prop_cat : Category;

  prop_strict : @StrictMonoidal prop_cat;
  prop_symmetric : @SymmetricMonoidal prop_cat;

  (*
   * Coherence between the two [Monoidal] paths through a PROP.
   [prop_strict] supplies a [Monoidal] via [strict_is_monoidal];
   [prop_symmetric] supplies one via
   [braided_is_monoidal ∘ symmetric_is_braided].  Without an axiom
   relating them, downstream tensor expressions resolve
   ambiguously.  We require these to be EQUAL as [Monoidal]
   records:

   [prop_monoidal_coherence] :
   [strict_is_monoidal prop_strict
   = braided_is_monoidal (symmetric_is_braided prop_symmetric)]

   so a [rewrite] (or [subst]) brings any term phrased via one path
   into agreement with the other.

   ** Known limitation (deferred refactor)

   This coherence is PROPOSITIONAL, not DEFINITIONAL: a tensor
   expression like [braid : (T ⨂ T) ~> (T ⨂ T)] in a [HypergraphPROP]
   context typically resolves [T ⨂ T] via [prop_symmetric]'s
   Monoidal, while the hypergraph SCFA on [T ⨂ T] is phrased via
   [prop_strict]'s.  Bridging requires an explicit
   [rewrite prop_monoidal_coherence] (or [subst]) at every use
   site.  See [Test/HypergraphPROPResolution.v] for the test case
   that documents this friction.

   The literature-correct DEFINITIONAL fix is to re-parameterise the
   library's [BraidedMonoidal] and [SymmetricMonoidal] classes to
   take an [@Monoidal C] as an explicit parameter rather than
   projecting one (similar to how [DepFun] takes its source
   explicitly).  That would let [prop_symmetric] inherit
   [strict_is_monoidal prop_strict] verbatim, making
   [prop_monoidal_coherence] reduce to [eq_refl] definitionally.

   This is a multi-file library refactor (touches every site that
   uses [BraidedMonoidal]/[SymmetricMonoidal] today) and is
   deferred to a separate PR. 

   --------
   * 通过 PROP 的两个 [Monoidal] 路径之间的一致性。  
   [prop_strict]  通过 [strict_is_monoidal] 提供一个 [Monoidal]；  
   [prop_symmetric]  通过 [braided_is_monoidal ∘ symmetric_is_braided] 提供一个。没有一个相关的公理，  
   下游的张量表达式会产生歧义。我们需要它们相等，正如 [Monoidal] 记录的：

   [prop_monoidal_coherence] ：
   [strict_is_monoidal prop_strict
   = braided_is_monoidal (symmetric_is_braided prop_symmetric)]

   因此 [rewrite]（或 [subst]）可以将通过一种路径表达的任何项  
   与另一种路径一致。

   ** 已知限制（推迟重构）这种相干性是命题性的，而不是定义性的：像  [braid : (T ⨂ T) ~> (T ⨂ T)]  这样的张量表达在  [HypergraphPROP]  上下文中通常通过  [prop_symmetric] 的幺半群来解析  [T ⨂ T] ，而 [T ⨂ T] 上的超图 SCFA 则是通过  [prop_strict] 来表述的。桥接在每个使用点都需要一个明确的  [rewrite prop_monoidal_coherence]（或 [subst]）。参见 [Test/HypergraphPROPResolution.v] 的测试用例，它记录了这种摩擦。

   在文献上正确的定义性解决方法是重新参数化库的  [BraidedMonoidal] 和 [SymmetricMonoidal] 类，使其将 [@Monoidal C] 作为显式参数，而不是投影一个（类似于 [DepFun] 明确地接收其源）。这将允许 [prop_symmetric] 照字面继承 [strict_is_monoidal prop_strict]，使 [prop_monoidal_coherence] 在定义上归约为 [eq_refl]。这是一个多文件库重构（涉及今天使用 [BraidedMonoidal] / [SymmetricMonoidal] 的每个站点），并被推迟到一个单独的合并请求中。
*)
  prop_monoidal_coherence :
    (@strict_is_monoidal prop_cat prop_strict)
    = (@braided_is_monoidal prop_cat
         (@symmetric_is_braided prop_cat prop_symmetric));

  (*
   * The canonical object correspondence: every natural number names an
   object of [prop_cat], with [0] the monoidal unit and addition
   reflecting tensor. 

   --------
   * 典范对象对应：每个自然数命名  [prop_cat] 的一个对象，其中 [0] 是单元对象，且加法对应于张量。
*)
  prop_of_nat : nat -> @obj prop_cat;

  prop_unit_zero :
    @I prop_cat (@strict_is_monoidal prop_cat prop_strict)
    = prop_of_nat 0;

  prop_tensor_plus : forall (m n : nat),
    ((prop_of_nat m) ⨂[@strict_is_monoidal prop_cat prop_strict]
     (prop_of_nat n))%object
    = prop_of_nat (m + n)
}.

#[export] Existing Instance prop_strict.
#[export] Existing Instance prop_symmetric.

Coercion prop_cat : PROP >-> Category.

(*
   * ** Smart accessors

   With [P : PROP], the canonical view sends every natural number to its
   PROP-object; in particular the tensor of [m] and [n] is literally the
   object named by [m + n].  Downstream files use these accessors to
   state PROP-morphism types as e.g. [prop_of_nat 2 ~{P}~> prop_of_nat 3]. 

   --------
   * ** 智能访问器

   使用 [P : PROP]，典范视图将每一个自然数发送到它的 PROP 对象；特别是 [m] 和 [n] 的张量在字面上就是由 [m + n] 命名的对象。下游文件使用这些访问器来声明 PROP-态射类型，例如 [prop_of_nat 2 ~{P}~> prop_of_nat 3]。
*)

Section PROPLemmas.

Context (P : PROP).

(*
   * The PROP-object [⟦n⟧] is the canonical object indexed by [n : nat]. 

   --------
   * PROP-对象 [⟦n⟧] 是由 [n : nat] 索引的典型对象。
*)
Notation "⟦ n ⟧" := (@prop_of_nat P n) (at level 0, format "⟦ n ⟧").

(** Sanity: the unit object of [P] is [⟦0⟧]. / 理智：[P] 的单位对象是 [[P]]。 *)
Lemma prop_I_eq_zero : @I P _ = ⟦0⟧.
Proof. exact prop_unit_zero. Qed.

(** Sanity: tensor on objects is addition. / 理智：对象上的张量是加法。 *)
Lemma prop_tensor_eq_plus (m n : nat) :
  (⟦m⟧ ⨂ ⟦n⟧)%object = ⟦m + n⟧.
Proof. exact (prop_tensor_plus m n). Qed.

(** Tensor of three PROP-objects collapses to the sum. / 三个PROP对象的张量坍缩为其和。 *)
Lemma prop_tensor_triple (m n p : nat) :
  ((⟦m⟧ ⨂ ⟦n⟧) ⨂ ⟦p⟧)%object = ⟦m + n + p⟧.
Proof.
  rewrite prop_tensor_plus.
  apply prop_tensor_plus.
Qed.

(** The unit object on the left of a tensor is absorbed. / 张量左边的单位对象被吸收。 *)
Lemma prop_tensor_unit_left_obj (n : nat) :
  (⟦0⟧ ⨂ ⟦n⟧)%object = ⟦n⟧.
Proof.
  rewrite prop_tensor_plus.
  reflexivity.
Qed.

(*
   * The unit object on the right of a tensor is absorbed, modulo [n + 0 = n]. 

   --------
   * 张量右侧的单位对象被吸收，模 [n + 0 = n] 。
*)
Lemma prop_tensor_unit_right_obj (n : nat) :
  (⟦n⟧ ⨂ ⟦0⟧)%object = ⟦n + 0⟧.
Proof. apply prop_tensor_plus. Qed.

(*
   * ** PROP-arity ergonomics

   The Leibniz equality [prop_tensor_plus : ⟦m⟧ ⨂ ⟦n⟧ = ⟦m+n⟧] is
   the right primitive, but using it to translate between the
   “single-object” view [⟦m+n⟧] and the “tensor of wires” view
   [⟦m⟧ ⨂ ⟦n⟧] is verbose at the use site.  The following helpers
   give downstream code a uniform way to flip between the two. 

   --------
   * ** PROP-arity 人体工学

   莱布尼茨等式 [prop_tensor_plus : ⟦m⟧ ⨂ ⟦n⟧ = ⟦m+n⟧] 是
   正确的原始方法，但在使用它在
   “单一对象”视图 [⟦m+n⟧] 和 “线张量”视图
   [⟦m⟧ ⨂ ⟦n⟧] 之间进行转换时，在使用地点显得冗长。以下辅助工具
   为下游代码提供了一种统一的方式在两者之间切换。
*)

Open Scope nat_scope.

(*
   * Iterated tensor of [n] copies of [⟦1⟧], starting from [I]. 

   --------
   * 从  [I] 开始，对 [[⟦1⟧]] 的 [n] 拷贝进行迭代张量。
*)
Fixpoint iter_tensor (n : nat) : @obj P :=
  match n with
  | O    => @I P _
  | S n' => (@prop_of_nat P 1 ⨂ iter_tensor n')%object
  end.

(*
   * Every PROP object [⟦n⟧] is Leibniz-equal to [iter_tensor n].

   Base: [⟦0⟧ = I] by [prop_unit_zero].
   Step: [⟦S n⟧ = ⟦1 + n⟧ = ⟦1⟧ ⨂ ⟦n⟧ = ⟦1⟧ ⨂ iter_tensor n] by IH. 

   --------
   * 每个 PROP 对象 [⟦n⟧] 都是 Leibniz 相等于 [iter_tensor n] 。

   基础：[[⟦n⟧] = I] 由 [prop_unit_zero]。
   步骤：[⟦S n⟧ = ⟦1 + n⟧ = [iter_tensor n] ⨂ ⟦n⟧ = [iter_tensor n] ⨂ iter_tensor n] 由 IH。
*)
Lemma prop_of_nat_iter : forall n, @prop_of_nat P n = iter_tensor n.
Proof.
  induction n; cbn.
  - exact (eq_sym (@prop_unit_zero P)).
  - rewrite <- IHn.
    exact (eq_sym (@prop_tensor_plus P 1 n)).
Qed.

(** The successor decomposition: [⟦S n⟧ = ⟦1⟧ ⨂ ⟦n⟧]. / 后继分解：[⟦S n⟧ = ⟦1⟧ ⨂ ⟦n⟧]。 *)
Lemma prop_of_nat_S :
  forall n, @prop_of_nat P (S n)
            = (@prop_of_nat P 1 ⨂ @prop_of_nat P n)%object.
Proof. intro n. exact (eq_sym (@prop_tensor_plus P 1 n)). Qed.

Close Scope nat_scope.

End PROPLemmas.

(*
   * ** Hypergraph PROPs

   A hypergraph PROP is a PROP whose underlying symmetric monoidal category
   carries a [Hypergraph] instance.  This is the standard setting for the
   ZX-calculus, the calculus of relations, and Fong-style decorated cospans:
   every object [⟦n⟧] is equipped canonically with a special commutative
   Frobenius algebra, coherent under the tensor.

   Because [Hypergraph] is parameterised by [SymmetricMonoidal] and a PROP
   already carries [prop_symmetric], the class composes cleanly. 

   --------
   * ** 超图 PROP

   超图 PROP 是一种 PROP，其底层对称单体范畴具有 [Hypergraph] 实例。这是 ZX 演算、关系演算以及 Fong 风格装饰余锥的标准设置：每个对象 [⟦n⟧] 都自然配备一个特殊的交换 Frobenius 代数，并在张量下保持一致性。

   由于 [Hypergraph] 由 [SymmetricMonoidal] 参数化，并且一个 PROP 已经携带 [prop_symmetric]，该类可以干净地进行组合。
*)

Class HypergraphPROP : Type := {
  hpprop : PROP;

  hpprop_hyper : @Hypergraph
                   (@prop_cat hpprop)
                   (@prop_symmetric hpprop)
}.

#[export] Existing Instance hpprop_hyper.

Coercion hpprop : HypergraphPROP >-> PROP.

(*
   * ** Discussion: concrete PROP instances

   Three illustrative kinds of PROP instance:

   1. **Free PROP on a signature** ([Construction/PROP/Free.v]).
   Given a signature [S : Signature], the free PROP on [S] has
   morphisms [m ~> n] the equivalence classes of [Term S m n]
   under [TermEq].  [Construction/PROP/Free.v] delivers the
   underlying [Category] layer ([FreeCat S]) from the inductive
   [Term] datatype, and the successor files complete it to an
   actual [PROP]: the tensor functor ([Construction/PROP/Tensor.v]),
   the structural isomorphisms ([Construction/PROP/Structural.v])
   and their naturality lemmas ([Construction/PROP/Naturality.v]),
   the shared [Monoidal] record ([Construction/PROP/Monoidal.v])
   with its braided/symmetric/strict structure ([Braided.v] /
   [Symmetric.v] / [Strict.v]), and finally the bundled
   [FreePROP S : PROP] with definitional coherence
   ([Construction/PROP/Instance.v]), together with interpretation,
   the universal property, and presentations ([Interp.v],
   [Universal.v], [Presentation.v]).  See also
   [Construction/PROP/Term.v] for the syntax and
   [Construction/PROP/TermEq.v] for the quotient.

   2. **Permutation PROP** (literature canonical, not yet in the
   library).  Its morphisms [m ~> n] are nonempty exactly when
   [m = n], in which case they are the symmetric group [S_n] of
   permutations of [Fin n].  Building [Perm n] requires
   either an inductive presentation of permutations as a quotient
   of [list (Fin n × Fin n)] adjacency generators, or the
   bijection presentation [{ p : Fin n -> Fin n | bij p }] under
   extensional equality.  [Instance/FinSet.v] now supplies part of
   the finite-combinatorics substrate (skeletal [FinSet] with
   computable coproducts and a [Fin.t] case-analysis toolkit), but
   the permutation subcategory [Perm n] itself remains unbuilt;
   downstream consumers needing [Perm n] morphisms supply their
   own datatype while retaining all theorems proven against the
   [PROP] class.

   3. **Trivial / discrete-thin PROP** (the terminal PROP).  Objects
   are [nat], every hom-set is a singleton (the unique morphism is
   an [m = n] equality proof).  Equipping this with full [PROP]
   structure ([StrictMonoidal] + [SymmetricMonoidal] +
   [prop_monoidal_coherence] + the [prop_of_nat] / [prop_unit_zero]
   / [prop_tensor_plus] data) is mechanical but volumetric.  It
   is omitted from this file since it adds no theoretical content
   beyond what the [PROP] class already specifies; should a
   downstream test need it, a minimal stub-instance can be
   inhabited per-test. 

   --------
   * ** 讨论：具体的 PROP 实例

   PROP 实例的三种说明性类型：1. **在一个签名上的自由PROP**（[Construction/PROP/Free.v]）。给定一个签名[S : Signature]，在[S]上的自由PROP具有态射[m ~> n]，它们是[Term S m n]在[TermEq]下的等价类。[Construction/PROP/Free.v] 提供了诱导 [Term] 数据类型的底层 [Category] 层（[FreeCat S]），而后续文件将其补充完整为实际的 [PROP]：张量范畴（[Construction/PROP/Tensor.v]）、结构同构（[Construction/PROP/Structural.v]）及其自然性引理（[Construction/PROP/Naturality.v]）、带有编织/对称/严格结构（[Braided.v] / [Symmetric.v] / [Strict.v]）的共享 [Monoidal] 记录（[Construction/PROP/Monoidal.v]），最终还有具有定义一致性的捆绑 [FreePROP S : PROP]（[Construction/PROP/Instance.v]），以及解释、普适性质和表示（[Interp.v]、[Universal.v]、[Presentation.v]）。另请参见 [Construction/PROP/Term.v] 了解语法，参见 [Construction/PROP/TermEq.v] 了解商。2. **置换 PROP**（文献中的规范写法，尚未在库中）。它的态射 [m ~> n] 当且仅当 [m = n] 非空，在这种情况下它们是 [Fin n] 的置换的对称群 [S_n]。构建 [Perm n] 需要使用置换的归纳表示法，将其表示为 [list (Fin n × Fin n)] 邻接生成元的商，或者使用扩展相等下的双射表示法 [{ p : Fin n -> Fin n | bij p }]。[Instance/FinSet.v] 现在提供有限组合底层（骨架 [FinSet]，具有可计算的直积和 [Fin.t] 的案例分析工具包），但置换子范畴 [Perm n] 本身仍未构建；下游需要 [Perm n] 单射的使用者提供自己的数据类型，同时保留对 [PROP] 类证明的所有定理。3. **平凡 / 离散-薄 PROP**（终端 PROP）。对象是 [nat]，每个 Hom 集是单例（唯一的态射是 [m = n] 的等式证明）。为其配备完整的 [PROP] 结构（[StrictMonoidal] + [SymmetricMonoidal] + [prop_monoidal_coherence] + [prop_of_nat] / [prop_unit_zero] / [prop_tensor_plus] 数据）是机械性的，但体积大。在此文件中被省略，因为它没有超出 [PROP] 类已经指定的理论内容；如果下游测试需要它，可以按测试为单位填充一个最小的模板实例。
*)
