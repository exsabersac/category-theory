 对称单值理论（一个 [SMT]）是一个符号 [Σ] ，再加上一族在匹配元数的 [Σ] 项之间的方程。
 它所呈现的 PROP 是 [Σ] 上的自由 PROP，进一步通过这些方程生成的合同被商化——正如由生成元和关系呈现的单子是由关系合同商化的自由单子一样。经典例子：交换单子理论呈现有限集及其函数的 PROP；特殊交换 Frobenius 代数理论呈现有限集余积的 PROP。

 具体来说，这个文件为理论 [E : SMT] 关于 [Σ := smt_sig E] 构建：-  [TermEqW E]，[Prop] 值的 [Term Σ] 上的合同，由自由方程 [TermEq Σ] 生成，连同公理 [smt_eqs E]（六个构造器：嵌入、公理、对称性、传递性，以及两个组合合同——反身性通过 [TE_refl] 的嵌入继承）；
 -  [PresentedCat E]，由 [FreeCat Σ] 通过 [TermEqW E] 商得，通过 [Construction/Quotient.v] 的全通用商工具包；
