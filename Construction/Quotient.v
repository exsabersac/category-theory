(*
   * * Quotient categories, and transport along object equalities

   nLab: https://ncatlab.org/nlab/show/quotient+category
   Wikipedia: https://en.wikipedia.org/wiki/Quotient_category

   This file is fully general — it never mentions any concrete category —
   and provides three kits, layered rather than independent, reusable by
   any construction that
   quotients a syntactic category or reasons about Leibniz-strict object
   equalities:

   (a) a transport kit for categories in which certain objects are related
   by Leibniz equality [=] (as happens in strict monoidal categories):
   the transported identities [id_cast]/[hom_cast] and their algebra,
   the [ObjDecEq] class giving axiom-free uniqueness of identity proofs
   on objects, and the [HomEqProp] class reflecting the hom-setoid
   equivalence into [Prop];

   (b) the quotient of an arbitrary category by a hom-congruence, whose
   relation family may be [Prop]-valued ([HomRel], as the syntactic
   layers use it) or [Type]-valued ([HomRelT], as a generated
   congruence must be): the quotient [Category] itself, the
   identity-on-objects projection functor, transfer of isomorphisms,
   the lifting universal property, and descent of bifunctors;

   (c) the least congruence generated by an arbitrary hom-relation,
   together with Mac Lane §II.8 Proposition 1 — the quotient by that
   closure, its projection, and the factorization of any functor
   merging the generating relation. 

   --------
   * * 商类，以及沿对象等式的迁移

   nLab:  https://ncatlab.org/nlab/show/quotient+category 
   维基百科:  https://en.wikipedia.org/wiki/Quotient_category 

   这个文件是完全通用的——它从未提及任何具体的范畴——
   并提供三个工具包，这些工具包是分层的而非独立的，可由任何构造复用，
   这些构造对语法范畴进行商运算或推导莱布尼茨严格对象等式：

   (a) 一个范畴迁移工具包，其中某些对象由莱布尼茨等式 [=] 关联（如在严格单体范畴中发生的情况）：
   被迁移的恒等式 [id_cast] / [hom_cast] 及其代数，
   [ObjDecEq] 类提供了对象上恒等证明的无公理唯一性，
   以及 [HomEqProp] 类将同态集等价关系反映到 [Prop]；(b) 任意范畴关于一个同态合同的商，其关系族可以是 [Prop] 值（[HomRel]，就语法层使用它而言）或者 [Type] 值（[HomRelT]，因为生成的合同必须如此）：商 [Category] 本身、对象恒等的投影函子、同构的传递、提升的普遍性质以及双函子的下行性质；

   (c) 由任意同态关系生成的最小合同，以及 Mac Lane §II.8 命题 1 —— 对该闭包的商、它的投影，以及任何合并生成关系的函子的分解。
*)

(*
   * ** The [id_cast]/[hom_cast] transport kit

   [id_cast e] is the identity morphism transported along an object-level
   Leibniz equality [e : x = y].  It is deliberately spelled with the same
   [match e in _ = T return x ~> T with eq_refl => id end] shape as the
   [strict_*_to] fields of [Structure/Monoidal/Strict.v] and the
   [strict_pure_iso_id]/[strict_ap_iso_id] fields of
   [Functor/Structure/Monoidal/Strict.v], so those fields read as
   [to φ ≈ id_cast e] without any unfolding. 

   --------
   * ** [id_cast] / [hom_cast] 传输工具包

   [id_cast e] 是沿着对象层级的 Leibniz 等式 [e : x = y] 传输的同一映射。它故意与 [Structure/Monoidal/Strict.v] 的 [strict_*_to] 字段以及 [Functor/Structure/Monoidal/Strict.v] 的 [strict_pure_iso_id] / [strict_ap_iso_id] 字段拼写成相同的 [match e in _ = T return x ~> T with eq_refl => id end] 形状，因此那些字段在不展开的情况下读取为 [to φ ≈ id_cast e]。
*)

Section HomCast.

Context {C : Category}.

(** The identity morphism, transported along an object equality. / 沿着对象相等性传递的恒等同态。 *)
Definition id_cast {x y : C} (e : x = y) : x ~> y :=
  match e in _ = T return x ~> T with eq_refl => id end.

(** At [eq_refl], the cast is the literal identity. / 在 [eq_refl]，类型转换就是字面上的身份。 *)
Lemma id_cast_refl {x : C} : id_cast (@eq_refl _ x) = id.
Proof. reflexivity. Qed.

(*
   * Composing two casts gives the cast along the composite equality. 

   --------
   * 组合两个类型转换得到沿复合等式的类型转换。
*)
Lemma id_cast_trans {x y z : C} (e1 : x = y) (e2 : y = z) :
  id_cast e2 ∘ id_cast e1 ≈ id_cast (eq_trans e1 e2).
Proof. destruct e2, e1; cat. Qed.

(*
   * Casting along [e] and back along [eq_sym e] is the identity. 

   --------
   * 沿 [e] 投射，再沿 [eq_sym e] 返回，是恒等映射。
*)
Lemma id_cast_inv_l {x y : C} (e : x = y) :
  id_cast (eq_sym e) ∘ id_cast e ≈ id.
Proof. destruct e; cat. Qed.

Lemma id_cast_inv_r {x y : C} (e : x = y) :
  id_cast e ∘ id_cast (eq_sym e) ≈ id.
Proof. destruct e; cat. Qed.

(*
   * Solve [f ≈ g ∘ cast⁻¹] from [f ∘ cast ≈ g]. 

   --------
   * 从 [f ∘ cast ≈ g] 求解 [f ≈ g ∘ cast⁻¹]。
*)
Lemma comp_cast_shift {x y z : C} (e : x = y) (f : y ~> z) (g : x ~> z) :
  f ∘ id_cast e ≈ g → f ≈ g ∘ id_cast (eq_sym e).
Proof.
  intros Hf.
  rewrite <- Hf.
  rewrite <- comp_assoc.
  rewrite id_cast_inv_r.
  now rewrite id_right.
Qed.

(** Nested cast conjugations fuse along [eq_trans]. / 嵌套的转换共轭沿 [eq_trans] 融合。 *)
Lemma id_cast_conj_fuse {x y x' y' x'' y'' : C}
  (e1 : x = x') (e2 : y = y') (d1 : x' = x'') (d2 : y' = y'')
  (f : x ~> y) :
  id_cast d2 ∘ (id_cast e2 ∘ f ∘ id_cast (eq_sym e1)) ∘ id_cast (eq_sym d1)
    ≈ id_cast (eq_trans e2 d2) ∘ f ∘ id_cast (eq_sym (eq_trans e1 d1)).
Proof. destruct e1, e2, d1, d2; cat. Qed.

(*
   * Leibniz-equal objects are in particular isomorphic, via the casts. 

   --------
   * 莱布尼茨相等的对象尤其是同构的，通过类型转换。
*)
Definition id_cast_iso {x y : C} (e : x = y) : x ≅ y := {|
  to := id_cast e;
  from := id_cast (eq_sym e);
  iso_to_from := id_cast_inv_r e;
  iso_from_to := id_cast_inv_l e
|}.

(*
   * A whole morphism transported along equalities on both endpoints. 

   --------
   * 一个整体态射沿着两个端点的等式被传送。
*)
Definition hom_cast {x y x' y' : C} (ex : x = x') (ey : y = y')
  (f : x ~> y) : x' ~> y' :=
  match ey in _ = b return x' ~> b with eq_refl =>
    match ex in _ = a return a ~> y with eq_refl => f end end.

(*
   * At [eq_refl] on both ends, the cast is the morphism itself. 

   --------
   * 在 [eq_refl] 的两端，类型转换就是态射本身。
*)
Lemma hom_cast_refl {x y : C} (f : x ~> y) :
  hom_cast eq_refl eq_refl f = f.
Proof. reflexivity. Qed.

(*
   * A [hom_cast] is conjugation by the endpoint [id_cast]s. 

   --------
   * A  [hom_cast] 是通过端点 [id_cast] 的共轭。
*)
Lemma hom_cast_decompose {x y x' y' : C} (ex : x = x') (ey : y = y')
  (f : x ~> y) :
  hom_cast ex ey f ≈ id_cast ey ∘ f ∘ id_cast (eq_sym ex).
Proof. destruct ex, ey; cat. Qed.

(*
   * Casting the identity along the same equality twice is the identity. 

   --------
   * 沿着同一个等式两次施加恒等映射就是恒等映射。
*)
Lemma hom_cast_id {x x' : C} (e : x = x') : hom_cast e e id ≈ id.
Proof. destruct e; cat. Qed.

(*
   * Casts fuse across composition when the middle equalities agree. 

   --------
   * 当中间的等式一致时，将保险丝投射到组合上。
*)
Lemma hom_cast_comp {x y z x' y' z' : C}
  (ex : x = x') (ey : y = y') (ez : z = z')
  (g : y ~> z) (f : x ~> y) :
  hom_cast ey ez g ∘ hom_cast ex ey f ≈ hom_cast ex ez (g ∘ f).
Proof. destruct ex, ey, ez; cat. Qed.

(** Casting there and back is the identity operation. / 在那里投掷然后返回是恒等操作。 *)
Lemma hom_cast_roundtrip {x y x' y' : C} (ex : x = x') (ey : y = y')
  (f : x' ~> y') :
  hom_cast ex ey (hom_cast (eq_sym ex) (eq_sym ey) f) = f.
Proof. destruct ex, ey; reflexivity. Qed.

(** [hom_cast] respects the hom-setoid equivalence. / [hom_cast] 尊重同态集合等价。 *)
#[export] Instance hom_cast_respects {x y x' y' : C}
  (ex : x = x') (ey : y = y') :
  Proper (equiv ==> equiv) (@hom_cast x y x' y' ex ey).
Proof. destruct ex, ey; repeat intro; assumption. Qed.

End HomCast.

(*
   * Functors take [id_cast e] to [id_cast (f_equal F e)].  This is the
   [id_cast]-phrased sibling of [fmap_match_id] from
   [Functor/Structure/Monoidal/Strict.v]; it is reproved here (one line)
   to keep this root file independent of the monoidal-functor stack. 

   --------
   * 函子将 [id_cast e] 映射到 [id_cast (f_equal F e)]。这是 [id_cast] 表达方式下的 [fmap_match_id] 的同类，从 [Functor/Structure/Monoidal/Strict.v] 得到；这里重新证明（仅一行），以保持此根文件独立于单子函子堆栈。
*)
Lemma fmap_id_cast {C D : Category} (F : C ⟶ D) {x y : C} (e : x = y) :
  fmap[F] (id_cast e) ≈ id_cast (f_equal F e).
Proof. destruct e; apply fmap_id. Qed.

(*
   * ** Decidable object equality gives axiom-free UIP

   When the objects of [C] have decidable Leibniz equality, uniqueness of
   identity proofs holds for them without any axiom, by
   [Eqdep_dec.UIP_dec].  This is the target-side mirror of the
   proof-irrelevance results available on syntactic categories with [nat]
   objects, and it makes every [id_cast]/[hom_cast] independent of the
   particular equality proof used. 

   --------
   * ** 可判定对象相等性提供无公理的 UIP

   当 [C] 的对象具有可判定的莱布尼茨相等性时，它们的身份证明的唯一性在没有任何公理的情况下成立，由 [Eqdep_dec.UIP_dec] 提供。这是可获得在具有 [nat] 对象的句法范畴上的证明无关性的目标端镜像，它使每个 [id_cast] / [hom_cast] 独立于所使用的具体相等性证明。
*)

Class ObjDecEq (C : Category) : Type :=
  obj_eq_dec : ∀ x y : obj[C], {x = y} + {x ≠ y}.

(** Uniqueness of identity proofs on objects, with no axioms. / 对象的身份证明的唯一性，无需公理。 *)
Lemma obj_uip {C : Category} `{@ObjDecEq C} {x y : C} (e1 e2 : x = y) :
  e1 = e2.
Proof. exact (UIP_dec obj_eq_dec e1 e2). Qed.

(*
   * [id_cast] does not depend on the choice of equality proof. 

   --------
   * [id_cast] 不依赖于等式证明的选择。
*)
Lemma id_cast_irr {C : Category} `{@ObjDecEq C} {x y : C} (e1 e2 : x = y) :
  id_cast e1 = id_cast e2.
Proof. rewrite (obj_uip e1 e2); reflexivity. Qed.

(*
   * Any cast along a loop equality [e : x = x] is the identity. 

   --------
   * 沿着循环等式 [e : x = x] 的任何投射都是恒等映射。
*)
Lemma id_cast_loop {C : Category} `{@ObjDecEq C} {x : C} (e : x = x) :
  id_cast e = id.
Proof. rewrite (obj_uip e eq_refl); reflexivity. Qed.

(*
   * Conjugation along different proofs of the same equalities agrees. 

   --------
   * 对相同等式的不同证明进行结合是相一致的。
*)
Lemma id_cast_conj_irr {C : Category} `{@ObjDecEq C} {x y x' y' : C}
  (p1 q1 : x = x') (p2 q2 : y = y') (f : x ~> y) :
  id_cast p2 ∘ f ∘ id_cast (eq_sym p1)
    ≈ id_cast q2 ∘ f ∘ id_cast (eq_sym q1).
Proof. rewrite (obj_uip p1 q1), (obj_uip p2 q2); reflexivity. Qed.

(*
   * [hom_cast] does not depend on the choice of equality proofs. 

   --------
   *  [hom_cast] 不依赖于等式证明的选择。
*)
Lemma hom_cast_irr {C : Category} `{@ObjDecEq C} {x y x' y' : C}
  (e1 e1' : x = x') (e2 e2' : y = y') (f : x ~> y) :
  hom_cast e1 e2 f = hom_cast e1' e2' f.
Proof. rewrite (obj_uip e1 e1'), (obj_uip e2 e2'); reflexivity. Qed.

(*
   * Casting a morphism along loop equalities is the morphism itself. 

   --------
   * 沿着环等式投射一个态射就是该态射本身。
*)
Lemma hom_cast_loop {C : Category} `{@ObjDecEq C} {x y : C}
  (e1 : x = x) (e2 : y = y) (f : x ~> y) :
  hom_cast e1 e2 f = f.
Proof. rewrite (obj_uip e1 eq_refl), (obj_uip e2 eq_refl); reflexivity. Qed.

(*
   * *** The strict functor-equality reading of a [hom_cast] conjugation

   Conjugating by [hom_cast] along Leibniz object equalities is exactly the
   data of [Functor_StrictEq_Setoid] ([Theory/Functor.v]), the hom-setoid
   of [StrictCat], modulo the [hom_cast] ↔ [transport]/[transport_r]
   reshuffle.  The three lemmas below make that reading available in both
   directions, so a uniqueness statement phrased with [hom_cast] — such as
   [QuotientLift_unique] below — is legible as an equality of functors in
   [StrictCat] with nothing further to prove. 

   --------
   * *** [hom_cast] 共轭的严格函子等式解读

   沿着 Leibniz 对象等式进行 [hom_cast] 共轭，正是 [Functor_StrictEq_Setoid]（[Theory/Functor.v]）的数据，即 [StrictCat] 的同态集合，并考虑 [hom_cast] ↔ [transport] / [transport_r] 的重排。下面的三个引理使该解读在两个方向上都可用，因此用 [hom_cast] 表述的唯一性命题——如下面的 [QuotientLift_unique]——可以作为 [StrictCat] 中函子等式来理解，无需进一步证明。
*)

(*
   * The reshuffle itself, both directions, by [destruct] on the endpoint
   equalities. 

   --------
   * 重组本身，无论方向，由 [destruct] 在端点等式上进行。
*)
Lemma hom_cast_transport_iff {D : Category} {a b a' b' : D}
  (ex : a = a') (ey : b = b') (f : a ~> b) (g : a' ~> b') :
  ((hom_cast ex ey f ≈ g) →
     (Logic.transport (fun z => hom a z) ey f
        ≈ Logic.transport_r (fun z => hom z b') ex g)) *
  ((Logic.transport (fun z => hom a z) ey f
      ≈ Logic.transport_r (fun z => hom z b') ex g) →
     (hom_cast ex ey f ≈ g)).
Proof. destruct ex, ey; split; intro; assumption. Qed.

(*
   * A [hom_cast]-conjugated agreement of two functors IS their equality in
   [StrictCat]. 

   --------
   * 两个函子的 [hom_cast]-结合一致性 在 [StrictCat] 中就是它们的相等。
*)
Lemma strict_of_hom_cast {C D : Category} (F G : C ⟶ D)
  (Hobj : ∀ x, fobj[F] x = fobj[G] x)
  (H : ∀ x y (f : x ~> y),
      hom_cast (Hobj x) (Hobj y) (fmap[F] f) ≈ fmap[G] f) :
  @equiv _ (@Functor_StrictEq_Setoid C D) F G.
Proof.
  exists Hobj. intros x y f.
  exact (fst (hom_cast_transport_iff (Hobj x) (Hobj y)
                (fmap[F] f) (fmap[G] f)) (H x y f)).
Qed.

(*
   * ...and conversely, an equality of functors in [StrictCat] yields the
   object equalities together with the [hom_cast]-conjugated agreement. 

   --------
   * …相反地，[StrictCat] 中函子的一致性会产生对象的一致性，同时伴随 [hom_cast]-共轭的一致性。
*)
Lemma hom_cast_of_strict {C D : Category} (F G : C ⟶ D)
  (E : @equiv _ (@Functor_StrictEq_Setoid C D) F G) :
  { Hobj : ∀ x, fobj[F] x = fobj[G] x &
      ∀ x y (f : x ~> y),
        hom_cast (Hobj x) (Hobj y) (fmap[F] f) ≈ fmap[G] f }.
Proof.
  destruct E as [Hobj Hmor].
  exists Hobj. intros x y f.
  exact (snd (hom_cast_transport_iff (Hobj x) (Hobj y)
                (fmap[F] f) (fmap[G] f)) (Hmor x y f)).
Qed.

(*
   * ** [Prop]-reflected hom equivalence

   The hom-setoid equivalence [≈] of this library is [Type]-valued (it is
   a [crelation]; see [Lib/Setoid.v]).  A [Prop]-valued inductive with two
   or more constructors — such as the term congruence of a syntactic
   category — cannot be eliminated into that [Type]-valued [≈] of an
   abstract target category: the elimination restriction on [Prop] blocks
   the induction.  Soundness inductions therefore land in a [Prop]-valued
   reflection [heq] of the hom equivalence and round-trip through
   [heq_intro]/[heq_elim].

   No [Equivalence] field is required: reflexivity, symmetry and
   transitivity of [heq] all follow by round-tripping through [≈]. 

   --------
   * ** [Prop] - 反射同态等价

   这个库的同态集合等价 [≈] 是 [Type] 值（它是一个 [crelation]；参见 [Lib/Setoid.v]）。一个具有两个或更多构造函数的 [Prop] 值归纳——例如语法类别的项同余——不能被消解到抽象目标类别的 [Type] 值的 [≈] 中：[Prop] 的消解限制阻止了归纳。因此，正确性归纳会落在同态等价的 [Prop] 值的反射 [heq] 中，并通过 [heq_intro] / [heq_elim] 进行往返。

   不需要 [Equivalence] 字段：[heq] 的自反性、对称性和传递性都可以通过往返 [≈] 来得到。
*)

Class HomEqProp (C : Category) : Type := {
  heq : ∀ {x y : C}, (x ~> y) → (x ~> y) → Prop;
  heq_intro : ∀ {x y : C} {f g : x ~> y}, f ≈ g → heq f g;
  heq_elim : ∀ {x y : C} {f g : x ~> y}, heq f g → f ≈ g
}.

(*
   * ** Quotient by a hom-congruence

   [HomRel] is the [Prop]-valued relation family, and it remains the shape
   the syntactic term congruences of [Construction/PROP/Presentation.v]
   and [Construction/ColouredPROP/Presentation.v] use.

   [HomRelT] is the general [Type]-valued family, and [HomRel] embeds into
   it by [Prop ⊆ Type] cumulativity, so the congruence class and the
   quotient below are stated over [HomRelT] and every [Prop]-valued client
   is accepted unchanged.

   A [Type]-valued family can serve directly as the quotient's hom-setoid
   equivalence, since [Setoid]'s [equiv] is itself a [crelation].

   [Quotient_HomEqProp] below stays pinned to a [Prop]-valued [R], because
   its [heq] field must land in [Prop].  That is why the [Prop] family
   keeps a name of its own, and why a quotient by a generated congruence
   (the last subsection of this file) carries no [HomEqProp] instance. 

   --------
   * ** 通过同态等价的商

   [HomRel] 是 [Prop] 值关系族，并保持了 [Construction/PROP/Presentation.v] 和 [Construction/ColouredPROP/Presentation.v] 的语法项同余所使用的形态。

   [HomRelT] 是一般的 [Type] 值族，[HomRel] 通过 [Prop ⊆ Type] 的累积嵌入其中，因此下述同余类和商在 [HomRelT] 上陈述，并且每个 [Prop] 值客户端都保持不变。

   一个 [Type] 值族可以直接作为商的同集等价，因为 [Setoid] 的 [equiv] 本身就是一个 [crelation]。[Quotient_HomEqProp] 保持固定在 [Prop] 值的 [R] 上，因为它的 [heq] 字段必须落在 [Prop] 中。这就是为什么 [Prop] 家族有自己的名字，以及为什么由生成同余得到的商（本文件的最后一个小节）不携带 [HomEqProp] 实例。
*)

Definition HomRel (C : Category) : Type :=
  ∀ x y : C, (x ~> y) → (x ~> y) → Prop.

Definition HomRelT (C : Category) : Type :=
  ∀ x y : C, (x ~> y) → (x ~> y) → Type.

(*
   * A congruence: an equivalence on each hom containing [≈] (whence
   reflexivity) and compatible with composition. 

   --------
   * 一种合同关系：在每个包含  [≈]  的同类上建立的等价关系（因此具有自反性）并且与组合兼容。
*)
Class HomCongruence {C : Category} (R : HomRelT C) : Type := {
  cong_incl {x y : C} {f g : x ~> y} : f ≈ g → R x y f g;
  cong_sym {x y : C} {f g : x ~> y} : R x y f g → R x y g f;
  cong_trans {x y : C} {f g h : x ~> y} :
    R x y f g → R x y g h → R x y f h;
  cong_comp {x y z : C} {f f' : y ~> z} {g g' : x ~> y} :
    R y z f f' → R x y g g' → R x z (f ∘ g) (f' ∘ g')
}.

(** Reflexivity of a congruence, from inclusion of [≈]. / 同余的自反性，来自 [≈] 的包含。 *)
Lemma cong_refl {C : Category} {R : HomRelT C} `{@HomCongruence C R}
  {x y : C} (f : x ~> y) : R x y f f.
Proof. apply cong_incl; reflexivity. Qed.

(** Each hom-relation of a congruence is an equivalence. / 每一个同余的同态关系都是等价关系。 *)
Lemma Quotient_equivalence {C : Category} {R : HomRelT C}
  `{@HomCongruence C R} (x y : C) : Equivalence (R x y).
Proof.
  constructor.
  - intros f. exact (cong_refl f).
  - intros f g Hfg. exact (cong_sym Hfg).
  - intros f g k Hfg Hgk. exact (cong_trans Hfg Hgk).
Qed.

(*
   * The quotient category [C/R]: same objects and morphisms as [C], with
   the hom-setoid equivalence coarsened from [≈] to [R].  The category
   laws hold because [R] contains [≈] (via [cong_incl]) and [C] already
   satisfies them up to [≈]. 

   --------
   * 商类 [C/R]：与 [C] 拥有相同的对象和态射，其 Hom-集合等价关系从 [≈] 粗化到 [R]。类律成立因为 [R] 包含 [≈]（通过 [cong_incl]），并且 [C] 已经满足它们直到 [≈]。
*)
(*
   【Quotient 范畴定义展开】/ Quotient walkthrough
   （口吻对齐 Theory/Category.v；受众：Coq 小白 + 范畴论小白的 Haskell 程序员）

   1) 这是什么 / What this is
      固定同态合同 R（含原 ≈、对复合封闭），商范畴 C/R：
      对象与箭头载体不变，只把「相等」从 ≈ 加粗成 R。
      Same objs/arrows; coarsen equality of arrows from ≈ to R.
      Haskell 对照：新type 包同一载体，改 Eq 实例 —— 这里改的是 Setoid。
      Like changing the Eq/Setoid, not the carrier.

   2) 前置 / Prerequisites above in this file
      HomRelT + HomCongruence（cong_incl / cong_comp / 等价律）；
      另有 id_cast 运输工具、生成最小合同 CongClosure 等。

   3) 本定义字段 / Fields of Quotient
      obj/hom/id/compose 同 C；homset.equiv := R；定律用 cong_incl 从 C 抬上来。

   4) 泛性质 / UP（下文）
      QuotientProj : C ⟶ C/R；满足 R 的函子唯一提升为 QuotientLift。

   阅读：先 HomCongruence → Quotient 改 ≈ → Proj / Lift。
   Read: congruence → coarsen ≈ → projection & lift.
*)

Definition Quotient (C : Category) (R : HomRelT C)
  `{@HomCongruence C R} : Category := {|
  obj := @obj C;
  hom := @hom C;
  homset := fun x y =>
    {| equiv := R x y; setoid_equiv := Quotient_equivalence x y |};
  id := @id C;
  compose := @compose C;
  compose_respects := fun x y z f f' Hf g g' Hg => cong_comp Hf Hg;
  id_left := fun x y f => cong_incl (id_left f);
  id_right := fun x y f => cong_incl (id_right f);
  comp_assoc := fun x y z w f g h => cong_incl (comp_assoc f g h);
  comp_assoc_sym := fun x y z w f g h => cong_incl (comp_assoc_sym f g h)
|}.

(*
   * The quotient's [≈] IS [R x y] after reduction, so both directions of
   the [Prop] reflection are the identity. 

   --------
   * 商的 [≈] 在约简后是 [R x y]，因此 [Prop] 反射的两个方向都是恒等映射。
*)
#[export] Instance Quotient_HomEqProp (C : Category) (R : HomRel C)
  `{@HomCongruence C R} : HomEqProp (Quotient C R) :=
  Build_HomEqProp (Quotient C R)
    (fun x y f g => R x y f g)
    (fun x y f g Hfg => Hfg)
    (fun x y f g Hfg => Hfg).

(*
   * The quotient has the same objects as [C], so decidability of object
   equality is inherited on the nose. 

   --------
   * 商同余类具有与 [C] 相同的对象，因此对象相等性的可判定性是直接继承的。
*)
#[export] Instance Quotient_ObjDecEq (C : Category) (R : HomRel C)
  `{@HomCongruence C R} `{OD : @ObjDecEq C} : ObjDecEq (Quotient C R) := OD.

(* * *** The universal property of the quotient / * *** 商的泛性质 *)

Section QuotientUMP.

Context {C : Category} {R : HomRelT C} `{@HomCongruence C R}.

(*
   * The projection functor: identity on objects and on morphisms; only the
   equivalence coarsens.  (Here and below the record is built with an
   explicit [Build_Functor] so that the codomain category is pinned to the
   quotient; a bare record literal would infer it from the field values,
   which live in [C].) 

   --------
   * 投影函子：在对象和态射上是恒等的；只有等价关系被粗化。（在这里及以下，记录是通过显式的 [Build_Functor] 构建的，以便将余类固定到陪域；如果只是一个简单的记录字面量，则会从字段值中推断，它们存在于 [C] 中。）
*)
Definition QuotientProj : C ⟶ Quotient C R :=
  Build_Functor C (Quotient C R)
    (fun x => x)
    (fun x y f => f)
    (fun x y f g Hfg => cong_incl Hfg)
    (fun x => cong_refl (@id C x))
    (fun x y z f g => cong_refl (f ∘ g)).

(*
   * Isomorphisms in [C] descend to isomorphisms in the quotient. 

   --------
   * [C] 中的同构会下降为商中的同构。
*)
Definition Quotient_iso {x y : C} (i : x ≅[C] y) : x ≅[Quotient C R] y :=
  @Build_Isomorphism (Quotient C R) x y (to i) (from i)
    (cong_incl (iso_to_from i))
    (cong_incl (iso_from_to i)).

Context {D : Category} (F : C ⟶ D)
  (HF : ∀ x y (f g : x ~> y), R x y f g → fmap[F] f ≈ fmap[F] g).

(*
   * A functor identifying [R]-related morphisms lifts through the
   quotient. 

   --------
   * 一个识别 [R] 相关态射的函子通过商提升。
*)
Definition QuotientLift : Quotient C R ⟶ D :=
  Build_Functor (Quotient C R) D
    (fun x => F x)
    (fun x y f => fmap[F] f)
    HF
    (fun x => @fmap_id C D F x)
    (fun x y z f g => @fmap_comp C D F x y z f g).

(*
   * The lift factors [F] through the projection — definitionally. 

   --------
   * 提升因子 [F] 通过投影——根据定义。
*)
Lemma QuotientLift_proj {x y : C} (f : x ~> y) :
  fmap[QuotientLift] (fmap[QuotientProj] f) = fmap[F] f.
Proof. reflexivity. Qed.

(*
   * The factorization, packaged as a single equality of functors in
   [StrictCat] — the same strength as [QuotientLift_unique] below. 

   --------
   * 因式分解，以单个函子等式的形式封装在 [StrictCat] 中——其强度与下面的 [QuotientLift_unique] 相同。
*)
Lemma QuotientLift_factors_strict :
  @equiv _ (@Functor_StrictEq_Setoid C D) (QuotientLift ◯ QuotientProj) F.
Proof. exists (fun _ => eq_refl). intros x y f. simpl. reflexivity. Qed.

(*
   * Uniqueness: [QuotientProj] is the identity on objects and on
   morphisms, so any competitor agreeing with [F] after precomposition
   with the projection is pinned pointwise on every hom.  The competitor's
   object action agrees with [F]'s up to the Leibniz equalities [Hobj],
   and the morphism-level agreement is phrased by conjugating with
   [hom_cast] along them (see the transport kit above); when the object
   agreement is definitional, instantiating [Hobj] with [eq_refl] makes
   both [hom_cast]s disappear definitionally.

   That [hom_cast] conjugation along Leibniz object equalities IS
   [StrictCat]'s functor equality ([Functor_StrictEq_Setoid],
   [Theory/Functor.v]); [strict_of_hom_cast] and [hom_cast_of_strict]
   above convert between the two phrasings in both directions.  The
   factorization half at that same strength is
   [QuotientLift_factors_strict] just above, the pointwise Leibniz
   [QuotientLift_proj] being the sharper but weaker-typed statement. 

   --------
   * 唯一性：[QuotientProj] 在对象和态射上都是恒等的，因此任何在与投影预组合后与 [F] 一致的竞争者，在每个同态上都是逐点固定的。竞争者的对象作用与 [F] 在莱布尼兹等式 [Hobj] 下保持一致，而态射层级的一致性通过沿它们与 [hom_cast] 共轭来表述（参见上面的传输工具包）；当对象的一致性是定义性的时，将 [Hobj] 实例化为 [eq_refl] 会使两个 [hom_cast] 在定义上消失。沿着 Leibniz 对象等式的 [hom_cast] 共轭是 [StrictCat] 的函子等式（[Functor_StrictEq_Setoid]，[Theory/Functor.v]）；上面的 [strict_of_hom_cast] 和 [hom_cast_of_strict] 在两个方向之间转换这两种表述。在相同强度下的因式分解部分就是上面的 [QuotientLift_factors_strict]，逐点 Leibniz [QuotientLift_proj] 是较精确但类型较弱的陈述。
*)
Lemma QuotientLift_unique (G : Quotient C R ⟶ D)
  (Hobj : ∀ x : C, fobj[G] x = fobj[F] x)
  (HG : ∀ x y (f : x ~{C}~> y),
      hom_cast (Hobj x) (Hobj y) (fmap[G] (fmap[QuotientProj] f))
        ≈ fmap[F] f) :
  ∀ x y (f : x ~{Quotient C R}~> y),
    hom_cast (Hobj x) (Hobj y) (fmap[G] f) ≈ fmap[QuotientLift] f.
Proof. exact HG. Qed.

End QuotientUMP.

(*
   * ** The projection identifies, and never separates

   Imposing equations can only merge morphisms; it never adds any.  The
   projection is the identity on objects and the identity on morphisms,
   and only the hom-setoid equivalence coarsens, so both halves of that
   reading are definitional here.  The projection is deliberately not
   [Faithful]: that non-instance is the whole content of Fong and
   Spivak's remark that imposing equations can merge morphisms but never
   add any (see [Construction/Free/Quiver/Presented.v]). 

   --------
   * ** 投影识别，但从不分离

   强加方程只能合并态射；它从不增加任何态射。投影在对象上是恒等的，在态射上也是恒等的，只有同态集合的等价关系被粗化，因此这一阅读的两部分在这里都是定义上的。投影故意不是 [Faithful]：这个非实例就是 Fong 和 Spivak 的评论的全部内容，即强加方程可以合并态射，但绝不增加（参见 [Construction/Free/Quiver/Presented.v]）。
*)

(*
   * The projection is the identity on objects, on the nose — the honest
   reading of "bijective on objects". 

   --------
   * 投影在对象上是恒等的，确切地说——这是“在对象上双射”的真实理解。
*)
Lemma QuotientProj_obj {C : Category} (R : HomRelT C)
  `{HR : @HomCongruence C R} (x : C) : fobj[@QuotientProj C R HR] x = x.
Proof. reflexivity. Qed.

(*
   * The sharpest form of "equations merge and never add": the hom TYPE is
   unchanged by the quotient. 

   --------
   * “等式合并而不相加”的最尖锐形式：同态 TYPE 在商中保持不变。
*)
Lemma Quotient_hom_type {C : Category} (R : HomRelT C)
  `{HR : @HomCongruence C R} (x y : C) :
  (x ~{Quotient C R}~> y) = (x ~{C}~> y).
Proof. reflexivity. Qed.

(*
   * Surjectivity on each hom-set, as a CHOSEN section, so no choice
   principle is used.  (The record is built with the fully applied
   [@Build_Full]: a bare record literal does not infer the functor.) 

   --------
   * 每个 Hom-set 上的满射性，作为一个选定的截面，因此没有使用选择公理。（记录是使用完全应用的 [@Build_Full] 构建的：一个空的记录字面量不能推断函子。）
*)
Definition QuotientProj_Full {C : Category} (R : HomRelT C)
  `{HR : @HomCongruence C R} : Full (@QuotientProj C R HR) :=
  @Build_Full C (Quotient C R) (@QuotientProj C R HR)
    (fun x y g => g) (fun x y g => @cong_refl C R HR x y g).

(*
   * ** Bifunctor descent

   A bifunctor on [C] whose morphism action preserves [R] componentwise
   descends to a bifunctor on the quotient.  The object and morphism
   actions are unchanged; only the respectfulness proof is new (note that
   the product category's hom equivalence is a pair). 

   --------
   * ** 双函子下降

   一个作用在  [C] 上的双函子，其对射的作用在 [R] 上逐分量保持不变，
   可以下降到商上的双函子。对象和射的作用保持不变；唯一新的部分是尊重性的证明（注意积范畴的同态等价是一个对）。
*)
Definition Quotient_bifunctor {C : Category} {R : HomRelT C}
  `{@HomCongruence C R} (F : C ∏ C ⟶ C)
  (HF2 : ∀ (x y : C ∏ C) (f g : x ~{C ∏ C}~> y),
      R (fst x) (fst y) (fst f) (fst g) →
      R (snd x) (snd y) (snd f) (snd g) →
      R (F x) (F y) (fmap[F] f) (fmap[F] g)) :
  Quotient C R ∏ Quotient C R ⟶ Quotient C R :=
  Build_Functor (Quotient C R ∏ Quotient C R) (Quotient C R)
    (fun x => F x)
    (fun x y f => fmap[F] f)
    (fun x y f g Hfg => HF2 x y f g (fst Hfg) (snd Hfg))
    (fun x => cong_incl (@fmap_id _ _ F x))
    (fun x y z f g => cong_incl (@fmap_comp _ _ F x y z f g)).

(*
   * ** The congruence generated by a hom-relation

   Book: Mac Lane, Categories for the Working Mathematician, 2nd ed.,
   §II.8, printed pp. 51-52 — Proposition 1 (the quotient by an
   arbitrary family of relations and its universal property), the
   definition of a congruence and of the least congruence containing
   a family, and the definition of a category presented by
   generators and relations
   nLab: https://ncatlab.org/nlab/show/quotient+category
   nLab: https://ncatlab.org/nlab/show/congruence

   WHY THE CLOSURE IS [Type]-VALUED.  The hom-setoid equivalence [≈] of
   this library is [Type]-valued (it is a [crelation]; see
   [Lib/Setoid.v]).  A [Prop]-valued inductive with two or more
   constructors cannot be eliminated into that [Type]-valued [≈] of an
   abstract target category, because the elimination restriction on [Prop]
   blocks the induction — the same obstruction the [HomEqProp] subsection
   above records.  The sharp form of it here is that the kernel congruence
   of a functor, [FunctorKernel] below, is [Type]-valued precisely because
   [≈] is, so it is not even expressible as a [HomRel]: Mac Lane's own
   proof of Proposition 1 cannot be transcribed in the [Prop] family.

   SCOPE, universes.  The composition constructor [cc_comp] binds an
   intermediate object, so the closure's sort absorbs the OBJECT universe,
   and the resulting quotient carries the constraint that the object
   universe is at most the proof universe.  This is harmless for
   quiver-presented categories, the intended application
   ([Construction/Free/Quiver/Presented.v]), but it would bite an attempt
   to present a category whose objects live strictly above its homs.

   SCOPE, reflection.  A quotient by a generated congruence has no
   [HomEqProp] instance, since [Quotient_HomEqProp] requires a
   [Prop]-valued relation; the consumers that require one —
   [Construction/PROP/Interp.v], [Construction/PROP/Algebra.v],
   [Construction/PROP/Universal.v], [Construction/ColouredPROP/Interp.v],
   [Construction/ColouredPROP/Algebra.v],
   [Construction/ColouredPROP/Universal.v], [Theory/Lawvere/PROP.v] — do
   not apply to it.  It has no need of one: the lift below no longer routes
   through [heq].

   RELATION TO THE SYNTACTIC CLOSURES.  [TermEqW]
   ([Construction/PROP/Presentation.v]) and [CTermEqW]
   ([Construction/ColouredPROP/Presentation.v]) are this closure shape run
   over term syntax: their [TEW_termeq], [TEW_ax], [TEW_sym], [TEW_trans]
   and [TEW_comp] are one for one [cc_equiv], [cc_gen], [cc_sym],
   [cc_trans] and [cc_comp], with [TermEq] playing the role the ambient
   hom-setoid [≈] plays here, whence reflexivity is derived on both sides
   ([TermEqW_refl] there, [cc_refl] here) rather than assumed.  They carry
   one constructor more, [TEW_tens] and [CTEW_tens], and it is NOT part of
   the least congruence in the categorical sense: it is exactly the
   hypothesis [Quotient_bifunctor] consumes, i.e. what makes those
   quotients monoidal rather than merely categories.  Formally [cc_least]
   yields the containment [CongClosure (smt_eqs E) ⊆ TermEqW E]; the
   converse is not available: nothing in the generic closure pushes a
   relation through a tensor context, and no in-tree countermodel is
   exhibited.  That containment is stated here in prose rather than as
   code because this file cannot depend on the PROP layer.  The phrase
   "smallest congruence" in both of those files reads in the TERM-ALGEBRA
   sense — least among relations closed under [T_comp] AND [T_tens] — and
   [cc_least] does not establish it: [cc_least] supplies only the
   containment above, the direction that leaves [TermEqW] the larger
   relation.  What [cc_least] does supply is the categorical half of the
   vocabulary those headers borrow: a formal least hom-congruence.

   Finally, [TermEqW] must STAY [Prop]-valued: that is what lets
   [Quotient_HomEqProp] supply the reflection its soundness inductions
   round-trip through, at the price that Proposition 1's arbitrary-target
   factorization is not available there — exactly the trade the
   [Type]-valued closure reverses. 

   --------
   * ** 由同态关系生成的陪集

   书籍：Mac Lane，《工作数学家的范畴论》，第二版，
   §II.8，第51-52页印刷版 — 命题1（任意关系族的商及其普遍性质），
   陪集的定义以及包含一个关系族的最小陪集的定义，
   以及由生成元和关系给出的范畴定义
   nLab:  https://ncatlab.org/nlab/show/quotient+category 
   nLab:  https://ncatlab.org/nlab/show/congruence为什么该闭包是 [Type] 值的。这个库的同态等价集 [≈] 是 [Type] 值的（它是一个 [crelation]；见 [Lib/Setoid.v]）。一个具有两个或更多构造子的 [Prop] 值归纳类型无法消去到抽象目标范畴的那个 [Type] 值 [≈]，因为对 [Prop] 的消去限制阻止了归纳——这正是上面 [HomEqProp] 小节记录的障碍。这里的尖锐形式是，一个函子 [FunctorKernel] 的核同余正因为 [≈] 是 [Type] 值的，所以它甚至无法表示为 [HomRel]：Mac Lane 对命题 1 的证明自身无法转录到 [Prop] 系列中。范围，宇宙。组合构造函数 [cc_comp] 绑定了一个中间对象，因此闭包的类型吸收了对象宇宙，并且生成的商带有约束，即对象宇宙最多是证明宇宙。这对于箭袋呈现的范畴（预期应用 [Construction/Free/Quiver/Presented.v]）是无害的，但对于尝试呈现对象严格高于其态射的范畴则会出现问题。

   范围，反射。由生成的同余生成的商没有 [HomEqProp] 实例，因为 [Quotient_HomEqProp] 需要一个 [Prop] 值的关系；需要它的使用者——ZW22WZZ、ZW23WZZ、ZW24WZZ、ZW25WZZ、ZW26WZZ、ZW27WZZ、ZW28WZZ——不适用于它。它不需要：下面的提升不再通过 [heq] 路由。

   与句法闭包的关系。[TermEqW]（[Construction/PROP/Presentation.v]）和[CTermEqW]（[Construction/ColouredPROP/Presentation.v]）是这种闭包形状在项语法上的运行：它们的[TEW_termeq]、[TEW_ax]、[TEW_sym]、[TEW_trans]和[TEW_comp]分别对应[cc_equiv]、[cc_gen]、[cc_sym]、[cc_trans]和[cc_comp]，其中[TermEq]扮演此处环境同值类[≈]的角色，因此两边的自反性是派生的（那边是[TermEqW_refl]，这边是[cc_refl]），而不是被假设的。它们携带一个额外的构造子[TEW_tens]和[CTEW_tens]，并且它在范畴意义上不是最小合同的一部分：它正是假设[Quotient_bifunctor]所消耗的，即使这些商是幺半群而不仅仅是范畴的原因。形式上  [cc_least]  导致包含关系  [CongClosure (smt_eqs E) ⊆ TermEqW E]；反之则不可行：通用闭包中没有任何东西可以将关系通过张量上下文推进，也没有展示任何树内反例。这里以散文方式而非代码形式陈述该包含关系，因为此文件不能依赖 PROP 层。两个文件中“最小合同”的短语在 TERM-ALGEBRA 意义下理解——在在  [T_comp] 和  [T_tens] 下闭合的关系中最小——而 [cc_least] 并未建立它：[cc_least] 只提供了上面的包含方向，即保持 [TermEqW] 为较大关系的方向。[cc_least] 所提供的是那些头文件借用词汇的范畴学一半：一个形式上的最小同态合同。最后，[TermEqW] 必须保持 [Prop] 值：这就是让 [Quotient_HomEqProp] 能够将其健全性归纳的反射进行往返的原因，条件是命题 1 的任意目标分解在那里不可用 —— 这正是 [Type] 值闭包所逆转的交换。
*)

(*
   * Mac Lane's kernel congruence of a functor: the morphisms it merges.
   It is [Type]-valued because [≈] is. 

   --------
   * Mac Lane 的函子核同余：它合并的态射。
   它是 [Type] 值的，因为 [≈] 是。
*)
Definition FunctorKernel {C D : Category} (F : C ⟶ D) : HomRelT C :=
  fun x y f g => fmap[F] f ≈ fmap[F] g.

(*
   * The kernel of a functor is a congruence.  Kept a plain [Definition] and
   [Defined] rather than an [Instance], so that nothing new enters
   typeclass search and the congruence witness stays transparent where
   [cc_kernel] elaborates its type. 

   --------
   * 函子（functor）的核（kernel）是一个同余（congruence）。保留了一个简单的 [Definition] 和 [Defined]，而不是 [Instance]，这样在类型类搜索中不会引入新的内容，并且当 [cc_kernel] 展开其类型时，同余的证人保持透明。
*)
Definition FunctorKernel_Congruence {C D : Category} (F : C ⟶ D) :
  @HomCongruence C (FunctorKernel F).
Proof.
  unshelve econstructor; unfold FunctorKernel.
  - intros x y f g Hfg. now rewrite Hfg.
  - intros x y f g Hc. now symmetry.
  - intros x y f g h H1 H2. now transitivity (fmap[F] g).
  - intros x y z f f' g g' H1 H2. rewrite !fmap_comp. now rewrite H1, H2.
Defined.

Section CongruenceClosure.

Context {C : Category}.
Variable R : HomRelT C.

(*
   * The congruence generated by [R]: five constructors — embed [R], embed
   the ambient [≈], symmetry, transitivity, and closure under composition
   on both flanks simultaneously (the shape that matches the [cong_comp]
   field verbatim).  There is deliberately no reflexivity constructor: it
   is derived below as [cc_refl], mirroring [TermEqW_refl] in the PROP
   presentation layer. 

   --------
   * 由 [R] 生成的合同关系：五个构造器——嵌入 [R]、嵌入环境 [≈]、对称性、传递性，以及在两侧同时对组合闭合（匹配 [cong_comp] 字段的形状）。刻意没有自反构造器：它将在下面作为 [cc_refl] 推导，反映 PROP 表示层中的 [TermEqW_refl]。
*)
Inductive CongClosure : ∀ x y : C, (x ~> y) → (x ~> y) → Type :=
  | cc_gen {x y : C} {f g : x ~> y} : R x y f g → CongClosure x y f g
  | cc_equiv {x y : C} {f g : x ~> y} : f ≈ g → CongClosure x y f g
  | cc_sym {x y : C} {f g : x ~> y} :
      CongClosure x y f g → CongClosure x y g f
  | cc_trans {x y : C} {f g h : x ~> y} :
      CongClosure x y f g → CongClosure x y g h → CongClosure x y f h
  | cc_comp {x y z : C} {f f' : y ~> z} {g g' : x ~> y} :
      CongClosure y z f f' → CongClosure x y g g' →
      CongClosure x z (f ∘ g) (f' ∘ g').

(*
   * The closure is a congruence, by a pure term: four of the five
   constructors map onto the four fields, with [cc_equiv] supplying
   [cong_incl]; [cc_gen] is what makes the closure contain [R] and plays
   no part here. 

   --------
   * 闭包是一个合同，通过一个纯项：五个构造函数中的四个映射到四个字段，[cc_equiv] 提供了 [cong_incl]；[cc_gen] 是使闭包包含 [R] 的部分，并且在这里不起作用。
*)
Definition CongClosure_Congruence : @HomCongruence C CongClosure :=
  @Build_HomCongruence C CongClosure
    (fun x y f g H => cc_equiv H)
    (fun x y f g H => cc_sym H)
    (fun x y f g h H1 H2 => cc_trans H1 H2)
    (fun x y z f f' g g' H1 H2 => cc_comp H1 H2).

(** Reflexivity, derived rather than assumed. / 反身性，其来源是衍生的而非假定的。 *)
Definition cc_refl {x y : C} (f : x ~> y) : CongClosure x y f f :=
  cc_equiv (reflexivity f).

(*
   * Leastness: the closure is contained in every congruence containing
   [R].  Because [HomCongruence] is stated over [HomRelT], a [Prop]-valued
   target congruence is covered by the same statement, through
   [Prop ⊆ Type] cumulativity. 

   --------
   * 最小性：闭包包含于包含 [R] 的每一个同余中。由于 [HomCongruence] 是在 [HomRelT] 上陈述的，通过 [Prop ⊆ Type] 的累积性，一个 [Prop] 值的目标同余也被同样的陈述覆盖。
*)
Lemma cc_least (S : HomRelT C) `{@HomCongruence C S}
  (HRS : ∀ x y (f g : x ~> y), R x y f g → S x y f g)
  {x y : C} {f g : x ~> y} : CongClosure x y f g → S x y f g.
Proof.
  intro Hc; induction Hc.
  - now apply HRS.
  - now apply cong_incl.
  - now apply cong_sym.
  - now apply (cong_trans IHHc1 IHHc2).
  - now apply cong_comp.
Qed.

(*
   * Mac Lane §II.8 Proposition 1's kernel lemma: a functor merging [R]
   merges the whole generated congruence.  It is a one-line corollary of
   leastness applied at the kernel congruence, not a second induction, and
   its type is exactly the hypothesis [QuotientLift] consumes. 

   --------
   * Mac Lane §II.8 命题 1 的核引理：合并 [R] 的函子合并整个生成的同余。这是将最小性应用于核同余的一行推论，而不是第二次归纳，并且它的类型正是假设 [QuotientLift] 所使用的类型。
*)
Definition cc_kernel {D : Category} (F : C ⟶ D)
  (HF : ∀ x y (f g : x ~> y), R x y f g → fmap[F] f ≈ fmap[F] g)
  {x y : C} {f g : x ~> y} :
  CongClosure x y f g → fmap[F] f ≈ fmap[F] g :=
  @cc_least (FunctorKernel F) (FunctorKernel_Congruence F) HF x y f g.

End CongruenceClosure.

Arguments CongClosure {C} R x y f g.
Arguments cc_gen {C R x y f g} _.
Arguments cc_equiv {C R x y f g} _.
Arguments cc_sym {C R x y f g} _.
Arguments cc_trans {C R x y f g h} _ _.
Arguments cc_comp {C R x y z f f' g g'} _ _.
Arguments cc_refl {C} R {x y} f.
Arguments CongClosure_Congruence {C} R.

(*
   * The quotient by the congruence GENERATED by an arbitrary relation
   family — Mac Lane §II.8 Proposition 1's category. 

   --------
   * 由任意关系族生成的合同的商 —— Mac Lane §II.8 命题 1 的范畴。
*)
Definition QuotientCong (C : Category) (R : HomRelT C) : Category :=
  @Quotient C (CongClosure R) (CongClosure_Congruence R).

(** Its projection. / 它的投影。 *)
Definition QuotientCongProj {C : Category} (R : HomRelT C) :
  C ⟶ QuotientCong C R :=
  @QuotientProj C (CongClosure R) (CongClosure_Congruence R).

(*
   * Proposition 1, clause (i): related arrows are identified by the
   projection. 

   --------
   * 命题 1，第 (i) 条款：相关箭头由投影确定。
*)
Lemma cong_identifies {C : Category} (R : HomRelT C) {x y : C}
  {f g : x ~> y} (Hr : R x y f g) :
  fmap[QuotientCongProj R] f ≈ fmap[QuotientCongProj R] g.
Proof. exact (cc_gen Hr). Qed.

(*
   * Proposition 1, clause (ii): any functor merging [R] factors through the
   projection, with no side condition on the target [D]. 

   --------
   * 命题 1，第 (ii) 条款：任何合并 [R] 的函子都通过投影进行，且对目标 [D] 没有附加条件。
*)
Definition QuotientCongLift {C D : Category} (R : HomRelT C) (F : C ⟶ D)
  (HF : ∀ x y (f g : x ~> y), R x y f g → fmap[F] f ≈ fmap[F] g) :
  QuotientCong C R ⟶ D :=
  @QuotientLift C (CongClosure R) (CongClosure_Congruence R) D F
    (fun x y f g Hc => @cc_kernel C R D F HF x y f g Hc).
