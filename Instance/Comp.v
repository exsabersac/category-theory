Module UniversalAlgebra.

(*
   * In universal algebra, a (many-sorted) signature lists the operations that
   characterize an algebraic structure. Signatures play the same role in
   mathematics as type signatures in computer programming.

   We start by defining operation signatures. These describe the operations
   of an algebra.

   The main trick is that the arity of an operation is *not* a number but
   rather a type. For instance, the arity of a binary operation is a type
   with two elements. (And nothing prevents us from having an infinite type
   as arity.) 

   --------
   * 在普遍代数中，一个（多排序的）符号列出了表征代数结构的运算。符号在数学中的作用类似于计算机程序中的类型签名。

   我们首先定义运算符号。这些符号描述了一个代数的运算。

   主要的技巧是运算的元数 *不是* 一个数字，而是一种类型。例如，一个二元运算的元数是一个具有两个元素的类型。（并且没有什么阻止我们使用无限类型作为元数。）
*)
Record OpSignature := {
  operation : Type ;             (* (Names of) operations. / （操作的）名称。 *)
  arity     : operation → Type  (* Each operation has an arity. / 每个操作都有一个元数。 *)
}.

Arguments arity {_} _.

(*
   * We shall consider algebras with given operations, but without equations.
   We call these "operation algebras". 

   --------
   * 我们将考虑具有给定运算但没有方程的代数。
   我们称这些为“运算代数”。
*)
Record OpAlgebra (S : OpSignature) := {
  carrier :> Type ;
  op : ∀ o : operation S, (arity o → carrier) → carrier
  (* no equations / 没有方程 *)
}.

Arguments carrier {_} _.
Arguments op {_} _ _ _.

(** We define the type of homomorphism between operation algebras A and B. / 我们定义了运算代数 A 和 B 之间同态的类型。 *)
Record AlgHom {S : OpSignature} (A : OpAlgebra S) (B : OpAlgebra S) := {
  map :> A → B ; (* The underlying map / 底层地图 *)
  (* The underlying map commutes with operations: / 底层映射与操作交换： *)
  op_commute : ∀ (o : operation S) (args : arity o → A),
    map (op A o args) = op B o (fun x => map (args x))
}.

Arguments map {_ _ _} _.

#[export] Program Instance AlgHom_Setoid
    {S : OpSignature} (A : OpAlgebra S) (B : OpAlgebra S) :
  Setoid (AlgHom A B) := {|
  equiv := fun f g : AlgHom A B => ∀ x : A, f x = g x
|}.
Next Obligation.
  equivalence.
  now rewrite H, H0.
Qed.

Section FreeAlg.
  Hypothesis S : OpSignature.
  Hypothesis X : Type.

  (* The free algebra for a given signature [S] generated by [X]. / 由 [X] 生成的给定符号 [S] 的自由代数。 *)
  Inductive Tree : Type :=
    | generator : X → Tree
    | node : ∀ (o : operation S), (arity o → Tree) → Tree.

  Definition Free : OpAlgebra S := {|
    carrier := Tree;
    op      := node
  |}.

  (* We show that the free algebra has the desired universal property. / 我们表明自由代数具有所需的普遍性质。 *)

  Hypothesis A : OpAlgebra S.
  Hypothesis h : X → A.

  Fixpoint induced_map (t : Tree) : A :=
    match t with
    | generator x => h x
    | node o arg => op A o (fun i => induced_map (arg i))
    end.

  Definition induced_hom : AlgHom Free A.
  Proof using A S X h.
    exists induced_map.
    intros o arg.
    reflexivity.
  Defined.

  (* The induced homomorphism is unique. / 诱导同态是唯一的。 *)
  Theorem from_free_unique (f g : AlgHom Free A) :
    (∀ x : X, f (generator x) = g (generator x)) → f ≈ g.
  Proof.
    intros eq_gen t.
    induction t.
    - now apply eq_gen.
    - rewrite 2 op_commute.
      f_equal.
      (*
 jww (2020-02-23): How to remove this axiom?  It is hard to avoid
 here: an operation's arguments are packaged as a function
 [arity o → Tree], so deriving equality of the two argument bundles
 from a pointwise hypothesis genuinely needs functional
 extensionality.  Working up to a setoid on [Tree] (rather than
 Leibniz [=]) would remove the dependency. 

 --------
 jww (2020-02-23)：如何去掉这个公理？这里很难避免：一个操作的参数被打包为一个函数 [arity o → Tree]，因此要从逐点假设推导出两个参数包的相等性，确实需要函数外延性。在 [Tree] 上建立一个集合结构（而不是在莱布尼茨 [=] 上）可以消除这种依赖。
*)
      extensionality x.
      now apply H.
  Qed.
End FreeAlg.

