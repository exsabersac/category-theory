   BACKGROUND.  nLab describes abelianization as "the process of
   freely making an algebraic structure 'abelian'", the group case
   being the notable one.  Mac Lane gives it as the first of his
   examples of a reflection, Riehl as the second clause of her roster,
   and Seven Sketches as a plain adjunction, with no mention of
   reflectivity.  The library already had the construction and the
   adjunction: Instance/Grp/Abelianization.v builds [AbelianizationOb],
   [Abelianization_Functor], the inclusion [Ab_to_Grp] and the
   projection [abel_proj], and Instance/Grp/Abelianize.v proves
   [abelianize_adjunction_via_transform : Abelianization_Functor ⊣
   Ab_to_Grp] and that [Ab_to_Grp] is full and faithful.  What was
   missing is the record of Construction/Reflective.v.

   WHY A NEW SUBCATEGORY.  [Reflective] is stated over the [Sub]
   inclusions of Construction/Subcategory.v, and [Ab_to_Grp] is not one
   of them: its objects are Instance/Ab.v's [AbObject] records, not
   groups carrying a predicate.  Measured, for an arbitrary
   [S : Subcategory Grp]: [Incl Grp S = Ab_to_Grp] is refused with
   "The term "Ab_to_Grp" has type "Ab ⟶ Grp" while it is expected to
   have type "Sub Grp S ⟶ Grp"", and building the record from
   Abelianize.v's adjunction is refused with "The term
   "Abelianization_Functor" has type "Grp ⟶ Ab" while it is expected to
   have type "Grp ⟶ Sub Grp S"".  Both are typing refusals.  So the
   subcategory is cut out of [Grp] by a commutativity predicate
   ([IsAbelian], [AbGrp_Sub], [AbGrp]), full with the trivially true
   [shom] of Instance/Rng.v's [CRng_Sub], and the universal arrow is
   rebuilt at it: [abel_kills_grp] is Abelianize.v's [abel_kills] with
   the target a commutative GROUP, [abel_med_grp] reads a homomorphism
   out of the quotient, [abgrp_universal] is the ∃!, and
   Theory/Universal/Arrow.v's plumbing gives [AbGrp_reflector],
   [AbGrp_adj] and the issue's pinned name
   [Ab_Reflective_in_Grp : Reflective AbGrp_Sub].

   THE ISSUE'S PATH.  The issue's verification step compiles
   Instance/Grp/Abelianization.v.  That file cannot host the record:
   the proof needs Abelianize.v's [ab_is_abelian] (and the S₃ witness
