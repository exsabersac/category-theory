   * * Ab is reflective in Grp: the abelianization as a [Reflective] record

   Mac Lane, "Categories for the Working Mathematician", 2nd ed.,
   Springer GTM 5, §IV.3, printed p. 92 (PDF p. 101), read from the
   page image, catalog item maclane:IV.3:construction1: "Here are some
   examples.  Ab is reflective in Grp.  For, if G/[G, G] is the usual
   factor-commutator group of a group G, then hom(G/[G, G], A) ≅
   hom(G, A) for A abelian, and Ab is full in Grp."  The definition is
   on printed p. 91 (PDF p. 100): "A subcategory A of B is called
   reflective in B when the inclusion functor K: A → B has a left
   adjoint F: B → A", and "If a full subcategory A ⊂ B is reflective in
   B, then by Theorem 1 each object a ∈ A is isomorphic to FKa".
   Riehl, "Category Theory in Context", §4.6, Example 4.6.13 (ii),
   printed p. 170 (PDF p. 190), read from the page image, catalog item
   riehl:4.6:example13: "Abelian groups define a reflective subcategory
   Ab ↪ Group of the category of groups.  The reflector carries a group
   G to its abelianization, the quotient G/[G,G] by the commutator
   subgroup, the normal subgroup generated by elements ghg⁻¹h⁻¹.  The
   quotient maps G → G/[G,G] define the components of the unit."
   Fong and Spivak, "Seven Sketches in Compositionality", §3.4.2,
   Example 3.74 (5), printed p. 104 (PDF p. 116), read from the page
   image, catalog item 7sketches:3.4.2:example3.74: "Given a group, you
   can quotient by its commutator subgroup to get an abelian group;
   this is a left adjoint.  The right adjoint is the inclusion of
