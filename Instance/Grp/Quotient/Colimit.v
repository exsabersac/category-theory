(*
   * * The quotient as a colimit: coequalizer, cokernel, normal closure

   Awodey, “Category Theory”, 2nd ed., §4.2 (printed p. 83)
   [awodey:4.2:construction-factor-group] -- the factor group presented as
   a colimit; Riehl, “Category Theory in Context”, 2nd ed., §3.1
   Example 3.1.25 (printed p. 89) [riehl:3.1:example25] -- the coequalizer
   of a homomorphism with the trivial homomorphism is the quotient of the
   codomain by the normal subgroup generated by the image.
   nLab: https://ncatlab.org/nlab/show/cokernel
   Wikipedia: https://en.wikipedia.org/wiki/Coequaliser

   Two presentations of the same universal property, both obtained from
   Instance/Grp/Quotient.v's [hom_theorem] rather than reproved:

   - G/N is the COEQUALIZER of the inclusion N ↪ G against the trivial
   homomorphism ([quot_IsCoequalizer]), equivalently the COKERNEL of
   that inclusion ([quot_IsCokernel]).  Awodey's “well-definedness of
   coset multiplication from normality” is discharged upstream, in
   [quot_rel_mul], and is not repeated here.

   - the coequalizer of an ARBITRARY φ : G → H with the trivial
   homomorphism is H modulo the NORMAL CLOSURE of the image
   ([normal_closure_IsCokernel]), which is Riehl's Example 3.1.25.
   The normal closure is the ≈-saturated inductive generation
   [InNormalClosure], and it is proved LEAST among normal subgroups
   containing the image ([normal_closure_least]), which is what earns
   the word “closure”.

   REUSE, not restatement.  [IsCokernel] is Structure/Kernel.v
   ([IsCokernel f e := IsCoequalizer f zero_mor q e]) with its API
   [cokernel_epic], [cokernel_desc], [normal_epi] and
   [cokernel_regular_epi]; nothing of that is redefined, and the
   consequences below are those lemmas applied.

   THE FIRST CONCRETE COKERNEL IN THE TREE, measured rather than assumed:
   at the parent commit the token [IsCokernel] occurs in exactly two
   files, Structure/Kernel.v (where it is defined, with its API and the
   abstract lemmas [cokernel_of_any_kernel] and
   [normal_epi_cokernel_of_kernel]) and Structure/Abelian.v (where it
   appears in class fields, accessors and hypothesis binders, all
   conditional on [Abelian] or [HasCokernels], neither of which has an
   instance).  So no [IsCokernel] was ever inhabited at a concrete
   category, and the two witnesses below are the first.

   NO [HasCokernels] INSTANCE IS CLAIMED for [Grp], although
   [normal_closure_IsCokernel] gives a cokernel for every map: packaging
   it would mean committing [Grp] to a chosen cokernel in the class's
   sigma form, and nothing here needs that.  Likewise no
   [HasCoequalizers], since the coequalizer of a general parallel pair
   (f, g) is the quotient by the normal closure of the image of
   f · g⁻¹, which is not built.  CORRECTION (#450): [HasCoequalizers
   Grp] is now inhabited, by [Grp_HasCoequalizers_via_GAFT] in
   Instance/Grp/Colimit.v -- a [Definition], not a registered instance
   -- assembled from the pushouts and the initial object that the
   adjoint functor theorem gives at the diagonal functor (that file's
   header says how), rather than built from a quotient; the explicit
   normal-closure quotient of f · g⁻¹ is still not built, here or there,
   and that file's coequalizer does not compute. 

   --------
   * * 商作为余极限：共同化子、余核、正规闭包

   Awodey，《范畴论》，第2版，第4.2节（印刷第83页）
   [awodey:4.2:construction-factor-group]  -- 作为余极限表示的因子群；Riehl，《范畴论在上下文中》，第2版，第3.1节
   例3.1.25（印刷第89页）  [riehl:3.1:example25]  -- 同态与平凡同态的共同化子是
   余域对由像生成的正规子群的商。
   nLab:  https://ncatlab.org/nlab/show/cokernel 
   维基百科:  https://en.wikipedia.org/wiki/Coequaliser 

   同一普遍性质的两种表示，均来源于
   Instance/Grp/Quotient.v 的  [hom_theorem] ，而非重新证明:- G/N 是包含映射 N ↪ G 与平凡同态 ([quot_IsCoequalizer]) 的**余等化子**，等价地，它是该包含映射的**余核** ([quot_IsCokernel])。Awodey 关于“从正规性得出陪集乘法的良定性”在上游的 [quot_rel_mul] 中已经处理，这里不再重复。

   - 任意 φ : G → H 与平凡同态的余等化子是 H 除以像的**正规闭包** ([normal_closure_IsCokernel])，这是 Riehl 的例 3.1.25。正规闭包是≈-饱和归纳生成 [InNormalClosure]，并且被证明是在包含像的正规子群中**最小的** ([normal_closure_least])，这也正是“闭包”一词的由来。重用，而不是重述。[IsCokernel] 是 Structure/Kernel.v（[IsCokernel f e := IsCoequalizer f zero_mor q e]）的结构/内核，其 API 为 [cokernel_epic]、[cokernel_desc]、[normal_epi] 和 [cokernel_regular_epi]；其中没有任何内容被重新定义，下面的结论是应用这些引理的结果。

   树中第一个具体的余核，经过测量而非假设：在父提交中，标记 [IsCokernel] 恰好出现在两个文件中，即 Structure/Kernel.v（其定义位置，带有其 API 和抽象引理 [cokernel_of_any_kernel] 和 [normal_epi_cokernel_of_kernel]）以及 Structure/Abelian.v（其出现在类字段、访问器和假设绑定中，均取决于 [Abelian] 或 [HasCokernels]，二者都没有实例）。因此，在具体范畴中从未存在 [IsCokernel]，而下面的两个见证者是第一个。没有 [HasCokernels] 实例被声明用于 [Grp]，尽管 [normal_closure_IsCokernel] 为每个映射提供了余核：封装它将意味着将 [Grp] 提交给类的 sigma 形式中的一个选定余核，而这里没有任何地方需要那样。同样也没有 [HasCoequalizers]，因为一般平行对 (f, g) 的余等化是 f · g⁻¹ 的像的正规闭包的商，这还没有构建。更正 (#450)：[HasCoequalizers Grp] 现在由 [Grp_HasCoequalizers_via_GAFT] 在 Instance/Grp/Colimit.v 中实现 —— 一个 [Definition] ，不是注册实例 —— 它是从推余和伴随函子定理在对角函子处给出的初始对象组装而成（该文件的标题说明了方法），而不是通过商构建的；f · g⁻¹ 的显式正规闭包商仍然没有在这里或那里构建，并且该文件的余等化器无法计算。
*)

(* * ** The trivial homomorphism computes / * ** 平凡同态计算 *)

(*
 [zero_mor] in [Grp] is the constant map at the unit -- Awodey's “the
 constant map” -- and this is a computation rather than a claim, since
 [Grp_Zero] (Instance/Grp.v) has the one-element group on both
 sides.  Recorded with `≈` because the composite passes through
 [zero_coincide]; the underlying element equation is the point. 

 --------
 [zero_mor] 在 [Grp] 中是单位上的恒等映射 —— Awodey 所说的“恒等映射” —— 这是一种计算而不是主张，因为 [Grp_Zero]（Instance/Grp.v）在两侧都有一个单元素群。用 `≈` 记录，因为复合映射经过 [zero_coincide]；其底层元素方程是点。
*)
Lemma grp_zero_mor_is_unit {G K : GrpObject} (a : carrier G) :
  grp_map (@zero_mor Grp Grp_Zero G K) a ≈ grp_unit K.
Proof. simpl; reflexivity. Qed.

