 ** WHAT IS BUILT

 (1) [RMod_WellPoweredAt_up W]: [RMod R] is well-powered ONE UNIVERSE UP,
 with nothing assumed.  The index is [Submodule W], whose membership is
 [Type]-valued, and the witness is Spanning.v's round trip with nothing
 added: [wp_to] is [smod_subobj], [wp_from] is [subobj_smod] (the image
 submodule of the mono, its preimage carried as data) and [wp_to_from]
 is [smod_subobj_image_equiv].  It is the module counterpart of
 Instance/Grp/WellPowered.v's [Grp_WellPoweredAt_up].

 (2) [RMod_WellPowered_untruncate U : WellPowered (RMod R)], AT THE PIN,
 under the hypothesis [U : Untruncate].  The index is [PSubmodule W], a
 submodule whose membership is a [Prop].  [wp_to] reads it as a
 [Submodule] ([psm_sub]) and takes the inclusion; [wp_from] is the
 truncated image [pimage] (“has a preimage”, as the impredicative
 [Powerset_squash]); the round trip [pim_to_from] composes
 [sub_le_antisym] with [smod_subobj_image_equiv], and it spends [U]
 exactly once, in [pim_fn], to turn a truncated preimage back into a
 carried one.

 (3) [RMod_CoWellPowered_untruncate U : CoWellPowered (RMod R)], AT THE
 PIN, under the same hypothesis, over the same index.  [wp_to] sends [N]
 to the quotient object [pquot N], the projection W -> W/N; [wp_from]
 sends a quotient object to the kernel [pker e] of its epi, whose
 membership is the target's [Prop] mirror of “e x ≈ 0” (every module
 carries [cmon_prop] since the PR “algebraic carriers are sets”,
 2026-09-17).  The round trip [cwp_to_from] is [quot_equiv_of_cod_iso] at
 the codomain isomorphism [pre_iso] : cod e ≅ W/ker e, whose forward map
 [pre_map] sends each element of cod e to a preimage under e.  That
 preimage is DATA, and [pre_fn] obtains it by spending [U] on the
 [Prop]-level surjectivity [rmod_epic_surjective] returns.

 (4) [RMod_ring_separates]: R, as a module over itself, separates [RMod R]
 -- two homomorphisms W -> V that agree after every R -> W agree, by
 evaluating at [rmod_by_element], the homomorphism sending 1 to a given
 element.  [RMod_Generator R] packages it as a one-object [Generator],
 and [RModop_Cogenerator R] reads that, through [cog_of_gen], as a
 [Cogenerator] of (RMod R)^op: Watt's opening sentence, quoted above.
 Nothing is assumed.

 (5) [RMod_CoWellPoweredAt_up W]: [RMod R] is co-well-powered ONE
 UNIVERSE UP, with nothing assumed -- the dual of (1), and the
 counterpart of Instance/Sets/WellPowered.v's [Sets_CoWellPoweredAt_up];
 [RMod_CoWellPowered_up] is the family over every W.  The index is the
 quotient objects themselves, read at the carrier level: a codomain
 module Q ([RModObject] at RMod's object instance), a map e : W -> Q and
 [RModPropSurjective e].  [wp_to] rebuilds the epi by Instance/Mod.v's
 [rmod_prop_surjective_epic]; [wp_from] reads a quotient object's epi
 back through [rmod_epic_surjective], whose [Prop]-level answer is all
 the index asks for; the round trip is the identity isomorphism of the
 codomain.  [Epic] quantifies over every object, which puts [QuotObj] at
 the object universe; [RModPropSurjective] quantifies over the carrier
 only, which puts this index at [max(c+1, a)].  No preimage is needed as
 data, so [Untruncate] is not spent.

