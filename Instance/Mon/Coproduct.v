Definition mon_const (A B : MonS) : A ~{MonS}~> B :=
  @mk_mon_hom A B (fun _ => mon_one B)
    (fun _ _ _ => reflexivity (mon_one B))
    (fun _ _ => symmetry (mon_one_l B (mon_one B)))
    (reflexivity (mon_one B)).

Lemma triv_eta (a : poly_unit) : ttt = a.
