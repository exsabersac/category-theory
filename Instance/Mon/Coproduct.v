   * * 单子群的自由积，作为 Mon(Sets) 中的余积书籍：Mac Lane，《为在职数学家准备的范畴论》，第2版，GTM 5，第III.3节，第68页印刷版，练习4 (maclane:III.3:ex4) — “描述余积，并证明它们的存在性，在小范畴 Cat、单子 Mon 和图 Grph 的范畴中。” 该文件仅包含 Mon 条款。Cat 条款位于 Instance/Cat/Cocartesian.v 的 [Cat_Cocartesian]，早于该文件；Grph 条款不属于本文件，这里不对此作任何声明。书籍：Awodey，《范畴论》，第1版（CMU 预印本，2005年9月），第3.2节，第61-64页印刷版，示例3.5（单子的余积）和示例3.9（自由积，作为按显然关系划分的词）。nLab：https://ncatlab.org/nlab/show/free+product  nLab：https://ncatlab.org/nlab/show/coproduct  维基百科：https://en.wikipedia.org/wiki/Free_product哪一类幺半群，以及为什么其他选项被拒绝。这个树中的三个记录可以称为一个幺半群，并且选择是明确说明的，而不是任其漂移。(1) Theory/Algebra/Monoid/Hom.v 的 [Mon C] — 在一个单体范畴 C 中的内部单体，对象是 sigma { x : C & Monoid x }，态射是 sigma { f & MonoidHom }，态射等价是底层 C-态射的等价。在 [(Sets, ∏)] 实例化时，这是集合同类单体的范畴：[@Mon] 在三个基上被应用（早期草稿说是两个，遗漏了 Construction/Opposite/Monoidal.v）整个树范围内 — 在 [Sets] 中的 Theory/Algebra/Rig.v、Instance/Roster.v 和 Instance/Rng/MonoidRing.v，以及在 [Coq] 中的 Instance/Coq/Monoid/Free.v。Instance/Roster.v 将 [Sets] 命名为 [Mon_Sets]，而 Instance/Rng/MonoidRing.v 将同一项命名为 [MonSets]；两者都是 [Definition] 的普通 [@Mon Sets Sets_Product_Monoidal]，这正是此文件所建立的基础。在这里都不是必需的——Roster.v 是一个叶子索引，会引入 Instance/Top 及其卫星文件；实数是通过这些卫星文件之一引入的，而不是通过 Instance/Top 本身，因此“因此”夸大了标准库中的实数，而 MonoidRing.v 位于环层次结构中（Rng、Mod、多项式）——因此从代数文件依赖其中任何一个都会颠倒分层顺序。因此，这里的识别是通过这两行的 delta，而不是通过本文件的机器检查；有关文件中已检查内容的信息，请参见 ENGINEERING NOTES。

   (2) Construction/Deloop.v 的 [MonObject] —— 一个基本记录（承载 setoid、单位、运算、守恒性、结合性以及两个单位定律），由 delooping 字典和 Instance/Matr/GL.v 的 [UnitsOf] 使用。它在这里不可用，并且原因是决定性的而非美学上的：树中的任何类别都没有以 [MonObject] 作为对象（Structure/Groupoid.v 声明了一个 [MonHom] 记录，但没有从中组装任何类别），因此“余积”根本无法作为 [Cocartesian] 实例被表达。(3) Instance/Coq/Monoid/Free.v 的 [MonCoq] — [@Mon Coq Coq_Monoidal]，是关于 TYPES 而非 setoids 的 monoid。也就是说，这是一个不同的范畴，不能与 (1) 混为一谈；该文件中的自由 monoid 及其伴随存在于那里，而不在这里。

   Instance/CMon.v 的 [CMon] 是第四类类 monoid 对象，并且由于另一个原因被排除：其 [CMonObject] 拥有 [cmon_plus_comm] 字段，因此它的对象是交换 monoid，而且它们两个的自由积根本不属于该类型。在 [Sets]，幺半群张量是乘积集合，所以 [mu] 是一个来自乘积的集合态射，并且可以进行元素级推理。第一部分通过元素访问器重新阅读类（[mon_ob], [mon_mul], [mon_one], [mon_fun] 以及六个一行定律投影）。该工具包几乎是 Instance/Rng/MonoidRing.v 的 [mcar] / [mop] / [mone] / [mmap] / [mhom] 的重复拷贝；这种重复是有意为之，为上面(1)中的分层原因，并且每个成员都是类在字面对上应用的单一投影，本身不包含任何证明内容。构造。遵循Awodey的例子3.9：[FPTerm] 是在两个不相交的载体的并集上形成形式词的归纳类型，带有形式单位和形式乘法，[fp_eq] 是由单元律、两个加数自身的乘法和单位以及在每个源集合等价类的`≈`下的饱和生成的归纳同余。这是Instance/Ab/Tensor.v、Instance/Mod/Free.v 和 Instance/Grp/Pushout.v 的[AmalgamGrp] 的生成元和关系惯用法。[AmalgamGrp] 是最接近的现有技术，在设计固定之前其记录已被阅读：它是群的自由积，因此它具有[am_inv] 前体和两个在此没有对应且不被假定的逆律构造子。反身性是衍生的，而不是作为构造子取得的（单位情况通过 [fe_one_l] 两次经过 [fp_refl]）。没有构建交替规范形式，也不需要：商表示携带了普遍性质，下面的每个负结果都是通过从商映射 OUT 得到的，而不是通过对 [fp_eq] 的归纳得到的。交付的内容。对于 Mon(Sets) 的任意对象 A 和 B，有两个单射 [fp_injl] / [fp_injr]，余配对 [fp_merge] 及其唯一性条款 [fp_merge_unique]，以及 [Mon_Sets_Cocartesian : @Cocartesian (@Mon Sets Sets_Product_Monoidal)] — 该实例是完全通用的，对所有对象进行量化，没有附加条件。[Mon_Sets_Initial]（单元素幺半群）同时存在，因此可以通过 Structure/Cocartesian.v 自身的 [coprod_zero_l] / [coprod_zero_r] 在同构强度下陈述平凡因子的控制。优势，严格优先测量。以下每一项都通过 [eq_refl] 结束，并记录为 [Example]：对构造的余积词汇（[Coprod] = [FreeProd]，[inl] = [fp_injl]，[inr] = [fp_injr]，[merge] = [fp_merge]）；自由积的载体、乘法和单位（[FPCarrier]，[fp_mul]，[fp_one]）；每个注入的基本函数与相应构造器对应；两个 beta 规则逐点；组合的基本函数层面的两个 beta 规则；初始对象与 [TrivMon] 对应；平凡因子同构在左字母上的正向部分；以及四个见证计算。这些测试规则是定义性的，因为 [fp_eval] 是一个 [Fixpoint]，这也是为什么 [fp_merge] 的两个同态义务由 [reflexivity] 履行的原因。

   进行了四次严格尝试并被驳回，每一次都是在类型良好的项上真正的“无法统一”，而不是展开失败（通过去掉保护并阅读消息进行检查）:(a) [fp_merge A B Q f g ∘ fp_injl A B = f] — 两个贝塔规则 **不** 以 Mon(Sets) 同态的方程形式成立；
   (b) 在底层 SetoidMorphism RECORD 层面同样成立，[`1 (fp_merge A B Q f g ∘ fp_injl A B) = `1 f] — 它 **精确定位了障碍**：通过（接下来的）[fp_beta_l_fun] 底层函数完全一致，所以不同的是 [proper_morphism] 证书，[setoid_morphism_compose] 重新构建了它；
   (c) eta 法则 [fp_merge A B (FreeProd A B) (fp_injl A B) (fp_injr A B) = id] 作为整个同态；
   (d) 在变量单词上的 eta 法则逐点，这个不是封装伪造，而是真正内容，该陈述只有通过对单词的归纳才能证明。当然，所有三个余积方程在 `≈` 上都成立，这是从实例继承而来，并以名称重新表述为 [fp_merge_inl]、[fp_merge_inr] 和 [fp_merge_eta]。

