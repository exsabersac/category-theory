  (p : ttt ~{CycCat n}~> ttt) :
  { r : nat & ((r < 0 + n)%nat * SEqAt 0 n p (spath r))%type }.
Proof. apply (scat_arrow_normal 0 n Hn). Qed.

(* * ** (d) [s^5 = s^2] -- Seven Sketches §3.2.2 Exercise 3.19 / * ** (d) [s^5 = s^2] -- 《七个草图》第3.2.2节 练习3.19 *)

