Lemma z2_distinct : SEqAt 0 2 (spath 0) (spath 1) -> False.
Proof.
  intro H. apply (rho_nf_of_spath_eq 0 2) in H. discriminate.
Qed.

Lemma z2_exhaust (p : ttt ~{Z2Cat}~> ttt) :
  { r : nat & ((r < 2)%nat * SEqAt 0 2 p (spath r))%type }.
