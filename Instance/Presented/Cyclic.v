Proof.
  intro Hn. apply spath_eq_of_rho_nf; [ exact Hn | ].
  rewrite (rho_nf_t 0 n). rewrite rho_nf_ge by lia.
  rewrite Nat.sub_0_r, Nat.Div0.mod_same. reflexivity.
Qed.

