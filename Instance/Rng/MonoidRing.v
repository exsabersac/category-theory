(*
   * * The monoid ring R[M], and ℤ[M] as a universal arrow

   Book: Mac Lane, “Categories for the Working Mathematician”, 2nd ed.,
   GTM 5, §III.1, printed p. 59, Exercise 1 — the integral group
   ring exhibited as a universal arrow (maclane:III.1:ex1); the
   roster of free constructions on printed p. 56
   (maclane:III.1:remark2)
   nLab:      https://ncatlab.org/nlab/show/monoid+algebra
   nLab:      https://ncatlab.org/nlab/show/group+algebra
   Wikipedia: https://en.wikipedia.org/wiki/Group_ring

   WHAT THE EXERCISE ASKS, AND THE GENERALIZATION TAKEN.  Mac Lane's
   Exercise 1 names the INTEGRAL GROUP RING ℤ[G] and asks for it as a
   universal arrow.  The construction never uses inverses, so what is
   built here is the MONOID ring R[M] over an arbitrary base ring R — as
   issue #310 itself proposes (“better, monoid ring”) — with the group
   case read off it in Instance/Rng/GroupRing.v, where the target is the
   group of units and the exercise's own phrasing is recovered.
   Splitting the two costs nothing and buys the general statement: over
   ℤ the universal arrow below is stated against the whole of [Rng], not
   only against commutative rings, because ℤ is central in every unital
   ring.

   WHICH CATEGORY OF MONOIDS.  There are two records in this tree that
   could be called a setoid monoid, and letting them drift would be a
   mistake, so the choice is stated.  Construction/Deloop.v's
   [MonObject] is a bare record — carrier, unit, operation, three laws —
   used by the delooping dictionary, by Instance/Matr/GL.v's [UnitsOf]
   and by Instance/Grp.v.  Theory/Algebra/Monoid/Hom.v's [Mon C] is the
   category of INTERNAL monoids in a monoidal category, and at
   [(Sets, ∏)] its objects are the same mathematical thing packaged as a
   multiplication morphism out of the product setoid.  This file uses
   the SECOND, for one decisive reason: Theory/Algebra/Rig.v already
   builds [Rig_Forget_Mon : Rig ⟶ Mon Sets], the multiplicative-monoid
   forgetful functor, and a universal arrow needs a functor to be
   universal TO.  [MonSets] below abbreviates that category and
   [Rng_Forget_Mon] extends the donor functor along [Ring_Forget_Rig];
   the element-level reading is recovered by [mop] and [mone], and all
   four readings at a ring hold by [eq_refl] ([rng_forget_mon_carrier]
   and its three siblings).  Instance/Rep.v had to bridge two
   identically named [GrpObject] records with [grp_mon] and says so;
   this file avoids the bridge by never introducing the second record.

   HOW R[M] IS PRESENTED.  By generators and relations, in the pattern of
   Instance/Ab/Tensor.v, Instance/Mod/Free.v, Instance/Mod/Tensor.v,
   Instance/Rng/Polynomial.v and Instance/Vect/TensorAlgebra.v: [MRTerm]
   is a plain inductive of formal expressions built from scalars,
   generators, sum, negation and product, and [mr_eq] is the congruence
   generated by the ring laws (multiplication NOT commutative), the two
   clauses making the scalar inclusion a ring homomorphism, the two
   making the generator insertion a homomorphism of monoids, and ONE
   further equation: scalars commute with generators.  That last one is
   not decoration.  In the classical monoid ring R[M] = ⊕_{m∈M} R the
   element r·e commutes with 1·m because e·m = m·e = m, so the equation
   HOLDS there and has to be imposed if the construction is to be R[M];
   what the construction would present WITHOUT it is not investigated
   here and no claim about that is made.  Note that the equation is
   imposed between scalars and GENERATORS only, and correspondingly
   [mring_scal_central] proves the scalars central only under
   commutativity of R; no claim is made that centrality is FALSE over a
   non-commutative R.

   What is given up by this presentation is the coefficient
   decomposition: there is no support function, no coefficient
   extraction, no normal form, and hence no decision procedure for
   equality in R[M].  What is kept, and is what a reader of §III.1
   wants, is that the construction does not collapse — see the witnesses
   at the end, all obtained by mapping OUT into a concrete ring.

   STRENGTHS, MEASURED.

   - [eq_refl]: the extension restricted to generators IS the given
   monoid homomorphism and restricted to scalars IS the given ring
   homomorphism ([mring_extend_gen], [mring_extend_scal]); the four
   element-level readings of [Rng_Forget_Mon]; the universal arrow
   IS the insertion ([zmring_arrow_is_insert]); the free functor's
   object part IS [ZMonRing] ([MonoidRingFunctor_obj]); the unit of
   the adjunction IS the insertion ([zmring_unit_is_gen]); and the
   concrete evaluations in the witness section reduce.
   - `≈` only, and this was tried strictly first: preservation of ZERO
   and of ONE by the extension, for the same reason
   Instance/Rng/Polynomial.v records for K[x] — the zero and the one
   of R[M] are scalars, so the fold returns the structure map's value
   there and reaching the target's zero and one is that map's own
   preservation law.
   - `≈` only, unavoidably: the transposes obtained from
   [ump_universal_arrows], which is [Qed]-opaque.  The counit of
   [zmring_adjunction] is on that side and no [eq_refl] is claimed
   for it.

   WHAT IS DELIVERED.

   - [MonoidRing R M] for an arbitrary [RingObject] R and an arbitrary
   object M of [Mon Sets], with [mring_scal] and [mring_gen];
   - [mring_extend] and [mring_extend_unique], the universal property
   in element form, over the hypothesis [MRComm] that the images of R
   and of M commute — which is exactly what holds in R[M] itself, and
   that is a theorem here rather than prose: [mring_comm_self]
   discharges the hypothesis at the two insertions, and
   [mring_extend_self] then shows the resulting extension is the
   identity;
   - [zmring_universal_arrow : UniversalArrow M Rng_Forget_Mon] and
   [zmring_auniversal_arrow]: ℤ[M] is the free unital ring on the
   monoid M, in both of Theory/Universal/Arrow.v's encodings, with
   the left-adjoint reading [MonoidRingFunctor] and
   [zmring_adjunction : MonoidRingFunctor ⊣ Rng_Forget_Mon];
   - [mring_AAlg]: over a COMMUTATIVE base ring, R[M] is an object of
   Instance/Rng/Algebras/Associative.v's category of associative
   R-algebras — the scalars are central, by an induction that is a
   theorem rather than a further generating equation;
   - non-degeneracy, proved: [zmring_gen_not_scalar],
   [zmring_nontrivial] and [zmring_not_commutative], each by mapping
   out into the upper-triangular matrix ring of
   Instance/Rng/Algebras/Associative.v, whose multiplicative monoid
   is a non-commutative monoid available with no new construction.

   WHAT IS NOT DELIVERED.  No support, no coefficient uniqueness, no
   normal form, no decision procedure, no dimension.  No augmentation map
   R[M] → R and hence no augmentation ideal.  No comparison with
   Instance/Mod/Free.v's free module: R[M] is NOT shown to be the free
   R-module on M's carrier with convolution product.  That route was
   considered and not taken, and the reason is structural rather than a
   matter of taste.  Defining the convolution (f * g) at m as the sum
   over factorizations a·b = m needs the coefficients of an element to be
   DETERMINED by it, and Instance/Mod/Free.v does not supply that: its
   [fv_normal_form] proves every element equal to some finite formal
   combination, but its own deferral list says “No uniqueness of
   coefficients ... what is missing is not the existence of a
   linear-combination form but its CANONICITY”.  A convolution defined
   off a non-canonical list would have to be shown independent of the
   choice, which is the missing half.  So the reuse would not be the
   cheap one it looks like.  No monoid
   ring over a non-commutative R as an algebra, for the reason stated
   above.  The group-ring reading against the units functor lives in
   Instance/Rng/GroupRing.v, not here. 

   --------
   * * 单半群环 R [M]，以及 ℤ [M] 作为一个通用箭头

   书籍：Mac Lane，《为工作数学家而设的范畴论》，第2版，
   GTM 5，第III.1节，印刷第59页，练习1 —— 积分群
   环以通用箭头的形式展示 (maclane:III.1:ex1)；在印刷第56页
   的自由构造清单 (maclane:III.1:remark2)
   nLab: https://ncatlab.org/nlab/show/monoid+algebra 
   nLab: https://ncatlab.org/nlab/show/group+algebra 
   维基百科: https://en.wikipedia.org/wiki/Group_ring练习要求的内容以及所采取的概化。Mac Lane 的练习 1 指定了整数群环 ℤ [G]，并要求将其作为一个泛箭头。构造从未使用逆元素，因此这里构建的是任意基环 R 上的幺半群环 R [M]——正如问题 #310 本身所提出的（“更好的是幺半群环”）——其中群情况在 Instance/Rng/GroupRing.v 中被导出，在那里目标是单位群，并恢复了练习自身的表述。将两者分开没有任何损失，并且获得了更一般的结论：在 ℤ 上，下面的泛箭头是针对整个 [Rng] 而不是仅针对交换环来说的，因为 ℤ 在每一个带单位环中都是中心的。单数对象的类别。有两个记录在这棵树中可以被称为集合单数对象，把它们忽略将是一个错误，所以作出了选择。Construction/Deloop.v 的 [MonObject] 是一个简单记录——载体、单位、运算、三个定律——被 delooping 字典使用，也被 Instance/Matr/GL.v 的 [UnitsOf] 和 Instance/Grp.v 使用。Theory/Algebra/Monoid/Hom.v 的 [Mon C] 是单元范畴中内部单数对象的类别，在 [(Sets, ∏)] 其对象是同样的数学对象，以积集合单数对象的乘法态射形式打包。这个文件使用第二种，原因只有一个：Theory/Algebra/Rig.v 已经构建了 [Rig_Forget_Mon : Rig ⟶ Mon Sets]，即乘法单数对象的遗忘函子，而一个泛箭需要一个函子作为泛对象的对象。[MonSets] 以下缩写了该类别，并且 [Rng_Forget_Mon] 沿 [Ring_Forget_Rig] 扩展了供体函子；元素级别的读取通过 [mop] 和 [mone] 恢复，并且所有四个环上的读取通过 [eq_refl] 保持（[rng_forget_mon_carrier] 及其三个兄弟）。Instance/Rep.v 必须使用 [grp_mon] 连接两个同名的 [GrpObject] 记录，并且说明了这一点；此文件通过从未引入第二个记录来避免该桥接。[M] 是如何呈现的。通过生成元和关系，以 Instance/Ab/Tensor.v、Instance/Mod/Free.v、Instance/Mod/Tensor.v、Instance/Rng/Polynomial.v 和 Instance/Vect/TensorAlgebra.v 的模式：[MRTerm] 是由标量、生成元、加法、取反和乘法构建的形式表达式的普通归纳类型，而 [mr_eq] 是由环定律生成的同余（乘法非交换）、使标量包含成为环同态的两个条款，使生成元插入成为幺半群同态的两个条款，以及另外一个方程：标量与生成元交换。最后这一条并非装饰。在经典的幺半群环 R [M] = ⊕_{m∈M} R 中，元素 r·e 与 1·m 可交换，因为 e·m = m·e = m，所以该方程在此成立，并且如果构造要成为 R [M]，则必须强加；没有在这里研究如果不强加它会产生什么构造，也未对其作任何声明。注意，该方程仅在标量与生成元之间强加，相应地 [mring_scal_central] 仅在 R 交换时证明标量是中心元；未声明在非交换 R 上中心性为假。这个演示放弃了的是系数分解：没有支持函数，没有系数提取，没有规范形式，因此在 R [M] 中也没有等式的判定过程。保留下来的，也是 §III.1 的读者所希望看到的，是该构造不会崩溃——参见最后的证据，都是通过将 OUT 映射到具体环中得到的。

   强度，已测量。- [eq_refl]：限制在生成元上的扩展是给定的幺半群同态，限制在标量上的扩展是给定的环同态（[mring_extend_gen]，[mring_extend_scal]）；[Rng_Forget_Mon] 的四个元素级读数；泛箭头是插入（[zmring_arrow_is_insert]）；自由函子对象部分是 [ZMonRing]（[MonoidRingFunctor_obj]）；伴随的单位是插入（[zmring_unit_is_gen]）；并且在证据部分的具体求值会简化。- 仅限 `≈`，并且这是严格首先尝试的：保持零  
   和通过扩展保持一，出于相同原因  
   Instance/Rng/Polynomial.v 为 K [x] 记录 — R [M] 的零和一  
   是标量，所以 fold 返回结构映射在那里的值  
   并且到达目标的零和一是该映射自身的  
   保持定律。- 仅限 `≈`，不可避免：从  
   [ump_universal_arrows] 获得的转置，是 [Qed] -不透明的。  
   [zmring_adjunction] 的余单位在那一侧，并且未主张  
   对它有 [eq_refl]。

   所交付的内容。-  对于任意的 [RingObject] R 和任意 [Mon Sets] 对象 M，具有 [mring_scal] 和 [mring_gen] 的 [MonoidRing R M]；
   -  [mring_extend] 和 [mring_extend_unique]，在元素形式中的通用性质，在假设 [MRComm] 下，即 R 和 M 的像可交换——这恰好在 R [M] 本身成立，并且这里是一个定理而非文字描述：[mring_comm_self] 在两个插入点解除假设，然后 [mring_extend_self] 显示得到的扩展就是恒等；
   -  [zmring_universal_arrow : UniversalArrow M Rng_Forget_Mon] 和 [zmring_auniversal_arrow]：ℤ [M] 是幺半群 M 上的自由幺环，在 Theory/Universal/Arrow.v 的两种编码中都是如此，左伴随读法为 [MonoidRingFunctor] 和 [zmring_adjunction : MonoidRingFunctor ⊣ Rng_Forget_Mon]；
   -  [mring_AAlg]：在交换基环上，R [M] 是一个对象 of
   Instance/Rng/Algebras/Associative.v 的结合 R-代数类别 —— 标量是中心的，这是通过归纳法证明的定理，而不是进一步生成的方程式；
   - 非退化性，已证明：[zmring_gen_not_scalar]，[zmring_nontrivial] 和 [zmring_not_commutative]，每个都是通过映射到 Instance/Rng/Algebras/Associative.v 的上三角矩阵环实现的，其乘法幺半群是非交换的幺半群，无需新的构造即可使用。

   未提供的内容。没有支持、没有系数唯一性、没有规范形、没有判定程序、没有维数。没有增广映射 R [M] → R，因此也没有增广理想。没有与 Instance/Mod/Free.v 中的自由模进行比较：R [M] 并未被证明是 M 的载体上的自由 R-模，并且具有卷积积。该路径曾被考虑但未采纳，原因是结构性的，而非个人偏好。在 m 处定义卷积 (f * g) 为对分解 a·b = m 的求和，要求元素的系数必须由此决定，而 Instance/Mod/Free.v 并未提供这一点：其 [fv_normal_form] 证明了每个元素都等于某个有限形式组合，但其自身的延期列表中写道“系数不唯一……”缺少的不是线性组合形式的存在，而是它的规范性。定义在非规范列表上的卷积必须被证明与选择无关，这是缺失的那一半。因此，重用不会像看起来那样便宜。由于上述原因，没有非交换 R 上的幺半群环作为代数。针对单位函子阅读的群环内容位于 Instance/Rng/GroupRing.v，而不在这里。
*)

(*
   * ** The category of setoid monoids, at the element level

   [Mon Sets] states its laws through the tensor bifunctor and the
   unitors; the four readings below turn them back into element
   equations, which is what a construction by generators and relations
   consumes.  Each is one projection of the class applied at a literal
   pair, with no proof of its own. 

   --------
   * ** 集合单体的范畴，在元素层面上

   [Mon Sets] 通过张量双函子和单位子规定其定律；下面的四种解读将它们转换回元素方程，这正是生成元和关系构造所使用的。每一个都是类在字面上的一对上的一个投影，没有自己的证明。
*)

Definition MonSets : Category := @Mon Sets Sets_Product_Monoidal.

Definition mcar (M : MonSets) : SetoidObject := `1 M.

Definition mop (M : MonSets) (a b : carrier (mcar M)) : carrier (mcar M) :=
  @mu Sets Sets_Product_Monoidal _ (`2 M) (a, b).

Definition mone (M : MonSets) : carrier (mcar M) :=
  @eta Sets Sets_Product_Monoidal _ (`2 M) ttt.

Lemma mop_respects (M : MonSets) : Proper (equiv ==> equiv ==> equiv) (mop M).
Proof.
  intros a a' Ha b b' Hb.
  exact (proper_morphism (@mu Sets Sets_Product_Monoidal _ (`2 M))
           (a, b) (a', b') (Ha, Hb)).
Qed.

Lemma mop_assoc (M : MonSets) (a b c : carrier (mcar M)) :
  mop M (mop M a b) c ≈ mop M a (mop M b c).
Proof. exact (@mu_assoc Sets Sets_Product_Monoidal _ (`2 M) ((a, b), c)). Qed.

Lemma mop_one_l (M : MonSets) (a : carrier (mcar M)) : mop M (mone M) a ≈ a.
Proof. exact (@mu_unit_left Sets Sets_Product_Monoidal _ (`2 M) (ttt, a)). Qed.

Lemma mop_one_r (M : MonSets) (a : carrier (mcar M)) : mop M a (mone M) ≈ a.
Proof. exact (@mu_unit_right Sets Sets_Product_Monoidal _ (`2 M) (a, ttt)). Qed.

Definition mmap {M N : MonSets} (f : M ~{MonSets}~> N)
  : carrier (mcar M) → carrier (mcar N) := `1 f.

Lemma mmap_op {M N : MonSets} (f : M ~{MonSets}~> N) (a b : carrier (mcar M)) :
  mmap f (mop M a b) ≈ mop N (mmap f a) (mmap f b).
Proof. exact (@hom_mu Sets Sets_Product_Monoidal _ _ _ _ _ (`2 f) (a, b)). Qed.

Lemma mmap_one {M N : MonSets} (f : M ~{MonSets}~> N) :
  mmap f (mone M) ≈ mone N.
Proof. exact (@hom_eta Sets Sets_Product_Monoidal _ _ _ _ _ (`2 f) ttt). Qed.

(* ...and back: element-level data assembles into a morphism of [MonSets]. / ...并返回：元素级数据组装成 [MonSets] 的一个态射。 *)
Program Definition mhom {M N : MonSets}
  (f : carrier (mcar M) → carrier (mcar N))
  (fp : Proper (equiv ==> equiv) f)
  (fo : ∀ a b, f (mop M a b) ≈ mop N (f a) (f b))
  (fu : f (mone M) ≈ mone N) : M ~{MonSets}~> N :=
  (({| morphism := f |} : mcar M ~{Sets}~> mcar N); _).
Next Obligation.
  intros M N f fp fo fu.
  unshelve econstructor.
  - intros [a b]; simpl; apply fo.
  - intros []; simpl; apply fu.
Qed.

(*
   * The multiplicative-monoid forgetful functor of RINGS, obtained by
   extending Theory/Algebra/Rig.v's [Rig_Forget_Mon] along
   [Ring_Forget_Rig].  All four element-level readings hold on the
   nose. 

   --------
   * RINGS 的乘法幺半群忘记函子，通过沿 [Ring_Forget_Rig] 扩展 Theory/Algebra/Rig.v 的 [Rig_Forget_Mon] 获得。所有四个元素级读取都准确成立。
*)
Definition Rng_Forget_Mon : Rng ⟶ MonSets := Rig_Forget_Mon ◯ Ring_Forget_Rig.

Example rng_forget_mon_carrier (S : Rng) :
  mcar (Rng_Forget_Mon S) = rig_setoid S := eq_refl.
Example rng_forget_mon_op (S : Rng) (a b : carrier (rig_setoid S)) :
  mop (Rng_Forget_Mon S) a b = rig_mul S a b := eq_refl.
Example rng_forget_mon_one (S : Rng) :
  mone (Rng_Forget_Mon S) = rig_one S := eq_refl.
Example rng_forget_mon_map (S T : Rng) (f : S ~{Rng}~> T)
  (a : carrier (rig_setoid S)) :
  mmap (fmap[Rng_Forget_Mon] f) a = rig_map f a := eq_refl.

(** * The term algebra / * 代数一词 *)

Section MonoidRing.

Context (R : RingObject).
Context (M : MonSets).

Inductive MRTerm : Type :=
  | mr_scal : carrier (rig_setoid R) → MRTerm
  | mr_gen  : carrier (mcar M) → MRTerm
  | mr_add  : MRTerm → MRTerm → MRTerm
  | mr_neg  : MRTerm → MRTerm
  | mr_mul  : MRTerm → MRTerm → MRTerm.

