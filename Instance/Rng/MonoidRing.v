   给定一个环 S，一个从 R 出发的环同态 φ，以及一个从 M 出发到 S 的乘法幺半群的单同态 ψ，其像是可交换的，每个 R [M] 的形式元素在 S 中都有一个值。这个可交换假设正是使折叠尊重生成方程 [me_scal_gen] 的原因；它在 R [M] 本身中成立，并且在 ℤ 上，由于整数的中心性，它被直接解决。宇宙测量，以及为什么这个发展没有在某个节中。[Rig_Forget_Mon] — 因此 [Rng_Forget_Mon] — 只能在 [RigObject@{Set Set _}] 实例化，也就是只能在其载体和 [≈] 都存在于 [Set] 的装置上。这个限制来自捐赠者，是通过 Theory/Algebra/Rig.v 中 [rig_mult_monoid] 内的宇宙最小化引入的，而不是这里引入的，并且并未显示这是不可避免的；该捐赠者的一个带有显式绑定器的变体可以解除它。其唯一明显的结果是结构性的：一个节变量 [S : RingObject] 在 [Context] 命令时，其宇宙被固定，而在同一节中对 [Rng_Forget_Mon S] 的后续提及会被拒绝，因此整个评估发展以 R、M 和 S 作为普通参数在顶层陈述。在顶层，约束被吸收到每个常数自身的实例中，这就是为什么下面的内容会详细说明。对于结果的影响是，[zmring_universal_arrow]及其结果是关于其载体位于[Set]中的环的陈述——这一类包含了该树中每个具体的代数环（[Int_Ring]、[Q_Ring]、[Zero_Ring]、[F2_Ring]、[FracRing]、[ZPoly]和[UT2]都实例化，它们之间使用了下面的见证者）。它排除的唯一封闭[RingObject]是[CRingOb X]，即连续实值函数环：[Top]的开集严格位于其点之上，因此载体在[Set]之上，并且永远无法达到[RigObject@{Set Set _}]。Test/ProbeAlgebras.v 检测边界：在 [Int_Ring@{Set Set Set}] 上是一个正控制，相对于被拒绝的实例向上一个宇宙，对于捐赠者以及由其构建的函子。
