(* * ** (A) The principal ideal of a ring element / * **（A）一个环元素的主理想 *)

Definition RingComm (R : RingObject) : Type :=
  ∀ a b : carrier (rig_setoid R), rig_mul R a b ≈ rig_mul R b a.

(*
 Stated against [CRng_Sub] ITSELF rather than against [RingComm]'s own
 body: the obvious form [RingComm R = (∀ a b, … ≈ …)] is an [X = X]
 after delta, names [CRng_Sub] nowhere, and so could not break if that
 predicate changed.  This one can. 

 --------
 陈述的是针对 [CRng_Sub] 本身，而不是针对 [RingComm] 自身的主体：明显的形式 [RingComm R = (∀ a b, … ≈ …)] 是 [X = X] 在 delta 之后，名称 [CRng_Sub] 无处可寻，因此如果那个谓词改变，它不会被破坏。这个可以。
*)
Example ring_comm_is_CRng_predicate (R : RingObject) :
  RingComm R = @sobj Rng CRng_Sub R := eq_refl.

Section Principal.

Context {R : RingObject}.
Context (Rcomm : RingComm R).
Context (d : carrier (rig_setoid R)).

(* Membership is divisibility, with the cofactor carried as DATA (the library's [∃] is [sigT]), so nothing is chosen anywhere below. / 成员资格是可分性，余因子作为数据（库的 [∃] 是 [sigT]）携带，所以下面没有地方被选择。 *)
Definition divides (a : carrier (rig_setoid R)) : Type :=
  { k : carrier (rig_setoid R) & a ≈ rig_mul R d k }.

Program Definition PrincipalIdeal : Ideal R := {|
  idl_mem := divides
|}.
Next Obligation.
  intros a b Hab [k Hk]; exists k; now rewrite <- Hab.
Qed.
Next Obligation.
  exists (rig_zero R); now rewrite (rig_mul_zero_r R d).
Qed.
Next Obligation.
  intros a b [k Hk] [l Hl]; exists (rig_add R k l).
