(* * ** (B) The residue tower of a ring element / * **（B）环元素的剩余塔 *)

Section Tower.

Context {R : RingObject}.
Context (Rcomm : RingComm R).
Context (d : carrier (rig_setoid R)).

(*
 Powers of the generator, by recursion on [nat] rather than through
 [Z.pow]: the tower is indexed by [nat] and this keeps the stage
 equations definitional, with no lemma whose name differs across
 Coq 8.19/8.20 and Rocq 9.1. 

 --------
 生成元的幂，通过对 [nat] 的递归而非通过 [Z.pow]：这个塔由 [nat] 索引，这保持了阶段方程的定义性，没有任何引理的名称在 Coq 8.19/8.20 和 Rocq 9.1 中不同。
*)
Fixpoint dpow (n : nat) : carrier (rig_setoid R) :=
  match n with
  | O   => rig_one R
  | S k => rig_mul R d (dpow k)
  end.

Definition ResIdeal (n : nat) : Ideal R := PrincipalIdeal Rcomm (dpow n).

Definition ResRing (n : nat) : RingObject := QuotientRing (ResIdeal n).

(*
 The tower's stages are nested: a multiple of d^(n+1) is a multiple of
 d^n.  This is the ONE arithmetic step the tower costs, and it is the
 SECOND of the file's two [Rcomm] spends (see the header): [dpow (S n)]
 is [d * dpow n], so the witness [d * k] must move [d] past [dpow n]. 

 --------
 塔的各个阶段是嵌套的：d^(n+1) 的倍数是 d^n 的倍数。这是塔所需的唯一算术步骤，并且是文件的两个 [Rcomm] 消耗中的第二个（参见文件头）：[dpow (S n)] 是 [d * dpow n]，因此见证 [d * k] 必须将 [d] 移过 [dpow n]。
*)
Lemma res_ideal_succ_sub (n : nat) (a : carrier (rig_setoid R)) :
  idl_mem (ResIdeal (S n)) a → idl_mem (ResIdeal n) a.
Proof.
  intros [k Hk]; exists (rig_mul R d k).
  rewrite Hk; simpl.
  rewrite (rig_mul_assoc R d (dpow n) k).
  rewrite <- (rig_mul_assoc R (dpow n) d k).
  rewrite (Rcomm (dpow n) d).
  now rewrite (rig_mul_assoc R d (dpow n) k).
Qed.

(*
 So the projection onto the n-th stage kills the (n+1)-st ideal, and the
 quotient's own universal property supplies the transition map.  Nothing
 is chosen: [rquot_med] is the unique such factorisation. 

 --------
 因此，投影到第 n 阶阶段会消去第 (n+1) 阶理想，而商本身的普遍性质提供了过渡映射。没有任何选择：[rquot_med] 是唯一的这样的分解。
*)
(*
 Built in tactic mode so that elaboration is directed BY THE GOAL TYPE.
 The term-mode [existT _ …] form compiles on Rocq 9.1 and is REJECTED on
 Coq 8.19: there the second component elaborates with [rquot_proj … a]
 written out rather than through [RKills]'s [rig_map h a], and the two
 do not unify.  Stating the type first inserts the coercion where the
 record wants it. 

 --------
 内置战术模式，以便根据目标类型指导展开。术语模式 [existT _ …] 形式可在 Rocq 9.1 上编译，但在 Coq 8.19 上被拒绝：在那里，第二个组成部分使用 [rquot_proj … a] 直接展开，而不是通过 [RKills] 的 [rig_map h a]，而这两者无法统一。先声明类型会在记录需要的地方插入强制转换。
*)
Definition res_kills (n : nat) : RKills (ResIdeal (S n)) (ResRing n).
Proof.
  exists (rquot_proj (ResIdeal n)).
  intros a Ha.
  exact (rquot_proj_kills (ResIdeal n) a (res_ideal_succ_sub n a Ha)).
Defined.

Definition res_proj (n : nat) : ResRing (S n) ~{Rng}~> ResRing n :=
  rquot_med (ResIdeal (S n)) (res_kills n).

(* The transition is the quotient projection read downstairs: composing it with the (n+1)-st projection gives the n-th, on the nose from the mediator's own commutation. / 过渡是楼下读取的商投影：将其与第 (n+1) 投影组合会得到第 n 个，从中介自身的换位中直接得到。 *)
Lemma res_proj_commutes (n : nat) :
  res_proj n ∘ rquot_proj (ResIdeal (S n)) ≈ rquot_proj (ResIdeal n).
Proof. exact (rquot_med_commutes (ResIdeal (S n)) (res_kills n)). Qed.

(*
 The action on an arbitrary order proof, by recursion on the derivation
 -- the [Construction/Chain.v] idiom, one shape down. 

 --------
 对任意顺序证明的操作，通过对推导的递归——[Construction/Chain.v] 成语，下降一个形状。
*)
Fixpoint res_hom {m n : nat} (f : le_t m n) : ResRing n ~{Rng}~> ResRing m :=
  match f with
  | le_t_n     => id
  | le_t_S f'  => res_hom f' ∘ res_proj _
  end.

Lemma res_hom_trans {m n k : nat} (a : le_t m n) (b : le_t n k) :
  res_hom (le_t_trans a b) ≈ res_hom a ∘ res_hom b.
Proof.
  induction b as [| k' b' IH].
  - cbn [res_hom le_t_trans]; now rewrite id_right.
  - cbn [res_hom le_t_trans]; rewrite IH; now rewrite comp_assoc.
Qed.

(*
 Stated at exactly the functor's shape, so the obligation below needs no
 conversion of [Omega^op]'s composition. 

 --------
 精确地按照函子形状陈述，因此下面的义务不需要对 [Omega^op] 的组合进行转换。
*)
Lemma res_hom_comp {x y z : nat}
  (f : y ~{Omega^op}~> z) (g : x ~{Omega^op}~> y) :
  res_hom (f ∘ g) ≈ res_hom f ∘ res_hom g.
Proof. exact (res_hom_trans f g). Qed.

(* [Omega]'s hom-setoid is strict equality, so respectfulness is [subst]. / [Omega] 的同态集合是严格相等，因此保持性是 [subst]。 *)
Lemma res_hom_respects {x y : nat} (f g : x ~{Omega^op}~> y) :
  f ≈ g → res_hom f ≈ res_hom g.
Proof. intro H; simpl in H; subst; reflexivity. Qed.

Lemma res_hom_id (x : nat) :
  res_hom (@id (Omega^op) x) ≈ @id Rng (ResRing x).
Proof. reflexivity. Qed.

(*
 Assembled as an explicit record rather than through [Program]: the
 obligation [Program] generates for [fmap_comp] presents its two sides
 under an unreduced beta-redex of the [fmap] field, against which
 neither orientation of the composition law unifies, while the law
 stated at the functor's own shape ([res_hom_comp]) fits the field
 directly.  Measured, not preferred. 

 --------
 作为明确记录组装，而不是通过 [Program]：[Program] 为 [fmap_comp] 产生的义务在 [fmap] 字段的未约简 β-约项下呈现其两面，对于该字段，组合律的任意一种方向都不能统一，而在函子自身形状（[res_hom_comp]）下陈述的律直接适用于该字段。经过测量，而非偏好。
*)
Definition ResTower : Omega^op ⟶ Rng :=
  @Build_Functor (Omega^op) Rng ResRing (fun _ _ f => res_hom f)
    (fun x y f g H => res_hom_respects f g H)
    res_hom_id
    (fun x y z f g => res_hom_comp f g).

End Tower.

