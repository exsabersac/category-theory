 Mac Lane's roster entry for Top, and Awodey's Example 3.6.  The
 coproduct of two spaces is their disjoint union: points are the sum of
 the two point sets, and a subset is open exactly when its two
 restrictions are.

 AWODEY'S CLAUSE IS THE DEFINITION, NOT A THEOREM.  Example 3.6 records
 alongside the construction that O(X + Y) ≅ O(X) × O(Y).  Here that is
 not something to prove: [sum_open] IS the conjunction of the two
 restrictions' openness, so [sum_open_is_pair] closes by [eq_refl].
 What that costs is the observation that no topology needs GENERATING —
 the naive “generated by the images of the two topologies” phrasing
 would quantify over opens of the summands, and Instance/Top.v's
 [IsOpen] field cannot host such a predicate at the same universe
 (Instance/Top/Homotopy.v measures exactly that wall for the
 cylinder).  The restriction phrasing only APPLIES [IsOpen] to a
 restricted predicate, so it stays at the space's own level, and this
 file adds no universe constraint of its own.

 THE TEMPLATE.  Instance/Top.v already builds a sum topology,
 for the cokernel pair of a single map: [CP_open] is a triple of a
 respect-the-gluing clause and the two restrictions.  The coproduct is
 that construction with the gluing removed, and the removal is what
 makes the first clause disappear rather than become trivial — over the
 sum setoid, equivalent points always lie in the SAME summand
 (Lib/Datatypes.v's [sum_setoid] sends the cross cases to [False]),
 so respect follows from each summand's own [open_proper] and is proved
 here rather than assumed.

 WHAT IS PROVED, AND AT WHAT STRENGTH.  [Top_Cocartesian] is the
 deliverable: [@Cocartesian Top], the tree's first coproduct structure
 on Top (Instance/Top.v registers only [Top_Terminal] and
 [Top_Initial], and does not even require Structure/Cocartesian.v).  The
 injections and the copairing are the evident maps at LEIBNIZ EQUALITY
 ([Top_inl_is_inl] and siblings, [eq_refl]), and so is the carrier
 ([Top_coprod_carrier]).  With Instance/Top.v's [Top_Initial] as unit,
 Structure/Cocartesian.v's [coprod_zero_l], [coprod_comm] and
 [coprod_assoc] come for free and are exhibited.

 A CLAUSE OF AWODEY'S EXAMPLE, PROVED: the disjoint union of two
 DISCRETE spaces is discrete ([sum_of_discrete]), stated as a
 biconditional between [sum_open] and [discrete_open] rather than as an
 isomorphism.  It is NOT an identification “on the nose” in this
 tree's sense: the [eq_refl] form would fail, [sum_open W] being a
 conjunction of two quantifications over the summands where
 [discrete_open W] (Instance/Top.v) is a single one over the sum.
 That is the fact Instance/Top/Forgetful.v
 asserts in prose when it says the coproduct of two one-point spaces is
 the two-point discrete space; the one-point instance
 ([point_sum_discrete]) is recorded here, but no identification with
 that file's [Bool_Discrete] is made — the carriers are [unit + unit]
 and [bool], different types.

 UNIVERSES, MEASURED.  [Sum_Top@{u u0} : TopSpace@{u} → TopSpace@{u0}
