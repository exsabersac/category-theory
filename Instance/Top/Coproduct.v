(* * ** The disjoint union of discrete spaces is discrete / * ** 离散空间的离散空间并集是离散的 *)

(* Stated as a biconditional between the two openness predicates, so the two topologies are identified on the nose rather than through a comparison map. / 表述为两个开性谓词之间的双条件，因此这两个拓扑在本质上是相同的，而不是通过比较映射来识别。 *)
Theorem sum_of_discrete (A B : SetoidObject)
        (W : sum_carrier (Discrete_Top A) (Discrete_Top B) → Type) :
  IsOpen (Sum_Top (Discrete_Top A) (Discrete_Top B)) W
    ↔ (∀ u v : sum_carrier (Discrete_Top A) (Discrete_Top B),
          u ≈ v → W u → W v).
Proof.
  split.
  - intros HW u v Huv Wu.
    exact (sum_proper (Discrete_Top A) (Discrete_Top B) W HW u v Huv Wu).
  - intro H.
    split.
    + intros a b Hab Wa.
      exact (H (Datatypes.inl a) (Datatypes.inl b) Hab Wa).
    + intros a b Hab Wa.
      exact (H (Datatypes.inr a) (Datatypes.inr b) Hab Wa).
Qed.

(*
 The one-point instance: the coproduct of two copies of the terminal
 space is discrete on [unit + unit].  Instance/Top/Forgetful.v says
 this in prose; no identification with that file's [Bool_Discrete] is
 claimed, the carriers being different types. 

 --------
 单点实例：两个终端空间的余积在 [unit + unit] 上是离散的。Instance/Top/Forgetful.v 用散文说明了这一点；没有声称与该文件的 [Bool_Discrete] 进行识别，因为承载类型不同。
*)
Corollary point_sum_discrete
        (W : sum_carrier Point_Top Point_Top → Type) :
  IsOpen (Sum_Top Point_Top Point_Top) W
    ↔ (∀ u v : sum_carrier Point_Top Point_Top, u ≈ v → W u → W v).
Proof. exact (sum_of_discrete _ _ W). Qed.

(** ** Non-vacuity / ** 非空性 *)

(* The two injections of [1 + 1] land on different points: the singleton subset of the left copy is a subset that one hits and the other does not. So the coproduct does not collapse. / [1 + 1] 的两次注入落在不同的点上：左边副本的单元素子集是一个被一次击中而另一次未击中的子集。因此，余积不会坍塌。 *)
Definition left_point (u : sum_carrier Point_Top Point_Top) : Type :=
  match u with
  | Datatypes.inl _ => poly_unit
  | Datatypes.inr _ => False
  end.

(* It is open, which is what makes the two copies topologically distinct and not merely set-theoretically so. / 它是开集，这就是使得这两个副本在拓扑上不同，而不仅仅是在集合论上不同的原因。 *)
Lemma left_point_open : IsOpen (Sum_Top Point_Top Point_Top) left_point.
Proof.
  split.
  - exact (open_whole Point_Top).
  - exact (open_empty Point_Top).
Qed.

Lemma point_sum_injections_differ :
  continuous_map (Top_inl Point_Top Point_Top) ttt
    ≈ continuous_map (Top_inr Point_Top Point_Top) ttt → False.
Proof. exact (fun H => H). Qed.
