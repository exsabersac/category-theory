(*
 The schema Mac Lane's remark needs: if a property P of setoid algebras
 holds of two algebras but not of their product, then no equational
 theory over that signature has exactly the P-algebras as its models.
 Stated over a FIXED signature — this is not Birkhoff's HSP theorem and
 does not pretend to be. 

