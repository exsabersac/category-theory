(*
   * ** Block F: products, and what they rule out

   Varieties are closed under products, and that is the lever for
   Mac Lane's field non-example: a class of algebras that is NOT closed
   under products cannot be the models of any equational theory over
   its signature, whatever the equations are.

   [soa_prod] is the componentwise CONSTRUCTION and nothing more is
   claimed for it: the two projections are shipped, but no pairing map,
   no triangle and no uniqueness, so it is NOT established here to be
