(* Satisfaction, now up to the carrier's own `≈` rather than Leibniz [=]. The equations are read through [soa_alg], so [UA.lhs] and [UA.rhs] are exactly Instance/Comp.v's. / 满意度，现在取决于承运人的 `≈`，而不是莱布尼茨 [=]。方程通过 [soa_alg] 读取，因此 [UA.lhs] 和 [UA.rhs] 恰好是 Instance/Comp.v 的。 *)
