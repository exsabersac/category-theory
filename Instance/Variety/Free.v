 Mac Lane §V.6, 书页 124 (PDF 页 133–134)。 对于任何代数类，其底层集合函子都有一个左伴随——集合上的自由代数——Mac Lane 从伴随函子定理得到它，解集是由像生成的子代数。 这个文件直接得到它。 之前的一个修订写道：“原因更多是衡量而非风格化”。 自 #450 起，Mac Lane 的路径也在树中，并且直接的方法由于以下“为什么不使用 GAFT”中的原因仍然保留。

 ** 唯一的设计决策，以及关于它的实际情况该标题的早期版本用大写字母写道，自由多样体的对象“不能存在于 #440 的 [Variety E] 中”，因为按一个关系对类型取商是 Coq 不提供的。这是不正确的，而且是通过构造而非论证来反驳的：两个生成元的自由交换半群确实存在，作为 #440 的 Leibniz [Variety CommEq] 的对象，通过按可判定的全顺序将项整理到标准形式中构建，其通用箭头通过本文件使用的相同 [universal_arrow_from_UMP] 封装。同一个点的廉价树内证据是 Test/ProbeVarietyFree441.v 的 [free_empty_eq_leibniz]：完全没有方程，项代数已经是一个 Leibniz-多样体对象。

 真正正确的，并且是设计的实际原因:(1) 一旦方程起作用，术语代数（TERM ALGEBRA）就不再是莱布尼茨-品类对象。[free_magma_not_comm_leibniz] 对交换幺半群证明了这一点——[x * y] 和 [y * x] 是不同的术语——这是相对于在布尔代数下 [xorb] 控制显示该形状是可居住的情况。所以天真的构造，即 Mac Lane 的文章描述的方式，并不能落入 [Variety E] 中。(2) 要让它落地，需要一个演示的规范形式：对每个同余类可计算地选择一个代表，这就是解决该演示的词问题。对于交换幺半群这是可行的，但并非统一可行——存在有限呈现的代数理论，其词问题是不可判定的，因此没有在 ⟨Ω,E⟩ 中统一的构造可以走这条路。这个文件的交付成果正是这样一个统一的构造：[Free_Variety] 对每一个 [E] 都定义，没有任何地方的可判定性假设。所以集合载体提供的是一致性，而不是存在性。商集成为在同一个载体上选择 `≈`，而不是一个新类型——设计文件 Instance/Sets/Quotient.v 的头部对于集合的商集有说明——这两种方式特意以相同的形式构建，都是作为一个代数范畴的 [Sub]，因此它们被看作是兄弟关系；#440 的 [Instance/Variety.v] 的 [Variety_sub] 是本文件遵循的模型。

 ** 为什么一般理论是无公理的，尽管 #440 的 [GroupVariety] 不是这是使文件成为可能的事实，并且正因为它看起来像是对 #440 的矛盾而值得明确说明。方程在这里仅通过 [EqSignature] 的 [lhs_natural] 和 [rhs_natural]（Instance/Comp.v）进入，而下面的每个构造都消耗这些字段；没有一个证明任何一个。#440 的 [functional_extensionality_dep] 是构建特定 [EqSignature]——对群律中那两个自然性字段进行释放的成本——而不是使用它的成本。因此：一般的伴随在全局上下文中是封闭的，而在 [UA.GroupEq] 上实例化它则不是。下面的 [FreeGroupOn] 和 [FreeGroup_adjunction] 恰好由于继承的原因承载了该公理，并且没有受限；深度为 1 的 [CommMagmaFree] 是封闭的，并且确实如此。

 ** 对项的合同是无公理的，而 #440 说的情况则相反Instance/Variety/Clone.v 中的“未交付”模块因如下原因拒绝了一个集合论等价类：在某个节点上，对于 [Tree]，传递性必须对 [tree_equiv] 进行反演，需要 [existT] 在一个没有可判定等式的 [operation S] 上具有单射性，因此可能会风险 [Eqdep] / [JMeq_eq]。这个理由是错误的，现在模块已经说明了这一点：将对称性和传递性设为构造器而非定理意味着永远不会进行反演。然后通过对树的普通归纳法得出 [tc_refl]。更正 (#450)。先前的修订中写道：“该关系必须是 [Type] 值，而不是 [Prop] 值，因为 [Setoid] 的 [equiv] 是一个 crelation，且 [free_alg_ext_respects] 消除了对它的推导。” [tree_equiv] 现在是 [Prop] 值。前半部分从未是理由：一个 [crelation] 字段通过累积性接受 [Prop] 值的关系，这就是 [Tree_Setoid] 现在使用它的方式。后半部分不再是理由：单次消除到 [Type] 分类目标 [free_alg_ext_respects]，现在通过 TARGET 的 [soa_prop]（下一节）：[pequiv_to] 首先将目标转换为 [Prop]，并且推导被消除到该目标中，正如 Instance/Mod/Free.v 的 [fv_eval_respects] 在 PR “代数承载体是集合”中所做的那样。移动的原因是 [soa_prop]（下一节）：[FreeSOA] 的 `≈` 必须可以与一个 [Prop] 值的关系相互推导，并且一个 [Prop] 值的 [tree_equiv] 就是该关系本身。必要性是被论证的，而非测量的：没有构建或探测任何替代方案（除了一个单独的 [Prop] 镜像之外的 [Type] 值的 [tree_equiv]）。[Prop] 类型也是 Instance/Variety/Colimit.v 的解集所使用的：它们的核同余只作为 [Prop] 的载体大小（Structure/Complete.v 的大小说明，第1项）。[About tree_equiv] 现在报告“只能被消去以产生类型为 SProp 或 Prop 的值”，而 Test/ProbeVarietyFree441.v 的 n4 将对 [Type] 类排序目标进行消去的拒绝与 [Prop] 类排序控制联系起来。它的 [_rect] 和 [_rec] 消除器已消失（[_ind] 和 [_sind] 仍然存在），并且没有任何门线命名它们。

 [tc_gen] 关联的是在 GENERATOR 集合中为 `≈` 的生成器，而不仅仅是相等的那些；这就是使自由构造成为 [Sets] 上的函子而不是在裸类型上的原因。

 ** 携带者的 `≈` 是一个命题（#450）[SetoidOpAlgebra] 携带第四个字段，[soa_prop : PropEquiv (is_setoid soa_obj)] (Lib/Setoid/Propositional.v)，与 PR “代数载体是集合” 在 CMon、Rig 和 Grp 的对象记录上放置的属性相同。#450 之前存在的六个构造点提供了它：来自同余本身的 [FreeSOA] ([PropEquiv_of_relation])，作为因子结合的 [soa_prod]，[leibniz_soa] 和 [F2] 作为 [eq_PropEquiv]，Instance/Variety/Spanning.v 中沿第一投影的 [sa_soa] ([sigma_first_PropEquiv])，以及 Test/ProbeVarietyFree441.v 中的 [BoolCommMagma] 作为 [eq_PropEquiv]。#450 添加的三个项是 Instance/Variety/Limit.v 中的 [svlim_soa] (来自组件字段的 Instance/Sets/Propositional.v 的 [limit_PropEquiv]) 和 Instance/Variety/Colimit.v 中的 [VQ_soa] 及 [FQ_soa]（索引同余本身）。在#450之前，用[About]在[Set Printing Universes]下对树进行测量：[SetoidAlgs]保持其七个宇宙绑定器，并恰好获得[Set < u1]，其对象宇宙；[SVariety]保持十五个并获得[Set < u7]；记录的分类从[Type@{max(u,u0,u1+1,u2+1)}]变为[Type@{max(Set+1,u,u0,u1+1,u2+1)}]；而[SVariety_Forget]则从十个宇宙绑定器变为十一。与CMon不同，这里没有任何类别需要手动固定。Blocks F和H的定理对[SetoidOpAlgebra]进行量化，因此自#450以来，它们涵盖的代数的`≈`是命题，并且它们并未全部变得更强。Block F的[soa_prod_satisfies]直接对其代数A和B进行量化，因此现在说的更少：通过忽略[soa_prop]，旧的陈述可以推导出新的陈述，而新的陈述关于`≈`不是命题的代数什么都没有说明。Block F 的模式 [not_equationally_definable] 现在要求命题见证 A 和 B（较弱），而其正确性和完备性假设覆盖的代数较少（较强），因此它与旧形式不可比。只有 Block H 的两个定理，其见证 [F2] 是固定的并且承载 [eq_PropEquiv bool]，仅在假设中发生变化，并且每个定理都变得（弱地）更强（Block H 开始的评论如此说明）。

 ** 为什么不用 GAFT —— 以及自 #450 起，也不用 GAFT

