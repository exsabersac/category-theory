 The direct construction stays the primary one for two measured
 reasons.  It is TRANSPARENT where the other is not: [GAFT] ends in
 [Qed], so the GAFT left adjoint supports none of the [eq_refl]
 readbacks Test/ProbeVarietyFree441.v states for this one (its
 [p441_left_adjoint_obj] among them).  And GAFT does not avoid the
 construction: every member of the congruence-indexed solution set is
 this file's term algebra under a coarser `≈`, so the theorem reaches
 the free algebra only by way of the carrier built here.

