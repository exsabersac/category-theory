 第V.7节（“子对象与生成元”），书本第127-128页（PDF 第136-137页）。
 定义6称一个箭头 f : x → G 为生成箭头（SPANNING），当它不通过 a 的任何真子对象时；引理2指出，当 A 的每一族子对象都有交集且 G 保持这些交集时，每个箭头都可以通过一个生成箭头进行分解，因此来自 x 的生成箭头形成一个解集；备注1是 Mac Lane 关心的应用——对于某个品类的底层集合函子，生成分解就是由像生成的子代数，而它产生的解集就是自由代数构造所依赖的对象。此文件是注解，而不是引理。定义是 Adjunction/SpanningArrow.v 中的固定定义——[SubFactorsThrough]、[Spanning] 和 [SpanningArrowsOutOf]——这里没有重新命名或重述它们。一般的引理是 #448 的另一部分，这里不再重复。

 ** 为什么注解是直接证明的，而不是通过引理证明引理取了给定箭头所经过的所有子对象的交集，在这个库中是 Theory/Subobject/Lattice.v 的 [sub_wide_intersection]（及其在 Structure/Pullback/Wide.v 的 [HasWidePullbacks] 下的 [sub_intersection]）。两者都希望在环境范畴中有宽拉回，而 [SVariety] 在 tree 中没有：在这个工作树上，每个除了这个之外命名 [HasPullbacks] 或 [HasWidePullbacks] 并且也命名 [SVariety] 的文件数量为零（使用命令 find . -name '*.v' | xargs grep -ln 'HasWidePullbacks\|HasPullbacks' | xargs grep -l 'SVariety' | wc -l，排除了这个作品的三个文件——这个文件，Adjunction/SpanningArrow.v 和 Test/ProbeVarietySpanning448.v——通过 find 的 -not -path；如果不排除，该命令报告的正是这三个文件，并且没有其他更早的文件）。构建该实例本身就是一个独立的开发工作，超出了此处的范围，因此下面的跨度分解是手工构造的，就像 Mac Lane 的文字所做的那样——通过生成子代数而不是通过交叉子对象——并且所使用的两个 Lattice.v 事实是被传递的，从未重新证明过：[sub_top_greatest] 和 [sub_le_antisym]，都被 Adjunction/SpanningArrow.v 的 [spanning_forces_top] 使用（首次在此文件中证明，并在集成时提升到那里，同时还有 [sub_le_top_iso]）。

 ** 这里的子代数是什么，以及为什么闭包是归纳的Instance/Variety/Free.v 的 [SVariety E] 是集合代数的一个完全子类别（它的 [SVariety_sub]，该文件证明它是完全的），所以子代数是在承载体上的一个成员资格谓词，它尊重 `≈` 并对每个运算封闭：下面的 [SubAlg]，三个字段。它承载一个集合代数（[sa_soa]），它满足 E 因为 A 满足 E（[sa_satisfies]，依据 Instance/Comp.v 的 [lhs_natural] 和 [rhs_natural] 以及包含映射——完全按照 Free.v 的积来消费这些字段，从不单独证明），并且它的包含映射是单射（[sa_incl_monic]），所以它是理论/Subobject.v 意义下 A 的 [SubObj]。由 h : X → G A 的像生成的子代数是 [SubGen]，这是一个带有三个构造子的归纳谓词（一个生成元在其中，它遵守 `≈`，它在运算下封闭）。另一种教材定义——包含该像的所有子代数的交集——没有被选择，原因是宇宙相关的问题而不是个人偏好：该谓词对 [SubAlg E A] 进行量化，其自身的 [sa_mem] 字段落在谓词必须处于的宇宙中，因此交集本身在同一级别上并不是 [SubAlg]。归纳闭包没有这个问题，这也使得最小性条款 ([sgen_least]) 变成了一个简单的递归。  

 ** [SVariety] 的单射恰好是注入映射跨越证明需要将单态变为单射，而这个方向不是形式化的：它需要一个探针对象。对于 [SAlgHom] 来说没有这样的桥（测量：除了这个文件，没有名为 [SAlgHom] 或 [SVariety] 的文件也命名为 [Monic]）；该树为其他类别有桥 —— 除了这项工作的两个文件外，还有 40 个非 Test 文件同时命名了 [Monic] 和 [injective]（grep -rlE '\bMonic\b' --include='*.v' . | grep -v /Test/ | xargs grep -l injective），包括通用的 Theory/Concrete/Morphisms.v [concrete_injective_monic] —— 并且都不适用，因为没有文件给 [SVariety E] 一个 [Concrete] 实例。在 Instance/Sets.v（[injectivity_is_monic]）中，探针是单例；而这里是一个单生成元的自由代数，[Free_Variety E unit_setoid_object]，而且从它出来的两个常量映射被 Free.v 的 [free_alg_hom_unique] 分开。那是 [svariety_monic_injective]；从 [Sub] 的逐点同值集合看，倒过来的 [svariety_injective_monic] 是直接的，并且 [svariety_monic_iff_injective] 是等价条件。借助它，[svariety_iso] 是 Instance/Sets.v 中 [bijective_is_iso] 的类似物：一个单射且具有分裂满射的同态是代数的同构，其逆映射也是同态，因为单射性将两个定律通过 f 传回。[injective] 和 [surjective] 来源于 Lib/Setoid.v，不是新词汇。

 ** 跨度分解，以及它是某种分解的是什么[variety_spanning] 证明了 h 的余限制到生成子代数。论证是 Mac Lane 的：生成子代数的一个子对象 m，通过其余限制的映射，推进到 A 后，其像（IMAGE）是 A 的一个子代数，包含每个 h x ([img_subalg])；根据最小性，它包含整个闭包；所以 m 的单态是满射；同时也是单态，它是单射，因此可逆，由此得到 [sub_le sub_top m]。[variety_spanning_forces_top] 接着表述为，用 Mac Lane 本人的话来说——m ≈ [sub_top]，因此没有适当的子对象接收余限制。[variety_solution_set] 本身就是备注 1：一个在每个集合 X 上的 [SVariety_Forget E] 的 Adjunction/GAFT.v [SolutionSet]，其 [sol_index] 是 [SpanningArrowsOutOf SVariety_Forget X]。三组 [Example] 读回 [eq_refl]——索引、对象映射以及覆盖给定 h 的成员——所以该声明不仅仅是存在一个解集，而是它就是 Mac Lane 所命名的那个。

