 ** The spanning factorization, and what it is a factorization OF

 [variety_spanning] proves [Spanning SVariety_Forget] of the
 corestriction of h to the generated subalgebra.  The argument is
 Mac Lane's: a subobject m of the generated subalgebra that the
 corestriction factors through has, pushed forward into A, an IMAGE
 that is a subalgebra of A containing every h x ([img_subalg]); by
 leastness it contains the whole closure; so the mono of m is
 surjective; being also monic it is injective, hence invertible, and
 [sub_le sub_top m] follows.  [variety_spanning_forces_top] then reads
 that back in Mac Lane's own words -- m ≈ [sub_top], so no PROPER
 subobject receives the corestriction.

 [variety_solution_set] is Remark 1 itself: a
 Adjunction/GAFT.v [SolutionSet] for [SVariety_Forget E] at every
 set X, whose [sol_index] IS [SpanningArrowsOutOf SVariety_Forget X].
 Three [Example]s read that back at [eq_refl] -- the index, the object
 map and the member covering a given h -- so the claim is not merely
 that a solution set exists but that it is the one Mac Lane names.

