      exact (proper_morphism (rig_map (aalg_unit A)) _ _ Hab).
  - apply pequiv_from; exact (proper_morphism (alin_map f) _ _ Hvw).
  - apply pequiv_from.
    exact (rig_add_respects AR _ _ (pequiv_to _ _ IHs)
