(* In [Prop] since the PR “algebraic carriers are sets” (2026-09-17), in lockstep with [tt_eq], which [ee_base] embeds. / 自从 [Prop] 的 PR “代数载体是集合”（2026-09-17）以来，与 [tt_eq] 保持同步，[ee_base] 已经嵌入其中。 *)
Inductive et_eq : TTerm → TTerm → Prop :=
  | ee_base {s t} : tt_eq s t → et_eq s t

  (* the alternating relation, at GENERATORS only / 交替关系，仅在发电机处 *)
  | ee_alt v : et_eq (tt_mul (tt_gen v) (tt_gen v))
                     (tt_scal (rig_zero (`1 K)))

  | ee_add {s s' t t'} :
      et_eq s s' → et_eq t t' → et_eq (tt_add s t) (tt_add s' t')
  | ee_neg {s s'} : et_eq s s' → et_eq (tt_neg s) (tt_neg s')
  | ee_mul {s s' t t'} :
      et_eq s s' → et_eq t t' → et_eq (tt_mul s t) (tt_mul s' t')

  | ee_sym {s t} : et_eq s t → et_eq t s
  | ee_trans {s t u} : et_eq s t → et_eq t u → et_eq s u.

Lemma et_refl (s : TTerm) : et_eq s s.
Proof. exact (ee_base (tt_refl s)). Qed.

Lemma et_eq_Equivalence : Equivalence et_eq.
Proof.
  constructor.
  - exact et_refl.
  - exact (fun s t => ee_sym).
  - exact (fun s t u => ee_trans).
Qed.

