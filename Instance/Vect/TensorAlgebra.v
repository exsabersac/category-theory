   * * The tensor algebra and the exterior algebra as universal arrows

   Book: Mac Lane, “Categories for the Working Mathematician”, 2nd ed.,
   GTM 5, §III.1, printed p. 59, Exercise 1 — the tensor algebra of
   a vector space and the exterior algebra, each to be exhibited as
   a universal arrow (maclane:III.1:ex1)
   Book: Mac Lane, ibid., §IV.2, printed p. 89, Exercise 1 — the same
   constructions read as left adjoints (maclane:IV.2:ex1)
   nLab:      https://ncatlab.org/nlab/show/tensor+algebra
   nLab:      https://ncatlab.org/nlab/show/exterior+algebra
   Wikipedia: https://en.wikipedia.org/wiki/Tensor_algebra
   Wikipedia: https://en.wikipedia.org/wiki/Exterior_algebra

   TWO CONSTRUCTIONS, ONE TERM ALGEBRA.  Mac Lane's exercise names the
   tensor algebra and the exterior algebra separately, and every textbook
   builds the second as a quotient of the first.  That is exactly how
   they are related here, and the relation is visible in the code rather
   than argued for in prose: [TTerm] is one inductive type of formal
   expressions, [tt_eq] is the congruence generated by the
   associative-algebra laws together with K-linearity of the insertion,
   and [et_eq] is [tt_eq] with ONE further generating equation, v·v ≈ 0,
   adjoined — its first constructor [ee_base] embeds the whole of
   [tt_eq], so the exterior relation is by construction coarser and
   nothing about the ring structure has to be re-proved.  The projection
   [ext_proj : T(V) → Λ(V)] is then the identity on terms
   ([ext_proj_computes], by [eq_refl]).

   THE ALTERNATING RELATION, AND WHY IT IS NOT ANTISYMMETRY.  The
   defining relation of Λ(V) is v ∧ v ≈ 0 for GENERATORS v, not
   v ∧ w ≈ −(w ∧ v).  The squares-vanish form is the one imposed, and it
   IMPLIES antisymmetry: [ext_anticomm] derives v ∧ w ≈ −(w ∧ v) by
   expanding (v + w) ∧ (v + w) ≈ 0.  The converse implication is the one
   that needs 2 to be cancellable, and over a base ring in which 2 ≈ 0
   antisymmetry degenerates into COMMUTATIVITY of the generators — which
   is a condition, but not the one wanted, since it does not give
   v ∧ v ≈ 0.  So the direction proved here is the useful one.  What is
   NOT proved here is that the converse is underivable: no countermodel
   is exhibited, and no claim of strict strength is made — what IS proved
   beyond the implication is that the derived antisymmetry is not vacuous
   ([ext_anticomm_nontrivial], where v ∧ w and w ∧ v are provably
   distinct).  There is in-tree precedent for taking this care, with a
   DIFFERENT degeneracy: Instance/Matr/Determinant.v derives its general
   alternation [det_alt] and records that it does “NOT follow from
   [det M ≈ ⊖ det M] — that is vacuous in characteristic 2”, the
   self-equation x ≈ −x being vacuous there in a way that the two-element
   equation above is not.  Note also that v ∧ v ≈ 0 is demanded of
   GENERATORS only — of elements of V, that is, of the image of [tt_gen] —
   and not of arbitrary elements of Λ(V); [ext_alt] is stated at that
   scope and nowhere widened.

   WHY [AAlg] AND NOT [KAlg].  Instance/Rng/Algebras/Associative.v
   carries the reason at length: [KAlgObject]'s [kalg_comm] field makes
   every object of [KAlg K] commutative, so T(V) — which is
   non-commutative already at the V used below, proved at
   [tensor_not_commutative] — is not an object of it, and Λ(V) is
   anticommutative rather than commutative.  The exercise is therefore
   stated over [AAlg K], the associative K-algebras, which that file
   builds.

   A CORRECTION TO THE ISSUE'S PRIOR ART, recorded here because a header
   is where a reader looks.  Issue #310's “Current state in the library”
   section says the material is “Absent” and that “No categories of
   rings, K-algebras, or vector spaces exist in Instance/ to host the
   constructions”.  Every clause of that but its closing rider was already
   false when this was written — and the rider, “to host the
   constructions”, was substantively RIGHT about the algebra half, which
   is the whole reason [AAlg K] exists: Instance/Rng.v is the category of unital rings,
   Instance/Rng/Algebras.v the category [KAlg] of COMMUTATIVE K-algebras,
   Instance/Mod.v the category of R-modules with Instance/Vect/Free.v and
   Instance/FdVect.v the vector-space readings, and Instance/Mod/Tensor.v
   the tensor product of two modules as a universal element.  What was
   genuinely absent is narrower, and is what this pair of files supplies:
   a category of algebras that does NOT demand commutativity, and the two
   constructions themselves.  The issue's own scope note — that a bundled
   PR is acceptable “only if the algebra-category substrate from the
   dependencies is already in place” — was therefore NOT met as written:
   the COMMUTATIVE substrate was in place, the associative one had to be
   built first, and building it is part of this work rather than a
   precondition of it.

   THE ROUTE NOT TAKEN, and it was measured rather than guessed.  The
   classical construction T(V) = ⊕_n V^⊗n over Instance/Mod/Tensor.v's
   binary tensor product is not available in this tree: it needs
   countable direct sums of modules, and [HasIndexedCoproducts] has
   exactly one instance anywhere (Instance/Sets/Products.v, at [Sets]),
   with no [Cocartesian (RMod R)] and no direct sum of modules of any
   kind.  So T(V) is built directly by generators and relations, which is
   the house pattern for exactly this situation — Instance/Ab/Tensor.v,
   Instance/Sets/Coend.v, Instance/Mod/Free.v, Instance/Mod/Tensor.v and
   Instance/Rng/Polynomial.v all present a quotient this way — and the
   grading is what is given up: there is no degree function on [TTerm],
   hence no decomposition of T(V) into homogeneous pieces, no normal
   form, and no decision procedure for equality.

   STRENGTHS, MEASURED, and they differ between the two halves of each
   extension.

   - [eq_refl]: evaluation restricted to the generators IS the given
   linear map, and restricted to the scalars IS the structure map
   ([tensor_extend_gen], [tensor_extend_scal], and the exterior
   counterparts); the exterior projection is the identity on terms
   ([ext_proj_computes]); the universal arrow of the tensor algebra IS
   the insertion ([tensor_arrow_is_insert]); the free functor's object
   part IS [TensorAlg] ([TensorFunctor_obj]); the unit of the
   adjunction IS the generator insertion ([tensor_unit_is_gen]); the
   universal element of [AltFunctor] IS the exterior insertion
   ([ext_universal_elem_is_insert]); and the concrete computations in
   the witness section reduce.
   - `≈` only, and this was tried strictly first: preservation of ZERO
   and of ONE by the extension.  The zero of T(V) is
   [tt_scal (rig_zero K)], so the fold returns the structure map's
   value at K's zero, and reaching the target's zero is that map's own
   preservation law.  Instance/Rng/Polynomial.v records the identical
   seam for K[x], for the identical reason.
   - `≈` only, unavoidably: the transposes obtained from
   [ump_universal_arrows], which is [Qed]-opaque.  The counit of
   [tensor_adjunction] is on that side and no [eq_refl] is claimed for
   it; Instance/Mod/Free.v records the same for the free module.

   WHAT IS DELIVERED.

   - [TensorAlg V : AAlgObject K] for any K-module V, with the insertion
   [tensor_insert : AAlgLinear V (TensorAlg V)];
   - [tensor_extend] and [tensor_extend_unique]: every K-linear map from
   V into an associative K-algebra extends uniquely to an algebra map
   out of T(V);
   - [tensor_universal_arrow : UniversalArrow V (AAlg_Forget_Mod K)] and
   [tensor_auniversal_arrow], Mac Lane's §III.1 Exercise 1 in both of
   Theory/Universal/Arrow.v's encodings, with the §IV.2 left-adjoint
   reading [TensorFunctor] and
   [tensor_adjunction : TensorFunctor ⊣ AAlg_Forget_Mod K];
   - [ExtAlg V : AAlgObject K] with [ext_insert], [ext_alt] and the
   derived [ext_anticomm]; [ext_extend], [ext_extend_unique];
   [ext_proj : T(V) ⟶ Λ(V)], the identity on terms;
   - [tensor_extend_self] and [ext_extend_self]: each universal
   property applied at its own object, so that the extension of an
   insertion along itself is the identity;
   - [AltLinear] and [AltFunctor V : AAlg K ⟶ Sets], and
   [ext_universal_element : AUniversalElement (AltFunctor V)
   (ExtAlg V)] — the exterior algebra in UNIVERSAL-ARROW form, with
   [ext_representation] exhibiting Λ(V) as representing the functor of
   alternating maps, [ext_representable], and [ext_auniversal_arrow]
   the arrow reading out of the one-point setoid;
   - non-degeneracy, proved and not asserted: [tensor_not_commutative]
   (T(V) is genuinely non-commutative for a concrete V, so the passage
   to [AAlg] was necessary), [tensor_gen_not_scalar],
   [ext_nontrivial], [ext_gen_not_scalar] and
   [ext_anticomm_nontrivial] (e₁∧e₂ and e₂∧e₁ are provably distinct in
   a concrete Λ, so antisymmetry is not vacuous), each obtained by
   mapping OUT into a concrete algebra, since no induction on the
   quotienting relation could yield a negative.

   THE TWO DEGENERACIES, NAMED AND EXCLUDED.  Both constructions have a
   degenerate case, and the witnesses below are chosen to avoid each.
   (i) A TRIVIAL BASE RING: if 1 ≈ 0 in K then the one and the zero of
   T(V) and of Λ(V) are the same scalar, and the separations below would
   be false.  The witnesses are over ℤ, and the exclusion is proved
   INSIDE the constructions rather than assumed of the base:
   [tensor_nontrivial] and [ext_nontrivial] show 1 ≉ 0 in T(V) and in
   Λ(V) themselves.  (ii) A ZERO MODULE: [te_gen_zero] proves the
   generator of the zero vector IS the scalar zero, so over V = 0 every
   generator is a scalar and [tensor_gen_not_scalar] would be false.  The
   witnesses avoid it, and again the avoidance is proved rather than
   assumed: [tensor_gen_not_scalar] and [ext_gen_not_scalar] exhibit
   generators that are provably not scalars, and [ext_gens_distinct] two
   generators that are provably distinct.  (No notion of linear
   independence is defined in this file and none is claimed; what is
   proved is exactly the distinctness just listed.)

   WHAT §IV.2 ASKS FOR BEYOND THIS, AND IS DELIBERATELY NOT DELIVERED.
   Mac Lane's §IV.2 Exercise 1 asks for the exterior algebra as a LEFT
   ADJOINT of a forgetful functor whose codomain is the category of GRADED
   ANTICOMMUTATIVE K-algebras, and makes a point of that forgetful functor
   being NOT FAITHFUL.  Neither is delivered here.  No category of graded
   anticommutative K-algebras is built — the tree has no grading on
   algebras at all, and neither dependency of this issue supplies one —
   and consequently no adjunction over such a category, and no
   non-faithfulness lemma.  NEITHER IS ASSUMED ANYWHERE in what follows:
   no proof below uses a grading, an anticommutativity law of a target
   algebra, or any property of a forgetful functor out of a graded
   category, and no comment below asserts any of the three as known.  What
   IS delivered for Λ(V) is the universal-arrow form over the same
   [AAlg K] substrate as T(V), which is what the issue's own scope
   increment specifies.  The left-adjoint upgrade and the
   non-faithfulness lemma are follow-up work over a category that does not
   yet exist.

   OTHER DEFERRALS.  No grading, no homogeneous components, no normal
   form, no coefficient uniqueness, hence no decision procedure and no
   dimension count — in particular Λ(V) is NOT shown to be finitely
   generated when V is, and no basis of Λ(V) is exhibited.  No symmetric
   algebra, and so no identification of the symmetric algebra as the
   [KAlg] reading of the same universal property.  No comparison with
   Instance/Mod/Tensor.v's binary tensor product: T(V) is not shown to
   contain V ⊗ V as its degree-two part, because there is no degree.  No
   functoriality of Λ in V as a stated functor — T gains it as the [fmap]
   of the left adjoint, and Λ has no adjunction here to inherit it from,
   since the alternating maps out of V do not arise as maps into a
   forgetful image.  The witnesses below are over ℤ; no field-specific
   statement is made, and Instance/FdVect.v's finite-dimensional vector
   spaces are not connected to this file.

   ONE IMPORT EXPLAINED.  Instance/Rng/Polynomial.v is required for
   exactly two lemmas, [rng_mul_neg_l] and [rng_mul_neg_r], which it
   proves for an arbitrary [RingObject] by uniqueness of additive
   inverses.  They are consumed once each, in [tensor_scal_central].
   Proving them a second time here would be duplication; nothing else of
   that file is used. 

