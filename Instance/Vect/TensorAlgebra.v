   （对于具体的 V，T(V) 真的不是交换的，所以需要过渡到 [AAlg]），[tensor_gen_not_scalar],
   [ext_nontrivial], [ext_gen_not_scalar] 和 [ext_anticomm_nontrivial]（在具体 Λ 中 e₁∧e₂ 和 e₂∧e₁ 可证明是不同的，因此反对称性不是空的），每个都是通过将 OUT 映射到具体代数中获得的，因为在商关系上进行归纳无法得到一个否定结果。

   两个退化情况，被命名并排除。两种构造都有一个退化情况，下面选择的见证者是为了避免每一种情况。(i) 一个平凡基环：如果在 K 中 1 ≈ 0，那么 T(V) 和 Λ(V) 中的一和零是同一个标量，下面的区分将是错误的。见证者是在 ℤ 上的，并且排除是在构造内部证明的，而不是假定基环：[tensor_nontrivial] 和 [ext_nontrivial] 显示 1 在 T(V) 和 Λ(V) 中本身不等于 0。(ii) 零模：[te_gen_zero] 证明零向量的生成元是标量零，因此在 V = 0 上，每个生成元都是标量，[tensor_gen_not_scalar] 将是错误的。证人们避开它，而且这种回避是被证明的，而不是假设的：[tensor_gen_not_scalar] 和 [ext_gen_not_scalar] 展示了可以被证明不是标量的生成元，而 [ext_gens_distinct] 展示了两个可以被证明彼此不同的生成元。（此文件中没有定义线性独立性的概念，也没有声称有定义；被证明的正是上面列出的不同之处。）§IV.2要求的内容超出了这里所提供的范围，并且故意没有提供。Mac Lane的§IV.2练习1要求将外代数作为一个忘记函子（其值域是分级反交换K-代数类别）的左伴随，并特别指出该忘记函子不是可信的。这里没有提供任何相关内容。没有建立任何分级反交换K-代数的类别——该树上的代数根本没有分级，并且此问题的依赖也没有提供——因此也没有在这样的类别上建立伴随关系，也没有非可信引理。以下内容中也没有假设任何这些：下面的证明没有使用分级、目标代数的反交换律，或来自分级类别的忘记函子的任何性质，也没有评论声明三者中的任何一项为已知。对 Λ(V) 所提供的是在与 T(V) 相同的 [AAlg K] 基础上的通用箭头形式，这正是该问题自身作用域增量所指定的。左伴随升级和非保真引理是在一个尚不存在的范畴上的后续工作。其他延期。没有分级，没有同类分量，没有正规形式，没有系数唯一性，因此没有判定程序，也没有维数计数——特别地，当 V 是有限生成时，Λ(V) 并未被证明为有限生成，也没有展示 Λ(V) 的基。没有对称代数，因此也没有将对称代数识别为相同普遍性质的 [KAlg] 读法。没有与 Instance/Mod/Tensor.v 的二元张量积的比较：T(V) 并未被证明包含 V ⊗ V 作为其二次部分，因为没有度。Λ 在 V 中作为明确定义函子没有函子性——T 作为左伴随的 [fmap] 获得了它，而 Λ 在此没有伴随可以继承它，因为来自 V 的交错映射不会作为映射进入遗忘函子的像而产生。下面的证人与 ℤ 相关；没有特定于域的陈述，并且 Instance/FdVect.v 的有限维向量空间与此文件无关。

   一个导入被解释。Instance/Rng/Polynomial.v 仅用于两个引理，[rng_mul_neg_l] 和 [rng_mul_neg_r]，它通过加法逆元的唯一性为任意 [RingObject] 证明它们。它们各自只被使用一次，在 [tensor_scal_central] 中。如果在这里再次证明它们将是重复；该文件的其他内容未被使用。
*)

(*
   * ** Alternating linear maps

   The data the universal property of Λ(V) consumes: a K-linear map whose
   values SQUARE TO ZERO.  Stated at [AAlgLinear] plus one field, so that
   everything Instance/Rng/Algebras/Associative.v proves about linear maps
   applies unchanged. 

   --------
   * ** 交替线性映射

   Λ(V) 的普遍性质所使用的数据：一个 K-线性映射，其值平方为零。以 [AAlgLinear] 加一个域的形式表述，因此 Instance/Rng/Algebras/Associative.v 关于线性映射所证明的一切内容都可以保持不变地适用。
*)

Record AltLinear {K : CRng} (V : RModObject (`1 K)) (A : AAlgObject K) := {
  alt_lin :> AAlgLinear V A;

  alt_sq : ∀ v, rig_mul (aalg_ring A) (alin_map alt_lin v) (alin_map alt_lin v)
                  ≈ rig_zero (aalg_ring A)
}.

Arguments alt_lin {K V A} _.
Arguments alt_sq {K V A} _ _.

Program Definition AltLinear_Setoid {K : CRng} (V : RModObject (`1 K))
  (A : AAlgObject K) : Setoid (AltLinear V A) := {|
  equiv := fun f g => ∀ v, alin_map (alt_lin f) v ≈ alin_map (alt_lin g) v
|}.
Next Obligation.
  intros K V A.
  constructor.
  - intros f v; reflexivity.
  - intros f g Hfg v; symmetry; apply Hfg.
  - intros f g h Hfg Hgh v; transitivity (alin_map (alt_lin g) v);
      [ apply Hfg | apply Hgh ].
Qed.

(*
 Postcomposing an alternating map with an algebra morphism keeps it
 alternating: the morphism carries the square to the square and the zero
 to the zero. 

 --------
 将一个交替映射与一个代数同态后合成仍然保持交替性：同态将平方映射到平方，将零映射到零。
*)
Program Definition alt_compose {K : CRng} {V : RModObject (`1 K)}
  {A B : AAlgObject K} (g : AAlgHom A B) (f : AltLinear V A)
  : AltLinear V B := {|
  alt_lin := alin_compose g (alt_lin f)
|}.
Next Obligation.
  intros K V A B g f v; simpl.
  rewrite <- (rig_map_mul (`1 g)).
  rewrite (proper_morphism (rig_map (`1 g)) _ _ (alt_sq f v)).
  apply (rig_map_zero (`1 g)).
Qed.

(*
 The functor of alternating maps out of V.  Λ(V) is what represents it,
 and that is [ext_universal_element] below. 

 --------
 从 V 出发的交替映射的函子。Λ(V) 表示它，而下面是 [ext_universal_element]。
*)
Program Definition AltFunctor {K : CRng} (V : RModObject (`1 K))
  : AAlg K ⟶ Sets := {|
  fobj := fun A => {| carrier := AltLinear V A;
                      is_setoid := AltLinear_Setoid V A |};
  fmap := fun A B g => {| morphism := alt_compose g |}
|}.
Next Obligation.
  intros K V A B g f f' Hff' v; simpl.
  exact (proper_morphism (rig_map (`1 g)) _ _ (Hff' v)).
Qed.
Next Obligation.
  intros K V A B g g' Hgg' f v; simpl; exact (Hgg' _).
Qed.
Next Obligation. intros K V A f v; simpl; reflexivity. Qed.
Next Obligation. intros K V A B C g h f v; simpl; reflexivity. Qed.

(** * The term algebra / * 代数一词 *)

Section Algebras.

Context (K : CRng).
Context (V : RModObject (`1 K)).

(*
   * ** Formal expressions

   Five formers: scalars, generators, sum, negation and product.  There is
   no former for the unit or for the zero — those are [tt_scal] of K's one
   and zero, exactly as in Instance/Rng/Polynomial.v. 

   --------
   * ** 正式表达

   五个生成元：标量、生成器、求和、取反和乘积。
   没有用于单位元或零元的生成元——那些是 K 的一和零的 [tt_scal]，就像在 Instance/Rng/Polynomial.v 中一样。
*)

Inductive TTerm : Type :=
  | tt_scal : carrier (rig_setoid (`1 K)) → TTerm
  | tt_gen  : carrier (cmon_setoid V) → TTerm
  | tt_add  : TTerm → TTerm → TTerm
  | tt_neg  : TTerm → TTerm
  | tt_mul  : TTerm → TTerm → TTerm.

(*
   * The congruence: the ring laws with multiplication NOT commutative, the
   two clauses making the scalar inclusion a ring homomorphism, and
   K-linearity of the generator insertion stated on BOTH sides — the
   right-hand form [te_gen_smul_r] is what makes the scalars central,
   and it is not derivable from the left-hand form alone. 

   --------
   * 同余：乘法不满足交换律的环律，两个条款使得标量包含成为环同态，以及生成元插入的 K-线性在双方都陈述——右侧形式 [te_gen_smul_r] 使得标量为中心元素，而仅从左侧形式无法推导出此点。
*)

(*
 AN EARLIER REVISION of this inductive landed in [Type].  Since the PR
 “algebraic carriers are sets” (2026-09-17) it lands in [Prop], because
 [RigObject] carries a [rig_prop : PropEquiv (is_setoid rig_setoid)] field
 and the `≈` of [TensorRing] IS [tt_eq].  [et_eq] below moves IN LOCKSTEP:
 its first constructor [ee_base] embeds a whole [tt_eq], so a [Type]-valued
 [et_eq] over a [Prop]-valued [tt_eq] would be a constructor argument in the
 wrong direction for the exterior algebra to stay a quotient of the tensor
 algebra.  The cost is one elimination in each of [teval_respects] and
 [exteval_respects], both of which now go through [pequiv_to] at the target
 algebra.  Test/ProbeTermModelPropRng.v pins the refusal of the old
 scripts. 

 --------
 这一归纳的早期修订版本落在 [Type]。由于 PR“代数载体是集合”（2026-09-17），它落在 [Prop]，因为 [RigObject] 拥有一个 [rig_prop : PropEquiv (is_setoid rig_setoid)] 域，并且 [TensorRing] 的 `≈` 是 [tt_eq]。下面的 [et_eq] 以同步步伐移动：它的第一个构造函数 [ee_base] 嵌入了整个 [tt_eq]，因此一个 [Prop] 值的 [tt_eq] 上的 [Type] 值 [et_eq] 将是外代数为了保持作为张量代数的商而在错误方向上的构造函数参数。代价是在 [teval_respects] 和 [exteval_respects] 中各进行一次消去，它们现在都通过目标代数中的 [pequiv_to]。Test/ProbeTermModelPropRng.v 固定了旧脚本的拒绝。
*)
Inductive tt_eq : TTerm → TTerm → Prop :=
  (* congruence for each former, saturating under the two source setoids / 每个前者的合同性，在两个源等价格下饱和 *)
  | te_scal {a b} : a ≈ b → tt_eq (tt_scal a) (tt_scal b)
  | te_gen {v w} : v ≈ w → tt_eq (tt_gen v) (tt_gen w)
  | te_add {s s' t t'} :
      tt_eq s s' → tt_eq t t' → tt_eq (tt_add s t) (tt_add s' t')
  | te_neg {s s'} : tt_eq s s' → tt_eq (tt_neg s) (tt_neg s')
  | te_mul {s s' t t'} :
      tt_eq s s' → tt_eq t t' → tt_eq (tt_mul s t) (tt_mul s' t')

  (* abelian group under addition / 加法下的阿贝尔群 *)
  | te_add_assoc s t u :
      tt_eq (tt_add (tt_add s t) u) (tt_add s (tt_add t u))
  | te_add_comm s t : tt_eq (tt_add s t) (tt_add t s)
  | te_add_zero_l s : tt_eq (tt_add (tt_scal (rig_zero (`1 K))) s) s
  | te_add_neg_l s : tt_eq (tt_add (tt_neg s) s) (tt_scal (rig_zero (`1 K)))

  (* monoid under multiplication — commutativity is NOT among the laws / 乘法下的幺半群——交换律不属于定律之一 *)
  | te_mul_assoc s t u :
      tt_eq (tt_mul (tt_mul s t) u) (tt_mul s (tt_mul t u))
  | te_mul_one_l s : tt_eq (tt_mul (tt_scal (rig_one (`1 K))) s) s
  | te_mul_one_r s : tt_eq (tt_mul s (tt_scal (rig_one (`1 K)))) s

  (* distributivity on both sides / 两边的分配律 *)
  | te_distr_l s t u :
      tt_eq (tt_mul s (tt_add t u)) (tt_add (tt_mul s t) (tt_mul s u))
  | te_distr_r s t u :
      tt_eq (tt_mul (tt_add s t) u) (tt_add (tt_mul s u) (tt_mul t u))

  (* the scalar inclusion is a homomorphism of rings / 标量包含是环的同态 *)
  | te_scal_add a b :
      tt_eq (tt_scal (rig_add (`1 K) a b)) (tt_add (tt_scal a) (tt_scal b))
  | te_scal_mul a b :
      tt_eq (tt_scal (rig_mul (`1 K) a b)) (tt_mul (tt_scal a) (tt_scal b))

  (* the generator insertion is K-linear, on both sides / 生成元插入在两边都是 K-线性的 *)
  | te_gen_add v w :
      tt_eq (tt_gen (cmon_plus V v w)) (tt_add (tt_gen v) (tt_gen w))
  | te_gen_smul_l r v :
      tt_eq (tt_gen (rm_smul V r v)) (tt_mul (tt_scal r) (tt_gen v))
  | te_gen_smul_r r v :
      tt_eq (tt_gen (rm_smul V r v)) (tt_mul (tt_gen v) (tt_scal r))

  | te_sym {s t} : tt_eq s t → tt_eq t s
  | te_trans {s t u} : tt_eq s t → tt_eq t u → tt_eq s u.

(*
 Reflexivity is derived, keeping the relation's induction principle one
 case shorter wherever it is consumed. 

 --------
 反身性是派生出来的，在使用关系的归纳原理时，总是将其缩短一个案例。
*)
Lemma tt_refl (s : TTerm) : tt_eq s s.
Proof.
  induction s.
  - exact (te_scal (reflexivity _)).
  - exact (te_gen (reflexivity _)).
  - exact (te_add IHs1 IHs2).
  - exact (te_neg IHs).
  - exact (te_mul IHs1 IHs2).
Qed.

Lemma tt_eq_Equivalence : Equivalence tt_eq.
Proof.
  constructor.
  - exact tt_refl.
  - exact (fun s t => te_sym).
  - exact (fun s t u => te_trans).
Qed.

(*
 As in Instance/Ab/Tensor.v and Instance/Rng/Polynomial.v this setoid is
 deliberately NOT registered as an instance: the [≈] of [TensorRing] IS
 [tt_eq] definitionally, so Theory/Algebra/Rig.v's lemmas apply to it
 unchanged. 

 --------
 正如在 Instance/Ab/Tensor.v 和 Instance/Rng/Polynomial.v 中，这个集合类刻意没有注册为实例：[≈] 的 [TensorRing] 在定义上就是 [tt_eq]，因此 Theory/Algebra/Rig.v 的引理对它不变地适用。
*)
Definition tt_Setoid : Setoid TTerm := {|
  equiv        := tt_eq;
  setoid_equiv := tt_eq_Equivalence
|}.

(** ** Derived laws / ** 派生法律 *)

Let TZ : TTerm := tt_scal (rig_zero (`1 K)).
Let TO : TTerm := tt_scal (rig_one (`1 K)).

Lemma te_add_zero_r (s : TTerm) : tt_eq (tt_add s TZ) s.
Proof. exact (te_trans (te_add_comm s TZ) (te_add_zero_l s)). Qed.

Lemma te_add_neg_r (s : TTerm) : tt_eq (tt_add s (tt_neg s)) TZ.
Proof. exact (te_trans (te_add_comm s (tt_neg s)) (te_add_neg_l s)). Qed.

Lemma te_add_cancel_l (s t u : TTerm) :
  tt_eq (tt_add s t) (tt_add s u) → tt_eq t u.
Proof.
  intro H.
  refine (te_trans (te_sym (te_add_zero_l t)) _).
  refine (te_trans (te_add (te_sym (te_add_neg_l s)) (tt_refl t)) _).
  refine (te_trans (te_add_assoc (tt_neg s) s t) _).
  refine (te_trans (te_add (tt_refl (tt_neg s)) H) _).
  refine (te_trans (te_sym (te_add_assoc (tt_neg s) s u)) _).
  refine (te_trans (te_add (te_add_neg_l s) (tt_refl u)) _).
  exact (te_add_zero_l u).
Qed.

Lemma te_mul_zero_l (s : TTerm) : tt_eq (tt_mul TZ s) TZ.
Proof.
  (* 0·s ≈ (0+0)·s ≈ 0·s + 0·s, so 0·s ≈ 0 by cancellation. / 0·s ≈ (0+0)·s ≈ 0·s + 0·s，因此 0·s ≈ 0 通过消去法。 *)
  apply (te_add_cancel_l (tt_mul TZ s)).
  refine (te_trans (te_sym (te_distr_r TZ TZ s)) _).
  refine (te_trans (te_mul _ (tt_refl s))
            (te_sym (te_add_zero_r (tt_mul TZ s)))).
  refine (te_trans (te_sym (te_scal_add (rig_zero (`1 K)) (rig_zero (`1 K)))) _).
  exact (te_scal (rig_add_zero_l (`1 K) (rig_zero (`1 K)))).
Qed.

Lemma te_mul_zero_r (s : TTerm) : tt_eq (tt_mul s TZ) TZ.
Proof.
  apply (te_add_cancel_l (tt_mul s TZ)).
  refine (te_trans (te_sym (te_distr_l s TZ TZ)) _).
  refine (te_trans (te_mul (tt_refl s) _)
            (te_sym (te_add_zero_r (tt_mul s TZ)))).
  refine (te_trans (te_sym (te_scal_add (rig_zero (`1 K)) (rig_zero (`1 K)))) _).
  exact (te_scal (rig_add_zero_l (`1 K) (rig_zero (`1 K)))).
Qed.

(* The generator of the zero vector IS the scalar zero — additivity plus cancellation. This is the second degeneracy named in the header: over the zero module every generator is a scalar. / 零向量的生成元是标量零——可加性加上消去。这是标题中提到的第二种退化：在零模上，每个生成元都是一个标量。 *)
Lemma te_gen_zero : tt_eq (tt_gen (cmon_zero V)) TZ.
Proof.
  apply (te_add_cancel_l (tt_gen (cmon_zero V))).
  refine (te_trans _ (te_sym (te_add_zero_r (tt_gen (cmon_zero V))))).
  refine (te_trans (te_sym (te_gen_add (cmon_zero V) (cmon_zero V))) _).
  exact (te_gen (cmon_plus_zero_l V (cmon_zero V))).
Qed.

(** ** The ring T(V) / ** 环 T(V) *)

Definition TensorRig : RigObject := {|
  rig_setoid := {| carrier := TTerm; is_setoid := tt_Setoid |};
  rig_zero := TZ;
  rig_add := tt_add;
  rig_one := TO;
  rig_mul := tt_mul;
  rig_add_respects := fun _ _ Hs _ _ Ht => te_add Hs Ht;
  rig_mul_respects := fun _ _ Hs _ _ Ht => te_mul Hs Ht;
  rig_add_assoc := te_add_assoc;
  rig_add_comm := te_add_comm;
  rig_add_zero_l := te_add_zero_l;
  rig_mul_assoc := te_mul_assoc;
  rig_mul_one_l := te_mul_one_l;
  rig_mul_one_r := te_mul_one_r;
  rig_distr_l := te_distr_l;
  rig_distr_r := te_distr_r;
  rig_mul_zero_l := te_mul_zero_l;
  rig_mul_zero_r := te_mul_zero_r;
  (*
 [tt_eq] IS a [Prop]-valued relation, so it is its own [Prop] mirror and
 both implications are the identity. 

 --------
 [tt_eq] 是一个 [Prop] 值的关系，因此它是其自身的 [Prop] 镜像，并且两个蕴涵都是恒等映射。
*)
  rig_prop := @PropEquiv_of_relation _ tt_Setoid tt_eq
                (fun _ _ h => h) (fun _ _ h => h)
|}.

Definition TensorRing : RingObject := {|
  ring_rig := TensorRig;
  ring_neg := tt_neg;
  ring_neg_respects := fun _ _ Hs => te_neg Hs;
  ring_neg_l := te_add_neg_l
|}.

(* * ** The scalar inclusion and the generator insertion / * ** 标量包含和生成器插入 *)

Program Definition tensor_scal : `1 K ~{Rng}~> TensorRing := {|
  rig_map := {| morphism := tt_scal |}
|}.
Next Obligation. intros a b H; exact (te_scal H). Qed.
Next Obligation. simpl; exact (tt_refl TZ). Qed.
Next Obligation. intros a b; exact (te_scal_add a b). Qed.
Next Obligation. simpl; exact (tt_refl TO). Qed.
Next Obligation. intros a b; exact (te_scal_mul a b). Qed.

(*
   * Scalars are CENTRAL in T(V).  This is a theorem, by induction on the
   term, rather than a further generating equation: the generator case is
   the two linearity clauses composed, the scalar case is commutativity of
   K, and the three recursive cases are the ring laws of [TensorRing]
   together with Instance/Rng/Polynomial.v's negation lemmas. 

   --------
   * 标量在 T(V) 中是中心的。这是一个定理，通过对项的归纳来证明，而不是进一步的生成方程：生成元情况是两个线性条款的组合，标量情况是 K 的交换性，而三个递归情况是 [TensorRing] 的环律以及 Instance/Rng/Polynomial.v 的取反引理。
*)
Lemma tensor_scal_central (r : carrier (rig_setoid (`1 K))) (t : TTerm) :
  tt_eq (tt_mul (tt_scal r) t) (tt_mul t (tt_scal r)).
Proof.
  induction t as [ a | v | s IHs u IHu | s IHs | s IHs u IHu ].
  - refine (te_trans (te_sym (te_scal_mul r a)) _).
    refine (te_trans (te_scal (`2 K r a)) _).
    exact (te_scal_mul a r).
  - exact (te_trans (te_sym (te_gen_smul_l r v)) (te_gen_smul_r r v)).
  - refine (te_trans (te_distr_l (tt_scal r) s u) _).
    refine (te_trans (te_add IHs IHu) _).
    exact (te_sym (te_distr_r s u (tt_scal r))).
  - refine (te_trans (rng_mul_neg_r TensorRing (tt_scal r) s) _).
    refine (te_trans (te_neg IHs) _).
    exact (te_sym (rng_mul_neg_l TensorRing s (tt_scal r))).
  - refine (te_trans (te_sym (te_mul_assoc (tt_scal r) s u)) _).
    refine (te_trans (te_mul IHs (tt_refl u)) _).
    refine (te_trans (te_mul_assoc s (tt_scal r) u) _).
    refine (te_trans (te_mul (tt_refl s) IHu) _).
    exact (te_sym (te_mul_assoc s u (tt_scal r))).
Qed.

(** T(V) as an object of [AAlg K]. / T(V) 作为 [AAlg K] 的一个对象。 *)
Definition TensorAlg : AAlgObject K :=
  Build_AAlgObject K TensorRing tensor_scal tensor_scal_central.

(*
   * The insertion of the generators, K-linear by two of the generating
   equations. 

   --------
   * 生成元的插入，通过两个生成方程是 K 线性的。
*)
Program Definition tensor_insert : AAlgLinear V TensorAlg := {|
  alin_map := {| morphism := tt_gen |}
