   * * 张量代数和外代数作为泛箭头

   书籍：Mac Lane，《面向实际数学家的范畴论》，第2版，
   GTM 5，§III.1，第59页，练习1 — 一个向量空间的张量代数和外代数，
   每一个都将展示为一个泛箭头 (maclane:III.1:ex1)
   书籍：Mac Lane，同上，§IV.2，第89页，练习1 — 相同的构造作为左伴随函子来理解 (maclane:IV.2:ex1)
   nLab:       https://ncatlab.org/nlab/show/tensor+algebra 
   nLab:       https://ncatlab.org/nlab/show/exterior+algebra 
   维基百科:   https://en.wikipedia.org/wiki/Tensor_algebra 
   维基百科:   https://en.wikipedia.org/wiki/Exterior_algebra两个构造，一个术语代数。Mac Lane 的习题分别命名了张量代数和外代数，每本教材都将后者构建为前者的一个商。这里它们的关系也是完全如此，而且这种关系在代码中是可见的，而不是通过文字论证的：[TTerm] 是形式表达式的一种归纳类型，[tt_eq] 是由结合代数定律以及插入的 K-线性生成的同余关系，而 [et_eq] 是在 [tt_eq] 上附加一个进一步的生成方程 v·v ≈ 0 ——它的第一个构造器 [ee_base] 嵌入了整个 [tt_eq]，所以外代数关系在构造上是更粗的，并且环的结构无需重新证明。投影
   [ext_proj : T(V) → Λ(V)] 然后在项上是恒等的
   ([ext_proj_computes] , 由 [eq_refl])。交替关系，以及为什么它不是反对称关系。Λ(V) 的定义关系是对生成元 v 有 v ∧ v ≈ 0，而不是 v ∧ w ≈ −(w ∧ v)。规定的是平方为零的形式，它蕴含了反对称性：[ext_anticomm] 通过展开 (v + w) ∧ (v + w) ≈ 0 推导出 v ∧ w ≈ −(w ∧ v)。相反的蕴含需要 2 可抵消，在 2 ≈ 0 的基环上，反对称性退化为生成元的交换性——这是一个条件，但不是所需的那一个，因为它并不导致 v ∧ v ≈ 0。因此，这里证明的方向是有用的。这里没有被证明的是其逆命题不可导出：没有展示反例模型，也没有提出严格强度的主张——超出蕴含之外所证明的是，导出的反对称性并非空洞（[ext_anticomm_nontrivial]，其中 v ∧ w 和 w ∧ v 可被证明是不同的）。在树内有这样的前例处理不同的退化情况：Instance/Matr/Determinant.v 导出了其一般的交替性 [det_alt] 并记录道其“不能从 [det M ≈ ⊖ det M] 推出——在特征为 2 时是空洞的”，自等式 x ≈ −x 在那里是空洞的，而上面的二元素等式则不是。还要注意，v ∧ v ≈ 0 仅对生成元要求——即对 V 的元素，也就是 [tt_gen] 的像——而不是对 Λ(V) 的任意元素； [ext_alt] 在该范围内被说明，并且没有被扩展。  为什么是 [AAlg] 而不是 [KAlg]。Instance/Rng/Algebras/Associative.v 文件中详细说明了原因：[KAlgObject] 的 [kalg_comm] 域使 [KAlg K] 的每个对象都是交换的，因此 T(V)——在下面使用的 V 上已被证明是非交换的，见 [tensor_not_commutative] ——不是它的对象，而 Λ(V) 是反交换的而不是交换的。因此，该练习是针对 [AAlg K]，即结合 K-代数，该文件构建了它们。对本期先前技术的更正，在此记录，因为读者会查看标题。第310号问题的“库中的当前状态”部分说明该材料是“缺失的”，并且“在 Instance/ 中不存在任何类别的环、K-代数或向量空间来承载这些构造”。当写下这段话时，其每一条款除了结尾的附加条款已经是错误的——而那条附加条款，“承载这些构造”，在代数部分实际上是正确的，这也是 [AAlg K] 存在的全部原因：Instance/Rng.v 是单环的范畴，Instance/Rng/Algebras.v 是交换 K-代数的范畴 [KAlg]，Instance/Mod.v 是 R-模的范畴，并有 Instance/Vect/Free.v 和 Instance/FdVect.v 的向量空间表示，Instance/Mod/Tensor.v 是两个模的张量积作为一个泛元素。真正缺失的是更狭义的部分，而这一对文件提供了它：一个不要求交换性的代数范畴，以及这两种构造本身。该问题自身的范围说明——即捆绑的 PR 仅在“依赖项中的代数类别基底已存在”的情况下才可接受——因此按照原文并未满足：可交换基底已存在，但结合基底必须先构建，而构建它是本工作的部分，而不是其先决条件。未选之路，而且这是经过测量而非猜测的。在 Instance/Mod/Tensor.v 的二元张量积上，经典的构造 T(V) = ⊕_n V^⊗n 在这棵树中不可用：它需要可数的模直接和，而 [HasIndexedCoproducts] 在任何地方恰好只有一个实例（Instance/Sets/Products.v，位于 [Sets]），没有 [Cocartesian (RMod R)]，也没有任何类型的模直接和。因此，T(V) 是直接由生成元和关系构建的，这正是这种情况的标准模式——Instance/Ab/Tensor.v、Instance/Sets/Coend.v、Instance/Mod/Free.v、Instance/Mod/Tensor.v 和 Instance/Rng/Polynomial.v 都以这种方式给出了一个商——而分次是所放弃的内容：在 [TTerm] 上没有次数函数，因此 T(V) 无法分解为齐次部分，没有规范形式，也没有等式判定程序。

   强项、测量，并且它们在每个扩展的两个部分之间有所不同。-  [eq_refl] ：对生成元的评估就是给定的线性映射，对标量的限制就是结构映射（[tensor_extend_gen]、[tensor_extend_scal]，以及外部对应物）；外部投影在项上是恒等映射（[ext_proj_computes]）；张量代数的通用箭头是插入（[tensor_arrow_is_insert]）；自由函子的对象部分是[TensorAlg]（[TensorFunctor_obj]）；伴随的单位是生成元插入（[tensor_unit_is_gen]）；[AltFunctor] 的通用元是外部插入（[ext_universal_elem_is_insert]）；并且见证部分中的具体计算可简化。- 仅`≈`，而且这是严格首先尝试的：通过扩展保持零和一。T(V) 的零点是 [tt_scal (rig_zero K)]，因此 fold 返回结构映射在 K 的零点处的值，而到达目标的零点就是该映射自身的保持律。Instance/Rng/Polynomial.v 对 K [x] 也记录了相同的连接出于相同的原因。- 仅 `≈`，不可避免：从 [ump_universal_arrows] 得到的转置是 [Qed] - 不透明的。[tensor_adjunction] 的余单位在那一侧，并且没有为它声明 [eq_refl]；Instance/Mod/Free.v 对自由模也记录了相同的情况。

