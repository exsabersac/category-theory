   linear because the module structure is componentwise, and alternating
   because the square of a degree-one element is (ab − ba) in the top
   slot, which is zero. 

   --------
   * ** Λ(V) 不会塌缩

   证据模是 [Lam2] 的底层 ℤ-模，证据交替映射是到一次部分的投影——线性，因为模结构是逐分量的，交替的，因为一次元素的平方在顶部位置是 (ab − ba)，这为零。
*)

Definition Lam2_Mod : RModObject (`1 Int_CRng) := AAlg_RMod Lam2_AAlg.

Definition lam2_deg1 (x : lam2) : lam2 :=
  match x with (_, a, b, _) => (0, a, b, 0)%Z end.

Definition lam2_deg1_proper
  : Proper (@equiv _ (is_setoid lam2_setoid_object)
              ==> @equiv _ (is_setoid lam2_setoid_object)) lam2_deg1 :=
  fun x y H => f_equal lam2_deg1 H.

Program Definition lam2_deg1_lin : AAlgLinear Lam2_Mod Lam2_AAlg := {|
  alin_map := {| morphism := lam2_deg1; proper_morphism := lam2_deg1_proper |}
|}.
Next Obligation.
  intros [ [ [ s a ] b ] p ] [ [ [ s' a' ] b' ] p' ].
  cbv beta iota delta [lam2_eqT lam2_add lam2_deg1]; apply lam2_eq4; ring.
Qed.
Next Obligation.
  intros r [ [ [ s a ] b ] p ].
  cbv beta iota delta [lam2_eqT lam2_mul lam2_scal lam2_deg1]; simpl.
  apply lam2_eq4; ring.
Qed.

Program Definition lam2_deg1_alt : AltLinear Lam2_Mod Lam2_AAlg := {|
  alt_lin := lam2_deg1_lin
|}.
Next Obligation.
  intros [ [ [ s a ] b ] p ].
  cbv beta iota delta [lam2_eqT lam2_mul lam2_zero lam2_deg1]; simpl.
  apply lam2_eq4; ring.
Qed.

Definition ext_to_Lam2
  : @ExtAlg Int_CRng Lam2_Mod ~{AAlg Int_CRng}~> Lam2_AAlg :=
  ext_extend Lam2_AAlg lam2_deg1_alt.

Example ext_to_Lam2_gen (x : lam2) :
  rig_map (`1 ext_to_Lam2) (@tt_gen Int_CRng Lam2_Mod x) = lam2_deg1 x := eq_refl.

Example ext_to_Lam2_e1_e2 :
  rig_map (`1 ext_to_Lam2) (tt_mul (@tt_gen Int_CRng Lam2_Mod lam2_e1) (@tt_gen Int_CRng Lam2_Mod lam2_e2))
    = (0, 0, 0, 1)%Z := eq_refl.

Example ext_to_Lam2_e2_e1 :
  rig_map (`1 ext_to_Lam2) (tt_mul (@tt_gen Int_CRng Lam2_Mod lam2_e2) (@tt_gen Int_CRng Lam2_Mod lam2_e1))
    = (0, 0, 0, -1)%Z := eq_refl.

(* Λ(V) is not the trivial algebra. / Λ(V) 不是平凡代数。 *)
Theorem ext_nontrivial :
  et_eq (@tt_scal Int_CRng Lam2_Mod 1%Z) (@tt_scal Int_CRng Lam2_Mod 0%Z)
    → False.
Proof.
  intro H.
  pose proof (proper_morphism (rig_map (`1 ext_to_Lam2)) _ _ H) as H2.
  unfold lam2_eqT, lam2_scal in H2.
  inversion H2.
Qed.

(*
 A generator of Λ(V) is not a scalar — so the alternating relation does
 not force the generators into the base ring, and in particular
 v ∧ v ≈ 0 does not force v ≈ 0. 

 --------
 Λ(V) 的生成元不是标量——因此交替关系并不强制生成元落入基环，特别地，v ∧ v ≈ 0 并不强制 v ≈ 0。
*)
Theorem ext_gen_not_scalar (r : Z) :
  et_eq (@tt_gen Int_CRng Lam2_Mod lam2_e1) (@tt_scal Int_CRng Lam2_Mod r) → False.
Proof.
  intro H.
  pose proof (proper_morphism (rig_map (`1 ext_to_Lam2)) _ _ H) as H2.
  unfold lam2_eqT, lam2_deg1, lam2_e1, lam2_scal in H2.
  inversion H2.
Qed.

(*
 ANTISYMMETRY IS NOT VACUOUS: the two orders of a product of distinct
 generators are provably different elements of this Λ(V).  Together with
 [ext_anticomm] — which says the second is the negative of the first —
 this exhibits a Λ in which the anticommutation law has content, rather
 than one in which both sides happen to be zero. 

 --------
 反对称性并非空洞：不同生成元的乘积的两个顺序可以证明是 Λ(V) 中不同的元素。再加上 [ext_anticomm]——它说明第二个元素是第一个元素的相反数——这说明了一个 Λ，其中反交换律是有实际内容的，而不是双方巧合为零的情况。
*)
Theorem ext_anticomm_nontrivial :
  et_eq (tt_mul (@tt_gen Int_CRng Lam2_Mod lam2_e1) (@tt_gen Int_CRng Lam2_Mod lam2_e2))
        (tt_mul (@tt_gen Int_CRng Lam2_Mod lam2_e2) (@tt_gen Int_CRng Lam2_Mod lam2_e1)) → False.
Proof.
  intro H.
  pose proof (proper_morphism (rig_map (`1 ext_to_Lam2)) _ _ H) as H2.
  unfold lam2_eqT in H2.
  inversion H2.
Qed.

(* ...and the generators themselves are distinct, so the pair above is a genuine pair. / ...并且发电机本身是不同的，所以上面的这一对是真正的一对。 *)
Theorem ext_gens_distinct :
  et_eq (@tt_gen Int_CRng Lam2_Mod lam2_e1) (@tt_gen Int_CRng Lam2_Mod lam2_e2) → False.
Proof.
  intro H.
  pose proof (proper_morphism (rig_map (`1 ext_to_Lam2)) _ _ H) as H2.
