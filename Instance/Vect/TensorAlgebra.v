  - apply pequiv_from;
      rewrite (rig_map_one (aalg_unit A)); apply rig_mul_one_l.
  - apply pequiv_from;
      rewrite (rig_map_one (aalg_unit A)); apply rig_mul_one_r.
  - apply pequiv_from; exact (rig_distr_l AR _ _ _).
  - apply pequiv_from; exact (rig_distr_r AR _ _ _).
