(*
   * * The walking isomorphism, by generators and relations

   nLab: https://ncatlab.org/nlab/show/walking+isomorphism
   nLab: https://ncatlab.org/nlab/show/free+category
   Book: Awodey, Category Theory, 1st ed., §4.4 Example 4.9, printed
   p. 90 (the category generated by two objects A and B and two
   arrows f : A → B, g : B → A subject to g ∘ f = 1_A and
   f ∘ g = 1_B)

   Awodey's example is the smallest presentation whose relations do
   something a finite enumeration cannot see.  Two nodes, two edges,
   two equations — and the free category on that quiver is INFINITE:
   the paths A → A are the alternating words (gf)^n of every even
   length, and they are pairwise distinct.  The two relations collapse
   that infinity to a single arrow in each of the four hom-sets, so
   the presented category has exactly four arrows, two of them
   identities, and the surviving pair is an isomorphism.

   That is the whole point of the example, and it is what separates it
   from [Instance/Square.v]'s walking commutative square: there the
   free category is already finite (ten arrows) and one relation merges
   one pair, so a classification of paths can be a finite enumeration
   of Leibniz equalities.  Here it cannot be, and the classification
   below is by ENDPOINTS AND LENGTH instead — every path is [wi_AA n],
   [wi_AB n], [wi_BA n] or [wi_BB n] for a unique [n], according to its
   two endpoints.

   WHAT IS DELIVERED.  (1) the presentation [WalkingIsoPresentation]
   and the category [WalkingIso] ([FinitelyPresented] of it), with the
   quiver, the finiteness data and the two equations all carried as
   data in the shape [Construction/Free/Quiver/Presented.v] fixes;
   (2) [wi_classify], a classification of every PATH of the underlying
   free category by its endpoints and its length, at LEIBNIZ strength —
   each path IS one of the four canonical families on the nose, not
   merely [≈] to it; (3) the two relations, [wiso_gf] and [wiso_fg],
   and from them [walking_iso], an inhabitant of [Theory/Isomorphism.v]'s
   [Isomorphism] whose two inverse laws ARE those two relations;
   (4) [WalkingIso_Thin] — every hom-set is a singleton — together with
   [wiso_hom_singleton], which pairs thinness with an inhabitant of each
   of the four hom-sets, and [WalkingIso_IsGroupoid], so [WalkingIso] is
   the chaotic groupoid on two points; (5) the counts, proved and not
   asserted: two objects, four arrows, two of them identities, two
   generators; (6) that the presenting projection is not
   faithful, measured — the free hom-set A → A carries the pairwise
   distinct family [wi_AA n] ([free_wi_AA_inj]) while all of them
   collapse in [WalkingIso] ([wi_AA_collapse]), whence
   [WalkingIsoProj_not_faithful], so [WalkingIso] is not free on its own
   quiver; and [free_iso_lengths], the general fact that a free category
   has no non-identity isomorphism, which is where an argument for "free
   on NO quiver" would start and which this file does not finish;
   (7) the universal property: a functor out of [WalkingIso] is exactly
   an isomorphism in the target, with both round trips and uniqueness at
   strict strength.

   WHAT IS CONSUMED RATHER THAN REBUILT.  All of the presentation
   machinery: [FiniteQuiver], [FiniteEquations], [fe_rel],
   [FinitePresentation], [FinitelyPresented], [pgen],
   [PresentedQuiverProj], [PresentedFunctor], [PresentedFunctor_gen] and
   [PresentedFunctor_unique] are
   [Construction/Free/Quiver/Presented.v]'s, and no analogue of any of
   them is declared here.  [FreeOnQuiver],
   [Build_Quiver_Standard_Eq], [InducedFunctor], [QuiverOfCat] and the
   whole [tlist] path algebra ([tlist_app_cons],
   [tlist'_equiv_lengths]) are [Construction/Free/Quiver.v]'s and
   [Lib/TList.v]'s.  The congruence is
   [Construction/Quotient.v]'s [CongClosure]: [≈] in a presented
   category IS a term of that inductive family, which is why
   [wiso_gf] and [wiso_fg] are one [cc_gen] each, and why
   [strict_of_hom_cast] converts the uniqueness clause.  [Thin] is
   [Structure/Thin.v]'s and [IsGroupoid] is [Structure/Groupoid.v]'s;
   requiring the latter costs exactly one module over the closure
   without it (34 against 35, measured with [coqdep -sort] on this
   file's own [Require] list), because
   [Instance/Sets] and [Construction/Deloop] are already reached
   through [Presented.v].

   DESIGN DECISIONS.

   THE CLASSIFICATION IS AT LEIBNIZ STRENGTH, and that is a genuine
   strengthening rather than a stylistic one.  The edges of
   [WIsoQuiver] carry the standard [eq] setoid
   ([Build_Quiver_Standard_Eq]), so [wi_classify] can and does conclude
   a Leibniz equality of paths rather than a [tlist] equivalence.  It
   is what makes [free_wi_AA_inj] a statement about ARROWS of the free
   category rather than about representatives: length is an invariant
   of the hom-setoid ([wi_equiv_length]), so the classification's [=]
   upgrades to a statement about [≈]-classes.  Every claim about an
   arrow of [WalkingIso] is at [≈]; the Leibniz equations elsewhere in
   the file are about term structure — that a composite of one-step
   paths IS a two-step path, that the projection IS the identity on
   morphisms — and each is marked where it occurs.

   THE ISOMORPHISM IS BUILT DIRECTLY FROM THE TWO RELATIONS, not
   through [Structure/Thin.v]'s [thin_iso].  Both routes exist, but the
   direct one is the honest reading of Awodey's example: the two
   inverse laws of [walking_iso] are literally [wiso_fg] and
   [wiso_gf], which are literally the two imposed equations, so the
   isomorphism is the presentation and not a consequence of a later
   theorem.  [thin_iso WalkingIso_Thin iso_f iso_g] would inhabit the
   same type by a different route; that alternative is not built here,
   and no claim is made that the two agree.

   THE FOUR CANONICAL FAMILIES ARE TWO FIXPOINTS AND TWO ABBREVIATIONS.
   [wi_AA] and [wi_BB] recurse two edges at a time, so neither needs
   mutual recursion; [wi_AB] and [wi_BA] are one edge on top of the
   other family's [n]-th term.  That is what lets [wi_classify] be a
   single induction on the path with the target destructed in both
   branches — [Instance/Square.v]'s [wsq_classify] idiom, which is
   forced here for the same reason it is forced there.  Measured: on a
   path whose endpoints are given as CONSTRUCTORS, a direct
   [induction p] is refused with "Abstracting over the terms \"WI_A\"
   and \"p\" leads to a term ... which is ill-typed", since the
   eliminator would have to generalize the endpoint the statement
   names.  Routing the induction through [wi_spec], which matches on
   the target and takes the source as an argument, is what makes the
   abstraction well typed.

   TWO TRAPS THIS FILE MET, both recorded because the error message
   names neither cause.

   THE FIRST IS THAT THE TWO CATEGORIES SHARE THEIR HOM TYPES.
   [WalkingIso] and [FreeWIso] have the same hom TYPES (equations merge
   and never add — [WalkingIso_hom_is_free]) and the same [compose]
   ([WalkingIso_compose_is_free]), so a morphism term does not say
   which category it is being read in, while the [≈] of a goal does.
   In the successor case of [wi_AA_collapse] the goal displays as
   [wi_AA n ∘ wi_g ∘ wi_f ≈ id{WalkingIso}] — visibly an instance of
   [comp_assoc]'s right-hand side — and yet a bare
   [rewrite <- comp_assoc] is refused, the setoid relation to rewrite
   under being left as an unresolved evar; the same rewrite with the
   category given explicitly as [FreeWIso] is refused identically, with
   the same message, which is what shows the obstruction to be the
   RELATION and not the term.  Naming
   [WalkingIso] resolves it, so every appeal to associativity below
   names its category.

   THE SECOND IS THAT [simpl] UNFOLDS PAST THE PATTERN.  In
   [wi_AA_step] the generators are [tlist_singleton] applications, and
   after [simpl] a [rewrite <- wi_cons_g] reports "Found no subterm
   matching \"?M ∘ wi_g\"" — the composite it wants has been unfolded
   to its [tlist] normal form.  Both step lemmas are therefore supplied
   as TERMS, built from [eq_trans] and [f_equal] over [tlist_app_cons],
   with no tactic at all.

   WHAT IS NOT DELIVERED.  No decision procedure on the hom-sets: the
   classification is a proof by induction, and no [ObjDecEq] or
   hom-decidability instance is registered.  Nothing is registered as
   an [Instance] at all.  No comparison with any other in-tree shape:
   neither [Instance/Indiscrete.v]'s [Indiscrete bool] nor
   [Instance/Two.v]'s [_2] is related to [WalkingIso] here, no
   comparison functor is built, and nothing is claimed about whether
   any of them are isomorphic or equivalent.
   [WalkingIsoProj_not_faithful] says that THIS presentation's
   projection from THIS free category is not faithful; it does NOT say
   that [WalkingIso] is not the free category on some other quiver, and
   no such statement is proved or attempted.  The free category's
   infinitude is delivered as the injectivity of one family
   ([free_wi_AA_inj]) rather than as a cardinality statement, the tree
   carrying no vocabulary for the latter.  No vertex group is computed,
   no [Deloop] comparison is made, and nothing is said about
   [WalkingIso]'s skeleton. 

   --------
   * * 生成元与关系的行走同构

   nLab:  https://ncatlab.org/nlab/show/walking+isomorphism 
   nLab:  https://ncatlab.org/nlab/show/free+category 
   书籍: Awodey，《范畴论》，第一版，第4.4节 示例4.9，印刷页 90（由两个对象 A 和 B 以及两条箭头 f : A → B、g : B → A 生成的范畴，满足 g ∘ f = 1_A 和 f ∘ g = 1_B）Awodey 的例子是最小的展示，其关系所做的事情是有限枚举无法看到的。两个节点、两条边、两个方程——该四元图上的自由范畴是无限的：从 A 到 A 的路径是交替字 (gf)^n，长度为偶数，并且它们两两不同。两个关系将那无限性压缩到每个四个 Hom 集中的单个箭头，因此展示的范畴恰好有四个箭头，其中两个是恒等箭头，剩下的两者是同构。这正是这个例子的整个要点，也是它与[Instance/Square.v]的可交换方行走例子不同之处：那里自由范畴已经是有限的（十个箭头），而且一个关系合并了一对箭头，因此路径的分类可以通过列举莱布尼茨等式来完成。而在这里不可以，下面的分类改为根据端点和长度——每条路径都是[wi_AA n]、[wi_AB n]、[wi_BA n]或[wi_BB n]，对应唯一的[n]，根据它的两个端点。交付的内容是什么。(1) 呈现 [WalkingIsoPresentation] 以及范畴 [WalkingIso]（它的 [FinitelyPresented]），连同箭形、有限性数据和作为数据携带的两个方程在形状 [Construction/Free/Quiver/Presented.v] 中固定；(2) [wi_classify]，对底层自由范畴的每条路径按其端点和长度进行分类，在莱布尼茨强度下——每条路径正好属于四个典型族之一，而不仅仅是 [≈]；(3) 两个关系 [wiso_gf] 和 [wiso_fg]，以及由它们构成的 [walking_iso]，它是 [Theory/Isomorphism.v] 的 [Isomorphism] 的一个元素，其两个逆律正是这两个关系；(4) [WalkingIso_Thin]——每个同态集都是单元素——以及 [wiso_hom_singleton]，它将薄性与四个同态集中的每个元素配对，以及 [WalkingIso_IsGroupoid]，因此 [WalkingIso] 是一个具有两个点的混乱群体；(5)计数，已证明而非声称：两个对象，四个箭头，其中两个是恒等箭头，两个是生成元；(6) 给出的投影不是忠实的，经过测量——自由同态集 A → A 携带成对不同的族 [wi_AA n] ([free_wi_AA_inj])，而它们在 [WalkingIso] ([wi_AA_collapse]) 中全部塌缩，因此 [WalkingIsoProj_not_faithful]，所以 [WalkingIso] 不是在其自身的箭图上自由的；以及 [free_iso_lengths]，一个自由范畴没有非恒等同构的一般事实，这也是“在无箭图上自由”的论证会开始的地方，而该文件未完成此部分；(7) 泛性质：从 [WalkingIso] 出发的函子恰好是在目标中的一个同构，具有严格强度下的双向回路和唯一性。

   被消耗而不是重建的。所有的呈现机制：[FiniteQuiver]、[FiniteEquations]、[fe_rel]、[FinitePresentation]、[FinitelyPresented]、[pgen]、[PresentedQuiverProj]、[PresentedFunctor]、[PresentedFunctor_gen] 和 [PresentedFunctor_unique] 都是 [Construction/Free/Quiver/Presented.v] 的，并且这里没有声明它们的任何类似物。[FreeOnQuiver]、[Build_Quiver_Standard_Eq]、[InducedFunctor]、[QuiverOfCat] 以及整个 [tlist] 路径代数（[tlist_app_cons]、[tlist'_equiv_lengths]）都是 [Construction/Free/Quiver.v] 和 [Lib/TList.v] 的。同余是 [Construction/Quotient.v] 的 [CongClosure]：在一个呈现的范畴中，[≈] 是那个归纳家族的一个项，这就是为什么 [wiso_gf] 和 [wiso_fg] 各是一个 [cc_gen]，以及为什么 [strict_of_hom_cast] 转换唯一性条款。[Thin] 是 [Structure/Thin.v] 的，[IsGroupoid] 是 [Structure/Groupoid.v] 的；
   需要后者的成本正好比不包含它的闭包多一个模块（本文件自身的 [Require] 列表使用 [coqdep -sort] 测量为 34 对 35），因为 [Instance/Sets] 和 [Construction/Deloop] 已经通过 [Presented.v] 达到。

   设计决策。分类属于莱布尼茨强度，这是一个真正的加强，而不是风格上的。[WIsoQuiver] 的边带有标准的 [eq] 集合点（[Build_Quiver_Standard_Eq]），因此 [wi_classify] 可以并且确实得出路径的莱布尼茨等式而不是 [tlist] 等价。这使得 [free_wi_AA_inj] 成为关于自由范畴箭头的陈述，而不是关于代表元的：长度是同态集合点（[wi_equiv_length]）的不变量，因此分类的 [=] 升级为关于 [≈] 类的陈述。关于 [WalkingIso] 的每一个箭头的声明都在 [≈]；文件中其他地方的莱布尼茨方程关于项结构——即一步路径的组合就是两步路径，投影在态射上就是恒等——并且每个都标记了它出现的位置。

   同构是直接由这两个关系构建的，而不是通过 [Structure/Thin.v] 的 [thin_iso]。两条路径都存在，但直接的方法才是对 Awodey 示例的真实解读：[walking_iso] 的两个逆律实际上是 [wiso_fg] 和 [wiso_gf]，这正是强加的两个方程，因此同构是此呈现的结果，而不是后续定理的推论。[thin_iso WalkingIso_Thin iso_f iso_g] 也可以通过另一条路径属于相同类型；这种替代方法在此未构建，也未声明两者一致。四个典型的家族是两个不动点和两个缩写。[wi_AA] 和 [wi_BB] 每次递归两条边，因此都不需要互相递归；[wi_AB] 和 [wi_BA] 是另一家族 [n] 的第 n 项之上的一条边。正是这使得 [wi_classify] 可以在路径上进行单次归纳，并在两个分支中对目标进行析构——[Instance/Square.v] 的 [wsq_classify] 习语，在此处被强制使用的原因与在那里被强制使用的一样。测量：在端点作为构造器给出的路径上，直接 [induction p] 被拒绝，并显示“对术语 'WI_A' 和 'p' 进行抽象会导致一个类型错误的术语”，因为消去器必须对语句所命名的端点进行泛化。将归纳通过 [wi_spec] 路由，这个函数在目标上匹配并将源作为参数传入，这使得抽象类型正确。

   该文件遇到的两个陷阱，均被记录，因为错误信息未指明具体原因。首先是这两个类别共享它们的同态类型。[WalkingIso] 和 [FreeWIso] 拥有相同的同态类型（方程会合并而不会新增 — [WalkingIso_hom_is_free]）并且拥有相同的 [compose]（[WalkingIso_compose_is_free]），所以一个态射项并不能说明它是在读哪个类别，而一个目标的 [≈] 却可以。在 [wi_AA_collapse] 的继承情况下，目标显示为 [wi_AA n ∘ wi_g ∘ wi_f ≈ id{WalkingIso}] — 明显是 [comp_assoc] 右边的一个实例 — 然而一个裸露的 [rewrite <- comp_assoc] 被拒绝，将要在其下重写的集合等价关系被保留为未解决的 evar；在明确给出类别为 [FreeWIso] 的情况下，同样的重写也被同样地拒绝，显示相同的消息，这表明阻碍在于 RELATION 而不是项。命名
   [WalkingIso] 解决了它，因此下面每次对结合性的调用
   都命名了它的类别。

   第二点是 [simpl] 展开超过了模式。在
   [wi_AA_step] 中，生成元是 [tlist_singleton] 应用，并且在
   [simpl] 之后，[rewrite <- wi_cons_g] 报告“未找到匹配 '?M ∘ wi_g' 的子项”——它想要的复合项已被展开为它的 [tlist] 正规形式。因此，这两个步骤引理都是作为 TERMS 提供的，由 [eq_trans] 和 [f_equal] 在 [tlist_app_cons] 上构建，完全没有使用策略。未提供的内容。关于同态集没有决策程序：分类是通过归纳证明的，没有注册任何 [ObjDecEq] 或同态可判定实例。完全没有任何内容被注册为 [Instance]。与任何其他树内形状没有比较：既没有 [Instance/Indiscrete.v] 的 [Indiscrete bool]，也没有 [Instance/Two.v] 的 [_2] 与 [WalkingIso] 有关，没有构建比较函子，也没有任何声明关于它们是否同构或等价。[WalkingIsoProj_not_faithful] 说明此表示的投影从该自由范畴出发并不忠实；它并未说明 [WalkingIso] 不是某个其他箭图的自由范畴，也没有证明或尝试过此类陈述。自由范畴的无穷性表现为一个族（[free_wi_AA_inj]）的单射性，而不是作为基数声明，因为树没有后者的词汇。没有计算任何顶点群，也没有进行[Deloop]的比较，并且没有涉及[WalkingIso]的骨架。
*)

(* * ** The quiver Two nodes and two edges, one in each direction. Awodey draws them as f : A → B and g : B → A. / * ** 箭袋 两个节点和两条边，各一条，方向相反。Awodey 将它们画为 f : A → B 和 g : B → A。 *)

Inductive WIsoNode : Set := WI_A | WI_B.

Inductive WIsoEdge : WIsoNode -> WIsoNode -> Set :=
  | WI_f : WIsoEdge WI_A WI_B
  | WI_g : WIsoEdge WI_B WI_A.

Definition WIsoQuiver : Quiver :=
  Build_Quiver_Standard_Eq WIsoNode WIsoEdge.

(** The free category on it: paths are alternating words in f and g. / 上面的自由范畴：路径是 f 和 g 的交替词。 *)
Definition FreeWIso : Category := FreeOnQuiver WIsoQuiver.

(** The two generating edges, as one-step paths. / 两条生成边，作为一步路径。 *)
Definition wi_f : WI_A ~{FreeWIso}~> WI_B :=
  tlist_singleton (B:=@edges WIsoQuiver) WI_f.
Definition wi_g : WI_B ~{FreeWIso}~> WI_A :=
  tlist_singleton (B:=@edges WIsoQuiver) WI_g.

(*
   * ** The four canonical path families

   A path alternates, so it is determined by its two endpoints and its
   length.  [wi_AA n] and [wi_BB n] are the loops of length 2n; the two
   families of odd-length paths are one edge on top of them.  Only
   these two recurse, and each consumes two edges at a step, so no
   mutual recursion is needed. 

   --------
   * ** 四个典型路径族

   一条路径是交替的，因此它由它的两个端点及其长度决定。[wi_AA n] 和 [wi_BB n] 是长度为 2n 的环；奇数长度路径的两个族是在它们上面加一条边。这两种路径族是唯一递归的，每步消耗两条边，因此不需要相互递归。
*)

Fixpoint wi_AA (n : nat) : WI_A ~{FreeWIso}~> WI_A :=
  match n with
  | O => tnil
  | S m => tcons (B:=@edges WIsoQuiver) _ WI_f
             (tcons (B:=@edges WIsoQuiver) _ WI_g (wi_AA m))
  end.

Fixpoint wi_BB (n : nat) : WI_B ~{FreeWIso}~> WI_B :=
  match n with
  | O => tnil
  | S m => tcons (B:=@edges WIsoQuiver) _ WI_g
             (tcons (B:=@edges WIsoQuiver) _ WI_f (wi_BB m))
  end.

Definition wi_AB (n : nat) : WI_A ~{FreeWIso}~> WI_B :=
  tcons (B:=@edges WIsoQuiver) _ WI_f (wi_BB n).
Definition wi_BA (n : nat) : WI_B ~{FreeWIso}~> WI_A :=
  tcons (B:=@edges WIsoQuiver) _ WI_g (wi_AA n).

(*
   * The empty path is the length-zero loop, and each generator is the
   length-one path of its own family. 

   --------
   * 空路径是长度为零的环，而每个生成元是其自身族的长度为一的路径。
*)
Example wi_AA_0 : wi_AA 0 = @id FreeWIso WI_A := eq_refl.
Example wi_BB_0 : wi_BB 0 = @id FreeWIso WI_B := eq_refl.
Example wi_AB_0 : wi_AB 0 = wi_f := eq_refl.
Example wi_BA_0 : wi_BA 0 = wi_g := eq_refl.

(*
   * ** Classifying every path by its endpoints and its length

   The specification: for each ordered pair of nodes, exactly which
   paths join them.  Unlike [Instance/Square.v]'s [wsq_spec] this is
   not a finite enumeration — the hom-sets of [FreeWIso] are infinite —
   but each is still pinned down completely, by a natural number.  The
   equalities are Leibniz, not [≈]; see the header. 

   --------
   * ** 按端点和长度分类每条路径

   规范：对于每一对有序节点，明确哪些路径将它们连接。与 [Instance/Square.v] 的 [wsq_spec] 不同，这不是有限的枚举——[FreeWIso] 的同态集是无限的——但每一个仍然可以通过自然数完全确定。等式采用的是 Leibniz，而不是 [≈]；见标题。
*)
Definition wi_spec (y : WIsoNode) :
  forall x : WIsoNode, (x ~{FreeWIso}~> y) -> Type :=
  match y as y0 return forall x : WIsoNode, (x ~{FreeWIso}~> y0) -> Type
  with
  | WI_A => fun x => match x as x0
                      return (x0 ~{FreeWIso}~> WI_A) -> Type with
      | WI_A => fun p => { n : nat & p = wi_AA n }
      | WI_B => fun p => { n : nat & p = wi_BA n }
      end
  | WI_B => fun x => match x as x0
                      return (x0 ~{FreeWIso}~> WI_B) -> Type with
      | WI_A => fun p => { n : nat & p = wi_AB n }
      | WI_B => fun p => { n : nat & p = wi_BB n }
      end
  end.

(*
   * Every path meets its specification.  One induction on the path: the
   empty path forces source and target to agree and is the zeroth term
   of the appropriate family, and a step is one of the two edges, which
   pins the source and hands the rest to the induction hypothesis.  The
   two loop branches are the only ones that increment the index. 

   --------
   * 每条路径都符合其规范。对路径进行归纳：空路径强制源和目标一致，并且是适当族的第零项；而一步是两个边之一，它固定源并将剩余部分交给归纳假设。两个循环分支是唯一增加索引的分支。
*)
Theorem wi_classify (y x : WIsoNode) (p : x ~{FreeWIso}~> y) :
  wi_spec y x p.
Proof.
  induction p as [ | i j e p IH ].
  - destruct y; exists 0%nat; reflexivity.
  - destruct e; destruct y; simpl in *;
      destruct IH as [n Hn]; subst.
    + exists (S n); reflexivity.
    + exists n; reflexivity.
    + exists n; reflexivity.
    + exists (S n); reflexivity.
Qed.

(* * ** The presentation Two nodes, two edges, TWO relations — one at each loop. Finiteness is carried as data throughout, in the shape [Construction/Free/Quiver/Presented.v] fixes: [Fin.t] indices with retractions, no existence claim over lists, hence no choice principle anywhere. / * ** 演示文稿 两个节点，两个边，两种关系——每个循环一个。有限性 作为数据在整个过程中传递，呈现为 [Construction/Free/Quiver/Presented.v] 修正：[Fin.t] 使用缩回的索引，不对列表的存在性做出声明，因此任何地方都不存在选择原理。 *)

Definition WIsoEqn_count (x y : WIsoQuiver) : nat :=
  match x, y with
  | WI_A, WI_A => 1 | WI_B, WI_B => 1 | _, _ => 0
  end.

Definition WIsoEqn_lhs (x y : WIsoQuiver) :
  Fin.t (WIsoEqn_count x y) -> x ~{FreeWIso}~> y.
Proof.
  destruct x, y; simpl; intro i;
    solve [ exact (Fin.case0 _ i) | exact (wi_AA 1) | exact (wi_BB 1) ].
Defined.

Definition WIsoEqn_rhs (x y : WIsoQuiver) :
  Fin.t (WIsoEqn_count x y) -> x ~{FreeWIso}~> y.
Proof.
  destruct x, y; simpl; intro i;
    solve [ exact (Fin.case0 _ i) | exact (wi_AA 0) | exact (wi_BB 0) ].
Defined.

Definition WIsoEqns : FiniteEquations WIsoQuiver := {|
  fe_count := WIsoEqn_count;
  fe_lhs   := WIsoEqn_lhs;
  fe_rhs   := WIsoEqn_rhs
|}.

Definition WIso_node (i : Fin.t 2) : WIsoNode :=
  match i with Fin.F1 => WI_A | Fin.FS _ => WI_B end.

Definition WIso_index (x : WIsoNode) : Fin.t 2 :=
  match x with WI_A => Fin.F1 | WI_B => Fin.FS Fin.F1 end.

Lemma WIso_node_rt (x : WIsoNode) : WIso_node (WIso_index x) = x.
Proof. destruct x; reflexivity. Qed.

Definition WIso_ecount (x y : WIsoNode) : nat :=
  match x, y with
  | WI_A, WI_B => 1 | WI_B, WI_A => 1 | _, _ => 0
  end.

Definition WIso_edge (x y : WIsoNode) :
  Fin.t (WIso_ecount x y) -> WIsoEdge x y.
Proof.
  destruct x, y; simpl; intro i;
    solve [ exact (Fin.case0 _ i) | exact WI_f | exact WI_g ].
Defined.

Definition WIso_eindex (x y : WIsoNode) (e : WIsoEdge x y) :
  Fin.t (WIso_ecount x y) :=
  match e in WIsoEdge a b return Fin.t (WIso_ecount a b) with
  | WI_f => Fin.F1
  | WI_g => Fin.F1
  end.

Lemma WIso_edge_rt (x y : WIsoNode) (e : WIsoEdge x y) :
  WIso_edge x y (WIso_eindex x y e) = e.
Proof. destruct e; reflexivity. Qed.

Definition WIsoFinite : FiniteQuiver WIsoQuiver :=
  @Build_FiniteQuiver WIsoQuiver 2 WIso_node WIso_index WIso_node_rt
    WIso_ecount WIso_edge WIso_eindex WIso_edge_rt.

Definition WalkingIsoPresentation : FinitePresentation := {|
  fp_quiver := WIsoQuiver;
  fp_finite := WIsoFinite;
  fp_eqns   := WIsoEqns
|}.

(** The walking isomorphism. / 行走同构。 *)
Definition WalkingIso : Category :=
  FinitelyPresented WalkingIsoPresentation.

(*
   * ...which is the presented category of the quiver and the relation,
   definitionally. 

   --------
   * ……这就是箭袋及其关系的呈现类别，从定义上来说。
*)
Example WalkingIso_is_presented :
  WalkingIso = PresentedQuiver WIsoQuiver (fe_rel WIsoEqns) := eq_refl.

(*
   * The hom TYPES of [WalkingIso] are the free ones: equations merge,
   and never add.  This is what makes the trap in the header
   possible. 

   --------
   * [WalkingIso] 的同类类型是自由类型：方程式会合并，而不会相加。这就是使标题中的陷阱成为可能的原因。
*)
Example WalkingIso_hom_is_free (x y : WIsoNode) :
  (x ~{WalkingIso}~> y) = (x ~{FreeWIso}~> y) := eq_refl.

(** Composition is the free category's, on the nose. / 组合是自由范畴的，正中要害。 *)
Example WalkingIso_compose_is_free {x y z : WIsoNode}
  (p : y ~{FreeWIso}~> z) (q : x ~{FreeWIso}~> y) :
  @compose WalkingIso x y z p q = @compose FreeWIso x y z p q := eq_refl.

(* * ** The generators, and the two relations / * ** 生成元，以及两个关系 *)

Definition iso_f : WI_A ~{WalkingIso}~> WI_B :=
  @pgen WIsoQuiver (fe_rel WIsoEqns) _ _ WI_f.
Definition iso_g : WI_B ~{WalkingIso}~> WI_A :=
  @pgen WIsoQuiver (fe_rel WIsoEqns) _ _ WI_g.

(*
   * Each composite of one-step paths IS the corresponding two-step loop,
   definitionally — composition in [FreeOnQuiver] is [tlist]
   concatenation with the arguments flipped.  Recorded as a Leibniz
   equality because the two sides are the very same term after
   reduction. 

   --------
   * 每个一步路径的复合物本质上是对应的两步循环 — 在定义上，[FreeOnQuiver] 中的复合是将参数翻转后的 [tlist] 拼接。 记录为莱布尼茨等式，因为两边在化简后就是完全相同的项。
*)
Example free_gf_is_loop :
  @compose FreeWIso _ _ _ wi_g wi_f = wi_AA 1 := eq_refl.
Example free_fg_is_loop :
  @compose FreeWIso _ _ _ wi_f wi_g = wi_BB 1 := eq_refl.

(*
   * Awodey's two equations, holding in the presented category.  Each is
   a single [cc_gen] — the generating constructor of
   [Construction/Quotient.v]'s congruence closure — applied to the
   corresponding index of the finite equation data. 

   --------
   * Awodey 的两个方程，在所展示的范畴中成立。每个方程都是一个单一的 [cc_gen] —— [Construction/Quotient.v] 同余闭包的生成构造子 —— 应用于有限方程数据的相应索引。
*)
Lemma wiso_gf :
  @equiv _ (@homset WalkingIso WI_A WI_A)
    (@compose WalkingIso _ _ _ iso_g iso_f) (@id WalkingIso WI_A).
Proof. apply cc_gen. exists Fin.F1. split; reflexivity. Qed.

Lemma wiso_fg :
  @equiv _ (@homset WalkingIso WI_B WI_B)
    (@compose WalkingIso _ _ _ iso_f iso_g) (@id WalkingIso WI_B).
Proof. apply cc_gen. exists Fin.F1. split; reflexivity. Qed.

(*
   * ** The headline: f is an isomorphism

   The example's whole content.  The two inverse laws of the record are
   the two imposed equations verbatim; nothing is proved here that was
   not proved by writing the presentation down. 

   --------
   * ** 标题: f 是一个同构

   示例的全部内容。记录的两个逆律就是
   两个逐字强加的方程；这里没有证明任何通过书写表示法未能证明的内容。
*)
Definition walking_iso : @Isomorphism WalkingIso WI_A WI_B := {|
  to          := iso_f;
  from        := iso_g;
  iso_to_from := wiso_fg;
  iso_from_to := wiso_gf
|}.

Example walking_iso_to : to walking_iso = iso_f := eq_refl.
Example walking_iso_from : from walking_iso = iso_g := eq_refl.

(*
   * ** Collapsing the free hom-sets

   Every path is one of the four families, and every member of a family
   is equivalent in [WalkingIso] to the family's zeroth term.  That is
   what makes the presented category thin. 

   --------
   * ** 折叠自由同态集合

   每条路径属于四个族中的一个，并且一个族中的每个成员在 [WalkingIso] 中都与该族的零阶项等价。 这就是使所呈现的范畴变薄的原因。
*)

(*
   * Consing an edge onto a path IS composing with the corresponding
   generator, at Leibniz equality — [Lib/TList.v]'s [tlist_app_cons]
   read at this quiver. 

   --------
   * 将一个边添加到路径上就是与相应的生成子组合，在 Leibniz 等式下 —— 在这个箭图中读取的 [Lib/TList.v] 的 [tlist_app_cons]。
*)
Lemma wi_cons_f {y : WIsoNode} (t : WI_B ~{FreeWIso}~> y) :
  tcons (B:=@edges WIsoQuiver) _ WI_f t = @compose FreeWIso _ _ _ t wi_f.
Proof. exact (tlist_app_cons WI_f t). Qed.

Lemma wi_cons_g {y : WIsoNode} (t : WI_A ~{FreeWIso}~> y) :
  tcons (B:=@edges WIsoQuiver) _ WI_g t = @compose FreeWIso _ _ _ t wi_g.
Proof. exact (tlist_app_cons WI_g t). Qed.

(*
   * Hence each loop is its predecessor followed by the round trip.
   Supplied as a term rather than by tactics: [simpl] unfolds the
   generators past the pattern the rewrite is looking for. 

   --------
   * 因此，每个循环都是其前身后跟往返行程。
   作为一个术语提供，而不是通过策略：[simpl] 展开生成器，超出了重写所寻找的模式。
*)
Definition wi_AA_step (n : nat) :
  wi_AA (S n) = @compose FreeWIso _ _ _
                  (@compose FreeWIso _ _ _ (wi_AA n) wi_g) wi_f :=
  eq_trans (wi_cons_f (tcons (B:=@edges WIsoQuiver) _ WI_g (wi_AA n)))
           (f_equal (fun t => @compose FreeWIso _ _ _ t wi_f)
                    (wi_cons_g (wi_AA n))).

Definition wi_BB_step (n : nat) :
  wi_BB (S n) = @compose FreeWIso _ _ _
                  (@compose FreeWIso _ _ _ (wi_BB n) wi_f) wi_g :=
  eq_trans (wi_cons_g (tcons (B:=@edges WIsoQuiver) _ WI_f (wi_BB n)))
           (f_equal (fun t => @compose FreeWIso _ _ _ t wi_g)
                    (wi_cons_f (wi_BB n))).

(*
   * Every loop at A collapses to the identity.  The appeal to
   associativity names [WalkingIso] explicitly; see the header. 

   --------
   * 每个在A处的回路都收缩为单位元。对结合律的引用明确命名了 [WalkingIso]；参见标题。
*)
Lemma wi_AA_collapse (n : nat) :
  @equiv _ (@homset WalkingIso WI_A WI_A) (wi_AA n) (@id WalkingIso WI_A).
Proof.
  induction n as [ | n IH ]; [ reflexivity | ].
  rewrite wi_AA_step.
  rewrite <- (@comp_assoc WalkingIso _ _ _ _ (wi_AA n) wi_g wi_f).
  rewrite wiso_gf, id_right.
  exact IH.
Qed.

Lemma wi_BB_collapse (n : nat) :
  @equiv _ (@homset WalkingIso WI_B WI_B) (wi_BB n) (@id WalkingIso WI_B).
Proof.
  induction n as [ | n IH ]; [ reflexivity | ].
  rewrite wi_BB_step.
  rewrite <- (@comp_assoc WalkingIso _ _ _ _ (wi_BB n) wi_f wi_g).
  rewrite wiso_fg, id_right.
  exact IH.
Qed.

Lemma wi_AB_collapse (n : nat) :
  @equiv _ (@homset WalkingIso WI_A WI_B) (wi_AB n) iso_f.
Proof.
  unfold wi_AB; rewrite (wi_cons_f (wi_BB n)).
  change (@compose FreeWIso ?x ?y ?z ?a ?b)
    with (@compose WalkingIso x y z a b).
  rewrite wi_BB_collapse; apply id_left.
Qed.

Lemma wi_BA_collapse (n : nat) :
  @equiv _ (@homset WalkingIso WI_B WI_A) (wi_BA n) iso_g.
Proof.
  unfold wi_BA; rewrite (wi_cons_g (wi_AA n)).
  change (@compose FreeWIso ?x ?y ?z ?a ?b)
    with (@compose WalkingIso x y z a b).
  rewrite wi_AA_collapse; apply id_left.
Qed.

(* * ** Thinness: every hom-set of [WalkingIso] is a singleton / * ** 稀疏性：[WalkingIso] 的每个同态集都是单元集 *)

(*
   * Any two parallel arrows agree.  Each of the four cases classifies
   both arrows and collapses each to the same normal form. 

   --------
   * 任何两条平行箭头都一致。四种情况中的每一种都对箭头进行分类，并将每一条箭头归结为相同的规范形式。
*)
Theorem WalkingIso_Thin : Thin WalkingIso.
Proof.
  intros x y p q; destruct x, y;
    destruct (wi_classify _ _ p) as [m Hm];
    destruct (wi_classify _ _ q) as [n Hn]; subst.
  - transitivity (@id WalkingIso WI_A);
      [ apply wi_AA_collapse | symmetry; apply wi_AA_collapse ].
  - transitivity iso_f;
      [ apply wi_AB_collapse | symmetry; apply wi_AB_collapse ].
  - transitivity iso_g;
      [ apply wi_BA_collapse | symmetry; apply wi_BA_collapse ].
  - transitivity (@id WalkingIso WI_B);
      [ apply wi_BB_collapse | symmetry; apply wi_BB_collapse ].
Qed.

(** A chosen inhabitant of each of the four hom-sets. / 每个四个同态集中的一个被选定的元素。 *)
Definition wiso_arrow (x y : WIsoNode) : x ~{WalkingIso}~> y :=
  match x, y with
  | WI_A, WI_A => id
  | WI_A, WI_B => iso_f
  | WI_B, WI_A => iso_g
  | WI_B, WI_B => id
  end.

(*
   * "Singleton" in full: inhabited, and any two members agree.  Both
   halves are needed — thinness alone would be satisfied by an empty
   hom-set, and this is what makes the arrow count below a count of
   arrows and not an upper bound. 

   --------
   * “单例”完整含义：有元素，并且任意两个成员都一致。两个部分都是必要的——仅仅稀疏性可以通过空的同构集合来满足，而这正是使下文的箭头计数成为箭头的计数而不是上界的原因。
*)
Theorem wiso_hom_singleton (x y : WIsoNode) :
  ((x ~{WalkingIso}~> y) *
   (forall p q : x ~{WalkingIso}~> y, p ≈ q))%type.
Proof. exact (wiso_arrow x y, WalkingIso_Thin x y). Qed.

(*
   * Every endomorphism is the identity: there are no nontrivial loops
   downstairs, though there are infinitely many upstairs. 

   --------
   * 每个自同态都是恒等映射：底层没有非平凡的环路，虽然在上层有无限多个。
*)
Corollary wiso_endo_id {x : WalkingIso} (p : x ~> x) : p ≈ id.
Proof. exact (WalkingIso_Thin x x p id). Qed.

(*
   * [WalkingIso] is the chaotic groupoid on two points: every arrow is
   invertible.  The inverse is the opposing arrow, which exists because
   every hom-set is inhabited, and both inverse laws are thinness.  The
   record is built directly rather than through [Structure/Thin.v]'s
   [thin_iso], which produces an [Isomorphism] where [IsGroupoid] asks
   for an [IsIsomorphism]. 

   --------
   * [WalkingIso] 是两个点上的混乱群元：每个箭头都是可逆的。逆元是相对的箭头，它存在是因为每个同态集都有元素，而且两个逆元律是单一性的。这个记录是直接构建的，而不是通过 [Structure/Thin.v] 的 [thin_iso] 构建，它会生成一个 [Isomorphism]，其中 [IsGroupoid] 会要求一个 [IsIsomorphism]。
*)
Theorem WalkingIso_IsGroupoid : IsGroupoid WalkingIso.
Proof.
  intros x y f.
  unshelve eapply Build_IsIsomorphism.
  - exact (wiso_arrow y x).
  - apply WalkingIso_Thin.
  - apply WalkingIso_Thin.
Qed.

(*
   * ** The presenting projection is not faithful, measured

   The free category is infinite where the presented one is not.  The
   contrast is exhibited on the loops at A: they are pairwise distinct
   upstairs and all equal downstairs.  READ THE WORD CAREFULLY: what
   this section establishes is that THIS presentation's projection from
   THIS free category is not faithful, so [WalkingIso] is not free on
   ITS OWN quiver.  It does NOT establish that [WalkingIso] is free on
   no quiver at all; [free_iso_lengths] below is the general fact that
   would begin such an argument, and the isomorphism-invariance step it
   would still need is neither proved nor attempted. 

   --------
   * ** 所给的投射不是忠实的，被测量过的

   自由范畴是无限的，而所呈现的范畴不是。这个对比在 A 处的环上表现得很明显：在上层它们两两不同，而在下层它们都相等。请仔细阅读文字：本节所证明的是，该表示的投射从其自由范畴出发不是忠实的，因此 [WalkingIso] 并不是在其自身的概图上自由的。它并没有证明 [WalkingIso] 在任何概图上都是自由的；下面的 [free_iso_lengths] 是那个可能开始此类论证的一般性事实，而其同构不变性步骤尚未被证明或尝试。
*)

(*
   * Equivalent paths of the free category have equal length —
   [tlist'_equiv_lengths] ([Construction/Free/Quiver.v]) at this
   quiver. 

   --------
   * 自由范畴的等价路径具有相等的长度——
   在这个向矢图中，[tlist'_equiv_lengths]（[Construction/Free/Quiver.v]）。
*)
Lemma wi_equiv_length {x y : WIsoNode} (p q : x ~{FreeWIso}~> y) :
  p ≈ q -> tlist_length p = tlist_length q.
Proof. intro H; exact (tlist'_equiv_lengths _ _ _ _ _ _ _ H). Qed.

(*
 A FREE CATEGORY HAS NO NON-IDENTITY ISOMORPHISM: both legs of one have
 length zero, because length is additive under concatenation and
 invariant under the hom-setoid.  Stated for an ARBITRARY quiver -- it
 mentions nothing of this file -- so it is an upstreaming candidate for
 [Construction/Free/Quiver.v].  Note the composition orientation:
 [g ∘ f] in [FreeOnQuiver] is [f +++ g], so the [change] is what lets
 [tlist_app_length] fire. 

 --------
 一个自由范畴没有非恒等同构：其中一条路径的两条支腿长度为零，因为长度在连接下是可加的，并且在同态集合下是不变的。对于一个任意的箭图来说——它并没有提到这个文件——因此它是 [Construction/Free/Quiver.v] 的一个上游候选。注意组合的方向：[g ∘ f] 在 [FreeOnQuiver] 中是 [f +++ g]，因此 [change] 是让 [tlist_app_length] 触发的东西。
*)
Lemma free_iso_lengths {Q : Quiver} {x y : Q}
  (f : x ~{FreeOnQuiver Q}~> y) (g : y ~{FreeOnQuiver Q}~> x)
  (H : @equiv _ (@homset (FreeOnQuiver Q) x x)
         (@compose (FreeOnQuiver Q) x y x g f) (@id (FreeOnQuiver Q) x)) :
  (tlist_length f = 0)%nat /\ (tlist_length g = 0)%nat.
Proof.
  pose proof (tlist'_equiv_lengths _ _ _ _ _ _ _ H) as HL.
  change (@compose (FreeOnQuiver Q) x y x g f) with (f +++ g) in HL.
  rewrite tlist_app_length in HL. simpl in HL. split; lia.
Qed.

Lemma wi_AA_length (n : nat) : tlist_length (wi_AA n) = (n + n)%nat.
Proof.
  induction n as [ | n IH ]; [ reflexivity | ].
  simpl; rewrite PeanoNat.Nat.add_succ_r; do 2 f_equal; exact IH.
Qed.

Lemma wi_BB_length (n : nat) : tlist_length (wi_BB n) = (n + n)%nat.
Proof.
  induction n as [ | n IH ]; [ reflexivity | ].
  simpl; rewrite PeanoNat.Nat.add_succ_r; do 2 f_equal; exact IH.
Qed.

Lemma wi_double_inj (m n : nat) : (m + m)%nat = (n + n)%nat -> m = n.
Proof.
  revert n; induction m as [ | m IH ]; intros [ | n ] H; simpl in H;
    try discriminate; try reflexivity.
  f_equal; apply IH.
  injection H as H.
  rewrite !PeanoNat.Nat.add_succ_r in H.
  now injection H.
Qed.

(*
   * The loops at A are pairwise distinct AS ARROWS of the free category
   — the statement is about [≈]-classes, not about representatives, so
   it survives the hom-setoid.  Hence [wi_AA] injects the naturals into
   that one hom-set. 

   --------
   * A 处的环路是自由范畴中两两不同的箭头 — 该陈述关于的是  [≈] 类，而不是代表元，因此它在同态集上仍然成立。因此  [wi_AA] 将自然数注入到那个同态集中。
*)
Theorem free_wi_AA_inj (m n : nat) :
  @equiv _ (@homset FreeWIso WI_A WI_A) (wi_AA m) (wi_AA n) -> m = n.
Proof.
  intro H.
  apply wi_double_inj.
  rewrite <- (wi_AA_length m), <- (wi_AA_length n).
  exact (wi_equiv_length _ _ H).
Qed.

Corollary free_wi_AA_distinct (m n : nat) (Hmn : m <> n) :
  @equiv _ (@homset FreeWIso WI_A WI_A) (wi_AA m) (wi_AA n) -> False.
Proof. intro H; exact (Hmn (free_wi_AA_inj m n H)). Qed.

(*
   * The presenting projection.  It is the identity on objects and on
   morphisms; only the hom-setoid coarsens. 

   --------
   * 呈现投影。它在对象和态射上都是恒等映射；只有态射集等价关系被简化。
*)
Definition WalkingIsoProj : FreeWIso ⟶ WalkingIso :=
  @PresentedQuiverProj WIsoQuiver (fe_rel WIsoEqns).

Example WalkingIsoProj_hom {x y : WIsoNode} (p : x ~{FreeWIso}~> y) :
  fmap[WalkingIsoProj] p = p := eq_refl.

(*
   * The two sides of the contrast at one concrete pair: the round trip
   (gf) and the empty path are distinct arrows of [FreeWIso] and the
   same arrow of [WalkingIso]. 

   --------
   * 在一个具体对比中，两边：往返（gf）和空路径是  [FreeWIso] 的不同箭头，而是 [WalkingIso] 的相同箭头。
*)
Theorem walking_iso_merges_the_loops :
  ((@equiv _ (@homset FreeWIso WI_A WI_A) (wi_AA 1) (wi_AA 0) -> False) *
   (@equiv _ (@homset WalkingIso WI_A WI_A) (wi_AA 1) (wi_AA 0)))%type.
Proof.
  split.
  - apply free_wi_AA_distinct; discriminate.
  - exact (wi_AA_collapse 1).
Qed.

(*
   * So the projection is not faithful.  Read this at exactly its
   strength: it says that THIS free category maps onto [WalkingIso]
   non-injectively on hom-sets, which is what "the relations do
   something" means.  It does NOT say that [WalkingIso] is not free on
   some other quiver, and no such claim is made anywhere in this
   file. 

   --------
   * 因此这个投影不是忠实的。准确理解这一点：它表示这个自由范畴在同态集上的映射到 [WalkingIso] 不是单射的，这就是“关系起作用”的意思。它并没有说 [WalkingIso] 不是在某个其他 quiver 上的自由范畴，并且在这个文件中没有做出这样的声明。
*)
Theorem WalkingIsoProj_not_faithful : Faithful WalkingIsoProj -> False.
Proof.
  intro HF.
  apply (free_wi_AA_distinct 1 0); [ discriminate | ].
  apply (@fmap_inj _ _ _ HF WI_A WI_A (wi_AA 1) (wi_AA 0)).
  exact (wi_AA_collapse 1).
Qed.

(*
   * ** The counts

   Two objects and four arrows, both proved.  [WalkingIso] is thin and
   every hom-set is inhabited ([wiso_hom_singleton]), so an arrow is
   determined by its endpoints and counting arrows is counting the
   ordered pairs of nodes. 

   --------
   * ** 计数

   两个对象和四个箭头，都已证明。[WalkingIso] 是薄的，并且每个同态集都是有元素的（[wiso_hom_singleton]），因此一个箭头由其端点决定，计数箭头就是计数节点的有序对。
*)

Definition wi_nodes : list WIsoNode := WI_A :: WI_B :: nil.

Lemma wi_nodes_complete (x : WIsoNode) : In x wi_nodes.
Proof. destruct x; simpl; auto. Qed.

Lemma wi_nodes_nodup : NoDup wi_nodes.
Proof. repeat constructor; simpl; intuition congruence. Qed.

(** Two objects. / 两个物体。 *)
Theorem wiso_object_total : length wi_nodes = 2%nat.
Proof. reflexivity. Qed.

Definition wi_all_pairs : list (WIsoNode * WIsoNode) :=
  list_prod wi_nodes wi_nodes.

Example wi_all_pairs_4 : length wi_all_pairs = 4%nat := eq_refl.

Lemma wi_all_pairs_complete (x y : WIsoNode) : In (x, y) wi_all_pairs.
Proof. apply in_prod; apply wi_nodes_complete. Qed.

(*
   * Every hom-set has exactly one arrow — the constant is what
   [wiso_hom_singleton] licenses, and nothing else in this section
   depends on which pair is being counted. 

   --------
   * 每个同态集恰好有一个箭头——常数是 [wiso_hom_singleton] 授权的，本节中没有其他内容依赖于正在计算的哪一对。
*)
Definition wiso_homcount (x y : WIsoNode) : nat := 1%nat.

Definition wiso_arrow_total : nat :=
  fold_right (fun q n => wiso_homcount (fst q) (snd q) + n)%nat 0%nat
    wi_all_pairs.

(** Four arrows. / 四支箭。 *)
Theorem wiso_arrow_total_4 : wiso_arrow_total = 4%nat.
Proof. reflexivity. Qed.

Definition wiso_identity_total : nat :=
  fold_right (fun x n => wiso_homcount x x + n)%nat 0%nat wi_nodes.

(** ...two of them identities. / ...其中两个身份。 *)
Theorem wiso_identity_total_2 : wiso_identity_total = 2%nat.
Proof. reflexivity. Qed.

Definition wiso_nonidentity_total : nat :=
  (wiso_arrow_total - wiso_identity_total)%nat.

(** ...and two of them not: [iso_f] and [iso_g]. / …其中有两个不是：[iso_f] 和 [iso_g]。 *)
Theorem wiso_nonidentity_total_2 : wiso_nonidentity_total = 2%nat.
Proof. reflexivity. Qed.

(*
   * The two non-identity arrows are not identities, because their
   endpoints differ. 

   --------
   * 这两个非恒等箭头不是恒等箭头，因为它们的端点不同。
*)
Lemma wiso_nonidentity_endpoints : WI_A <> WI_B.
Proof. discriminate. Qed.

(*
   * Neither of the two arrows is a composite of others: the quiver has
   exactly two edges, computed from the [FiniteQuiver] data rather than
   asserted, and the presented category has exactly two non-identity
   arrows. 

   --------
   * 这两个箭头都不是其他箭头的组合：箭袋恰好有两个边，是根据 [FiniteQuiver] 数据计算出来的，而不是断言的，并且所呈现的范畴恰好有两个非恒等箭头。
*)
Definition wiso_generator_total : nat :=
  fold_right
    (fun q n => fq_edges WIsoQuiver WIsoFinite (fst q) (snd q) + n)%nat
    0%nat wi_all_pairs.

Theorem wiso_generator_total_2 : wiso_generator_total = 2%nat.
Proof. reflexivity. Qed.

(*
   * ** The universal property: a functor out of [WalkingIso] is an
   isomorphism

   This is what the word "walking" means, and it is the converse
   direction that makes the presentation worth having. 

   --------
   * ** 通用性质：从 [WalkingIso] 出来的函子是一个同构

   这就是“walking”这个词的意思，而正是相反的方向使得该表示值得拥有。
*)

Section IndexShape.

Context {C : Category}.

Definition wiso_node {a b : C} (i : a ≅ b) (n : WIsoNode) : C :=
  match n with WI_A => a | WI_B => b end.

Definition wiso_edgemap {a b : C} (i : a ≅ b) (x y : WIsoNode)
  (e : WIsoEdge x y) : wiso_node i x ~> wiso_node i y :=
  match e in WIsoEdge u v return wiso_node i u ~> wiso_node i v with
  | WI_f => to i
  | WI_g => from i
  end.

Definition wiso_quiver_hom {a b : C} (i : a ≅ b) :
  QuiverHomomorphism WIsoQuiver (QuiverOfCat C).
Proof.
  unshelve eapply Build_QuiverHomomorphism.
  - exact (wiso_node i).
  - exact (wiso_edgemap i).
  - intros x y u v Huv; simpl in Huv; subst; reflexivity.
Defined.

(*
   * The two imposed relations are merged: they are exactly the two
   inverse laws, modulo the trailing identity a [tlist] fold leaves
   behind. 

   --------
   * 这两个强加的关系被合并：它们正好是两个逆定律，只是在尾随的恒等式 a  [tlist]  折叠后留下。
*)
Lemma wiso_quiver_hom_merges {a b : C} (i : a ≅ b) :
  forall x y (p q : x ~{FreeWIso}~> y), fe_rel WIsoEqns x y p q ->
    fmap[@InducedFunctor WIsoQuiver C (wiso_quiver_hom i)] p
      ≈ fmap[@InducedFunctor WIsoQuiver C (wiso_quiver_hom i)] q.
Proof.
  intros x y p q [k [Hp Hq]].
  destruct x, y; simpl in k; try solve [ exact (Fin.case0 _ k) ];
    simpl in Hp, Hq; rewrite Hp, Hq; simpl; rewrite !id_left.
  - exact (iso_from_to i).
  - exact (iso_to_from i).
Qed.

(** The functor an isomorphism names. / 函子是同构的名称。 *)
Definition WalkingIsoFunctor {a b : C} (i : a ≅ b) : WalkingIso ⟶ C :=
  @PresentedFunctor WIsoQuiver (fe_rel WIsoEqns) C
    (wiso_quiver_hom i) (wiso_quiver_hom_merges i).

Example WalkingIsoFunctor_A {a b : C} (i : a ≅ b) :
  fobj[WalkingIsoFunctor i] WI_A = a := eq_refl.
Example WalkingIsoFunctor_B {a b : C} (i : a ≅ b) :
  fobj[WalkingIsoFunctor i] WI_B = b := eq_refl.

Lemma WalkingIsoFunctor_f {a b : C} (i : a ≅ b) :
  fmap[WalkingIsoFunctor i] iso_f ≈ to i.
Proof.
  exact (@PresentedFunctor_gen WIsoQuiver (fe_rel WIsoEqns) C
           (wiso_quiver_hom i) (wiso_quiver_hom_merges i) _ _ WI_f).
Qed.

Lemma WalkingIsoFunctor_g {a b : C} (i : a ≅ b) :
  fmap[WalkingIsoFunctor i] iso_g ≈ from i.
Proof.
  exact (@PresentedFunctor_gen WIsoQuiver (fe_rel WIsoEqns) C
           (wiso_quiver_hom i) (wiso_quiver_hom_merges i) _ _ WI_g).
Qed.

(*
   * The converse: a functor out of [WalkingIso] carries the two
   generators to an inverse pair, the two laws coming from [wiso_fg]
   and [wiso_gf] under [fmap_respects]. 

   --------
   * 相反情况：从 [WalkingIso] 出发的函子将两个生成元分别映射为逆元对，这两个律来自 [wiso_fg] 和 [wiso_gf]，通过 [fmap_respects]。
*)
Lemma functor_iso_to_from (F : WalkingIso ⟶ C) :
  fmap[F] iso_f ∘ fmap[F] iso_g ≈ id.
Proof.
  rewrite <- fmap_comp.
  rewrite (@fmap_respects _ _ F _ _ _ _ wiso_fg).
  apply fmap_id.
Qed.

Lemma functor_iso_from_to (F : WalkingIso ⟶ C) :
  fmap[F] iso_g ∘ fmap[F] iso_f ≈ id.
Proof.
  rewrite <- fmap_comp.
  rewrite (@fmap_respects _ _ F _ _ _ _ wiso_gf).
  apply fmap_id.
Qed.

Definition IsoOfFunctor (F : WalkingIso ⟶ C) :
  fobj[F] WI_A ≅ fobj[F] WI_B := {|
  to          := fmap[F] iso_f;
  from        := fmap[F] iso_g;
  iso_to_from := functor_iso_to_from F;
  iso_from_to := functor_iso_from_to F
|}.

(*
   * Round trip one, on the isomorphism side: the objects come back on
   the nose and the two morphisms up to [≈]. 

   --------
   * 往返一次，在同构的一边：对象准确返回，并且两个态射到 [≈] 为止。
*)
Example wiso_round_obj_a {a b : C} (i : a ≅ b) :
  fobj[WalkingIsoFunctor i] WI_A = a := eq_refl.
Example wiso_round_obj_b {a b : C} (i : a ≅ b) :
  fobj[WalkingIsoFunctor i] WI_B = b := eq_refl.

Theorem wiso_round_morphisms {a b : C} (i : a ≅ b) :
  ((to (IsoOfFunctor (WalkingIsoFunctor i)) ≈ to i) *
   (from (IsoOfFunctor (WalkingIsoFunctor i)) ≈ from i))%type.
Proof. exact (WalkingIsoFunctor_f i, WalkingIsoFunctor_g i). Qed.

(*
   * Round trip two, on the functor side, at STRICT strength — Leibniz on
   objects and a [hom_cast] conjugation on morphisms, which is
   [StrictCat]'s functor equality ([Functor_StrictEq_Setoid], via
   [strict_of_hom_cast]).  As in [Instance/Square.v], the object
   agreement is [eq_refl] at each node but not uniformly in a variable
   node, since [wiso_node] is a match; that is a statement about
   reduction, not a weakening. 

   --------
   * 双程旅行二，在函子一侧，以严格强度 —— 莱布尼茨在对象上，以及在态射上的 [hom_cast] 共轭，这就是 [StrictCat] 的函子等式（[Functor_StrictEq_Setoid]，通过 [strict_of_hom_cast]）。如在 [Instance/Square.v] 中，每个节点上的对象一致性为 [eq_refl]，但在可变节点中并不统一，因为 [wiso_node] 是匹配的；这是关于约化的陈述，而不是关于弱化的。
*)
Definition wiso_round_obj (F : WalkingIso ⟶ C) (x : WIsoNode) :
  fobj[F] x = wiso_node (IsoOfFunctor F) x :=
  match x with WI_A => eq_refl | WI_B => eq_refl end.

Theorem wiso_functor_round (F : WalkingIso ⟶ C) :
  forall (x y : WIsoNode) (p : x ~{WalkingIso}~> y),
    hom_cast (wiso_round_obj F x) (wiso_round_obj F y) (fmap[F] p)
      ≈ fmap[WalkingIsoFunctor (IsoOfFunctor F)] p.
Proof.
  apply (@PresentedFunctor_unique WIsoQuiver (fe_rel WIsoEqns) C
           (wiso_quiver_hom (IsoOfFunctor F))
           (wiso_quiver_hom_merges (IsoOfFunctor F))
           F (wiso_round_obj F)).
  intros x y e; destruct e; reflexivity.
Qed.

Theorem wiso_functor_round_strict (F : WalkingIso ⟶ C) :
  @equiv _ (@Functor_StrictEq_Setoid WalkingIso C)
    F (WalkingIsoFunctor (IsoOfFunctor F)).
Proof.
  apply (strict_of_hom_cast F (WalkingIsoFunctor (IsoOfFunctor F))
           (wiso_round_obj F)).
  exact (wiso_functor_round F).
Qed.

(*
   * The universal property, bundled: to give a functor out of
   [WalkingIso] is exactly to give an isomorphism, and the functor is
   unique at strict strength. 

   --------
   * 通用性质，打包：从 [WalkingIso] 给出一个函子，恰好是给出一个同构，并且该函子在严格强度下是唯一的。
*)
Theorem walking_iso_universal {a b : C} (i : a ≅ b) :
  { F : WalkingIso ⟶ C &
  { Hobj : forall x : WIsoNode, fobj[F] x = wiso_node i x &
    (((hom_cast (Hobj WI_A) (Hobj WI_B) (fmap[F] iso_f) ≈ to i) *
      (hom_cast (Hobj WI_B) (Hobj WI_A) (fmap[F] iso_g) ≈ from i)) *
     (forall (K : WalkingIso ⟶ C)
        (Hobj' : forall x : WIsoNode, fobj[K] x = wiso_node i x),
        (forall (x y : WIsoNode) (e : WIsoEdge x y),
           hom_cast (Hobj' x) (Hobj' y)
             (fmap[K] (@pgen WIsoQuiver (fe_rel WIsoEqns) x y e))
             ≈ wiso_edgemap i x y e) ->
        forall (x y : WIsoNode) (p : x ~{WalkingIso}~> y),
          hom_cast (Hobj' x) (Hobj' y) (fmap[K] p)
            ≈ hom_cast (Hobj x) (Hobj y) (fmap[F] p)))%type } }.
Proof.
  exists (WalkingIsoFunctor i), (fun _ => eq_refl).
  split; [ split | ].
  - exact (WalkingIsoFunctor_f i).
  - exact (WalkingIsoFunctor_g i).
  - intros K Hobj' Hgen x y p.
    exact (@PresentedFunctor_unique WIsoQuiver (fe_rel WIsoEqns) C
             (wiso_quiver_hom i) (wiso_quiver_hom_merges i)
             K Hobj' Hgen x y p).
Qed.

End IndexShape.
