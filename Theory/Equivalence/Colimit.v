这里有两个语句，它们是不同的语句——文件故意将它们分开。

(1) 传输。自然同构的图形具有相同的余极限，并且拥有相同的顶点：[isacolimit_transport] 和 [colimit_transport]，它们是 Theory/Equivalence/Limit.v 中的 [isalimit_transport] 和 [limit_transport] 的完全对偶。假设是同构，结论固定了顶点。

(2) 引导映射。一个自然变换 α : G ⟹ G'，即使不假设其可逆，仍然会在 G 和 G' 的极限都存在时引入一个它们之间的比较 —— [limit_induced] —— 并且对偶地在余极限之间引入比较 —— [colimit_induced]。这在假设上较弱（没有可逆性），而在一般性上较强（两个顶点可能不同，且除非提供，否则不假定其存在）；它不要求环境范畴具有所有 J 形（协）极限，只需要提供的两个。

陈述 (2) 包含了 (1) 的存在性部分，但不包括其顶点固定：[limit_induced_of_transport] 显示，由一个同构 e 的前向分量诱导的比较，在一个极限及其沿 e 自身的传输之间，等于恒等映射——这正是 (1) 所增加而 (2) 不能说明的内容，(2) 的两个顶点彼此无关。这里没有任何地方声称 (2) 蕴含 (1)。

承重部件在下文 (A) 中，它是具有超出此文件的重用价值的部分。[Colimit F] 被定义为 [Limit (F^op)]（Structure/Limit.v），而 [IsAColimit F c] 被定义为 [IsALimit (F^op) c]（Structure/Limit/Preservation.v），因此对任何极限-传输结果进行双重化都需要在对立化过程中携带函子等价：G ≈ G' ⟹ G^op ≈ G'^op。即 [Opposite_Functor_respects]，其伴随 [Opposite_Functor_Proper] 用于注册以进行重写。

现有技术，以及对本文件所依据前提的更正。声称在树的任何地方都不存在这样的引理是错误的，如所述。Instance/Cat/Opposite.v 使用 [fobj := Opposite] 和 [fmap := Opposite_Functor] 构建 [Op : Cat ⟶ Cat]；由于 Cat 的同态集合是 [Functor_Setoid]（Instance/Cat.v），该函子在 [fmap_respects] 上的义务——常量 [Op_obligation_1]——正好包含 [Opposite_Functor_respects] 的内容，并且基本上具有相同的证明（该文件的头部解释了 2-态的反转及其可逆性如何控制它）。

所以 (A) 是一个更严格的、更通用的、透明的重新表述——而不是首次出现，这个标题也没有把它呈现为首次出现。

为什么源代码搜索找不到这个事实，这是更尖锐的教训：字符串 [Op_obligation_1] 在 Instance/Cat/Opposite.v 中出现次数为零，字符串 [Proper] 也是如此。NAME 和 TYPE 都是由 [Program] 从 [Next Obligation] 块生成的。无论是通过名称还是语句关键字在源代码中进行 grep，都无法找到它；只能在已编译的模块上通过 [Print Module] 或 [About] 才能找到。

偏好独立引理的两个自然解释都是错误的，而且测量结果也表明如此。这不是依赖成本：Instance/Cat 已经在该文件的模块闭包中（32 个模块），通过 Theory/Equivalence.v 被引入，而添加 Instance/Cat/Opposite.v 将只额外增加 2 个模块，而不是增加堆栈。而且这也不是因为 [Op] 将其参数固定在 Cat 自身的 universe：[Cat] 是 universe 多态的，因此 [@fmap_respects Cat Cat Op J C G G' e : G^op ≈ G'^op] 可以在两个任意范畴上进行类型检查。

存留下来的两个原因各自都与一个对照进行比较：

- 不透明性。[Op_obligation_1] 与 [Qed] 闭合，因此所产生的等价性没有任何减少。测量：读取回传 [`1 (Opposite_Functor_respects e) x = Isomorphism_Opposite (`1 e x)] 由 [eq_refl] 保持，而通过 [fmap_respects Op] 的同一读取回传被拒绝。下面（B）节中的每个 [eq_refl] 示例都依赖于此。- 宇宙。[Op] 路由强制两个范畴的 OBJECT 宇宙重合：它在 [J C : Category@{u2 u3 u3}] 处展开——为两者使用同一个对象层次——而 [Opposite_Functor_respects] 在 [J : Category@{u2 u4 u4}]、[C : Category@{u3 u4 u4}] 处展开，保持它们分开。在声明 [jo < co] 的部分下测量：独立引理在那里展开，[Op] 路由被拒绝。（[Cat] 自身的声明也带来了独立引理没有的严格不等式。）

