   Two statements live here, and they are DIFFERENT statements — the
   file keeps them apart on purpose.

   (1) TRANSPORT.  Naturally isomorphic diagrams have the same colimits,
       with the same apex: [isacolimit_transport] and [colimit_transport],
       the exact duals of Theory/Equivalence/Limit.v's
       [isalimit_transport] and [limit_transport].  The
       hypothesis is an isomorphism, and the conclusion pins the apex.

   (2) THE INDUCED MAP.  A natural transformation α : G ⟹ G' that is NOT
       assumed invertible still induces a comparison between the limits
       of G and G' whenever both limits exist — [limit_induced] — and
       dually between the colimits — [colimit_induced].  This is weaker
       in hypotheses (no invertibility) and stronger in generality (the
       two apexes may differ, and neither is assumed to exist unless it
       is supplied); it does NOT require the ambient category to have all
       J-shaped (co)limits, only the two that are handed in.

   Statement (2) subsumes the EXISTENCE half of (1) but not its
   apex-pinning: [limit_induced_of_transport] shows that the comparison
   induced by the forward components of an isomorphism e, read between a
   limit and its own transport along e, is the IDENTITY — which is
   exactly the content that (1) adds and (2) cannot state, (2)'s two
   apexes being unrelated.  Nothing here claims (2) implies (1).

   THE LOAD-BEARING PIECE IS (A) BELOW, and it is the part with reuse
   value beyond this file.  [Colimit F] is DEFINED as [Limit (F^op)]
   (Structure/Limit.v) and [IsAColimit F c] as [IsALimit (F^op) c]
   (Structure/Limit/Preservation.v), so dualizing ANY limit-transport
   result requires carrying a functor equivalence across oppositization:
   G ≈ G' ⟹ G^op ≈ G'^op.  That is [Opposite_Functor_respects], with the
   companion [Opposite_Functor_Proper] registering it for rewriting.

